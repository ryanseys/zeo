//! Single-byte encodings beyond Latin-1: per-byte Unicode mapping tables.
//!
//! GENERATED from the ruby 4.0.6 oracle (see the script in the commit that
//! added this file): for every byte 0x80..=0xFF, the Unicode scalar CRuby's
//! own converter produces, or `None` where CRuby raises
//! `Encoding::UndefinedConversionError`. Deliberately NOT the WHATWG
//! (encoding_rs) tables -- those fill several undefined vendor-page slots
//! with C1 controls (windows-1252 `0x81` -> U+0081) where CRuby refuses the
//! conversion, and this table IS the compatibility contract. Every byte is
//! still a valid CHARACTER in its encoding (`valid_encoding?` is true and
//! `length` counts it) -- `None` only refuses transcoding OUT.
//!
//! The low half (0x00..=0x7F) is ASCII in every one of these encodings and
//! is not tabulated.

/// One single-byte encoding's mapping surface.
pub struct SingleByteTable {
    /// Whether CRuby case-maps this encoding through full Unicode case
    /// mapping (the windows-125x and ISO-8859 families) or folds ASCII
    /// letters only (KOI8-R, whose Cyrillic letters CRuby leaves uncased).
    pub unicode_case: bool,
    /// Unicode scalar for byte `0x80 + i`.
    pub hi: [Option<char>; 128],
}

impl SingleByteTable {
    /// The Unicode scalar for `byte`, `None` for a valid-but-unmapped one.
    pub fn decode(&self, byte: u8) -> Option<char> {
        if byte < 0x80 {
            Some(byte as char)
        } else {
            self.hi[(byte - 0x80) as usize]
        }
    }

    /// The byte encoding `c`, or `None` when this encoding can't represent
    /// it. A linear scan of 128 entries -- fine for the transcode path,
    /// which is never hot.
    pub fn encode(&self, c: char) -> Option<u8> {
        let cp = c as u32;
        if cp < 0x80 {
            return Some(cp as u8);
        }
        self.hi
            .iter()
            .position(|&e| e == Some(c))
            .map(|i| (i + 0x80) as u8)
    }
}

