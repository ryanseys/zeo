//! Object model & dynamic dispatch. See the plan's "Object model & dynamic
//! dispatch" section for the full design rationale: two dispatch paths
//! (static direct/match-on-class_id calls, generated entirely by `zeo`;
//! and this module's runtime `ClassRegistry`/`send`, reached only when
//! `zeo` cannot resolve a call statically). Zeo itself never needs
//! this module at all -- it's the one deliberate architectural addition.

use crate::builtins::{arg_error, frozen_error, name_error, type_error};
use crate::{RubyValue, Signal, Symbol};
use std::any::Any;
use std::collections::{HashMap, HashSet};
use std::sync::{Arc, OnceLock};

/// Identifies a Ruby class at runtime. This is the SHARED `zeo-abi` type --
/// the compiler bakes the same numbering into generated code from the same
/// source of truth, so there is nothing to keep in sync by hand.
pub use zeo_abi::ClassId;

/// Implemented (via `ruby_class!`) by every generated Ruby class, and by the
/// built-in `Object` root below. `Send + Sync` supertrait bounds (Part 9):
/// satisfied automatically for every generated class once its own fields are
/// `parking_lot::Mutex`-wrapped, needing no manual `unsafe impl` anywhere.
pub trait RubyObject: Any + Send + Sync {
    fn class_id(&self) -> ClassId;

    /// Lets `send`'s dispatcher downcast an erased `RObj` back to its
    /// concrete type. No default body: a default `{ self }` here would be
    /// type-checked generically over an unsized `Self` (rustc checks default
    /// bodies once, not per-impl) and fail to coerce to `&dyn Any`. Each
    /// concrete impl provides the one-line body instead (`ruby_class!`
    /// generates it), where `Self` is always a concrete, sized type.
    fn as_any(&self) -> &dyn Any;

    /// The owned-handle counterpart to `as_any` -- needed because every
    /// generated method now takes `self: Arc<Self>` (not `&self`, see
    /// `ruby_class!`'s docs), so Path 2's dynamic trampolines need an
    /// `Arc<Concrete>`, not a `&Concrete`, to actually call one. `Arc<dyn Any
    /// + Send + Sync>` supports a real consuming `downcast::<T>()`; `Arc<dyn
    /// RubyObject>` doesn't (there's no such inherent method on an arbitrary
    /// trait object), so this is the bridge -- same "no default body"
    /// reasoning as `as_any` above.
    fn as_any_rc(self: Arc<Self>) -> Arc<dyn Any + Send + Sync>;

    /// `.frozen?` state -- backed by the `__frozen: AtomicBool`
    /// field `ruby_class!` generates on every class struct (the per-object
    /// counterpart of `collections::Freezable`'s flag). On the trait (not
    /// just inherent) so `freeze_value`/`is_frozen_value` can reach it
    /// through an erased `RObj` without downcasting. The frozen CHECK before
    /// an ivar write is emitted by codegen (`emit_ivar_write_stmt`'s guard),
    /// which alone can construct the `FrozenError` to raise.
    fn is_frozen(&self) -> bool;

    /// Marks this object frozen -- `.freeze`'s storage half; a repeat call
    /// is a harmless no-op, matching CRuby's own already-frozen guard.
    fn set_frozen(&self);

    /// A snapshot of every ivar's current value -- the runtime
    /// ivar ENUMERATION `Ractor`'s recursive shareability check and
    /// `make_shareable`'s deep-freeze traversal need. (Ractor sends still
    /// reject an unfrozen Object rather than deep-copying it -- see
    /// `ractor`'s module docs for that documented divergence.) Generated by
    /// `ruby_class!` from its own ivar list.
    fn ivar_values(&self) -> Vec<RubyValue>;

    /// Every ivar as an ordered `("@name", value)` pair -- what the default
    /// `Object#inspect` rendering and `instance_variables` reflection need,
    /// with names and values paired in ONE pass (so a name-keyed root
    /// `Object`'s map can't desync the two). Generated by `ruby_class!` in
    /// field-declaration order; the default is empty for the runtime's
    /// hand-written objects, which expose no Ruby-visible ivars.
    fn ivar_pairs(&self) -> Vec<(String, RubyValue)> {
        Vec::new()
    }

    /// Read one ivar BY NAME (without the `@`), for the paths where the
    /// receiver's concrete class isn't statically known and codegen
    /// therefore couldn't emit a direct field access: `instance_exec`'s
    /// rebound self, and the top-level `main` object. `None` means this
    /// class declares no such ivar -- distinct from `Some(Nil)`, which is a
    /// declared-but-unassigned one. Generated by `ruby_class!` from its own
    /// ivar list; the default keeps the trait total for the runtime's
    /// hand-written objects, which have no Ruby-visible ivars.
    ///
    /// An ivar the class never names statically (`obj.instance_exec {
    /// @brand_new = 1 }`, `instance_variable_set` with a novel name) lives in
    /// the generated struct's `__overflow` map -- `ruby_class!` routes both
    /// accessors through it after the typed fields miss, so the named path is
    /// total over declared AND invented ivars.
    fn ivar_get_named(&self, _name: &str) -> Option<RubyValue> {
        None
    }

    /// Write one ivar BY NAME -- `ivar_get_named`'s counterpart, same
    /// statically-unknown-receiver paths. Answers whether the write landed
    /// (generated classes always land it, via typed field or `__overflow`;
    /// only ivar-less hand-written runtime objects answer `false`).
    fn ivar_set_named(&self, _name: &str, _v: RubyValue) -> bool {
        false
    }

    /// Remove one ivar BY NAME (without the `@`) -- `Kernel#remove_instance_variable`'s
    /// storage half. `Some(old)` is the removed value; `None` means the object
    /// has no such ivar (the caller raises `NameError`). The default keeps the
    /// trait total for the runtime's hand-written objects. See the caveat in
    /// `ivar_get_named`'s TODO: a generated struct field always physically
    /// exists, so a declared-but-never-assigned field answers `Some(Nil)` where
    /// CRuby raises -- name-keyed objects (`Object`/`DynObject`) don't have this
    /// gap because their map genuinely lacks absent keys.
    fn ivar_remove_named(&self, _name: &str) -> Option<RubyValue> {
        None
    }

    /// `Kernel#dup`/`#clone`'s per-class shallow copy: a fresh
    /// instance of the same concrete struct with every ivar's CURRENT value
    /// cloned into it (a `RubyValue` clone is a handle clone, so nested
    /// objects are SHARED -- CRuby's own shallow rule). `copy_frozen` is
    /// the one `dup`-vs-`clone` difference: `clone` carries the receiver's
    /// frozen flag over, `dup` starts unfrozen. Generated by `ruby_class!`
    /// from its own ivar list (only the concrete impl knows the fields);
    /// `initialize_copy`/singleton-state carryover are documented
    /// scope-cuts. See `RubyValue::dup_value` for the non-Object kinds.
    fn dup_object(&self, copy_frozen: bool) -> RObj;

    /// The wrapped builtin value of a value-builtin SUBCLASS instance (D3):
    /// `class Stack < Array` stores a `RubyValue::Array` here, so inherited
    /// `Array` methods run against it (the `send_in` payload bridge). `None`
    /// for every ordinary object -- only `ValueSubclass` overrides these three.
    /// Returns a HANDLE clone (cheap `Arc` bump), never holding the internal
    /// lock across the re-entrant dispatch that follows.
    fn builtin_payload(&self) -> Option<RubyValue> {
        None
    }
    /// The root builtin whose methods this subclass inherits (`Array` for
    /// `Stack < Array`) -- the ancestor the payload bridge substitutes at.
    fn builtin_root(&self) -> Option<ClassId> {
        None
    }
    /// Re-seat the whole payload (a `super`/`replace`/`initialize` that rebuilds
    /// the collection). `false` for a non-value-subclass. The single write path.
    fn set_builtin_payload(&self, _v: RubyValue) -> bool {
        false
    }
}

/// A handle to any live Ruby object, used wherever the concrete class isn't
/// statically known. The Rust trait object's vtable *is* the tag. Mutability
/// lives on individual ivar fields (see `ruby_class!`), not on this handle, so
/// no lock layer is needed here. `Arc` (not `Rc`): every concrete `RubyObject` impl is
/// `Send + Sync` (via the trait's own supertrait bounds above), so this type
/// itself is genuinely `Send + Sync` -- no `unsafe impl` needed.
pub type RObj = Arc<dyn RubyObject>;

/// The root of every class hierarchy. `ClassId(0)`, no superclass -- the
/// base case `ruby_class!`'s `$super` bottoms out at.
///
/// Unlike a generated class, its ivars live in a NAME-KEYED map rather than
/// struct fields: this is the type behind `main_object()`, and the top level's
/// `self` has no compile-time class whose ivar list codegen could have
/// materialized into fields. `@x` at the top level (or inside a block that
/// `instance_exec` later rebinds onto some other receiver) is resolved by
/// name at runtime, so a map is the honest representation.
#[derive(Default)]
pub struct Object {
    ivars: parking_lot::Mutex<std::collections::HashMap<String, RubyValue>>,
    /// `Object.new.freeze` sets this; `main` never does. A generic Object had
    /// no frozen slot at all before, so `freeze`/`frozen?`/`clone(freeze:)`
    /// silently no-op'd (issue_3033).
    frozen: std::sync::atomic::AtomicBool,
}

impl Object {
    pub const CLASS_ID: ClassId = ClassId(0);
}

/// The builtin `Enumerable` MODULE -- an ordinary
/// `class_table` row (`builtins::enumerable`'s generated `lookup`), reached
/// by the MRO walk for any receiver whose ancestors contain this id. Like
/// every id above, re-exported from the shared `zeo-abi` numbering.
pub use zeo_abi::ENUMERABLE_CLASS;
/// Fixed, well-known `ClassId`s for every built-in Ruby type this runtime
/// models as a `RubyValue` variant rather than a generated `ruby_class!`
/// struct -- numerically mirrored by `zeo::compiler::BUILTIN_CLASSES`
/// (same "two `ClassId` types, on purpose" convention as `Object::CLASS_ID`/
/// `compiler::OBJECT_CLASS`). Registered into the `ClassRegistry` once, from
/// generated `main()` (`codegen::mod`'s `builtin_registrations`), with the
/// SAME linearized `ancestors` every user class gets -- what makes
/// `5.is_a?(Integer)`/`"x".is_a?(Object)`-style checks against a built-in-
/// typed receiver work uniformly through the one general `is_a`/`send`
/// mechanism, and the prerequisite for eventually `include`ing a plain-Ruby
/// `Enumerable`/`Comparable` into these types via ordinary materialization.
pub use zeo_abi::{
    ARRAY_CLASS, BASIC_OBJECT_CLASS, CLASS_CLASS, COMPARABLE_CLASS, COMPLEX_CLASS,
    ENUMERATOR_CLASS, FALSE_CLASS, FIBER_CLASS, FLOAT_CLASS, HASH_CLASS, INTEGER_CLASS,
    KERNEL_CLASS, MATCH_DATA_CLASS, MATH_CLASS, MODULE_CLASS, MUTEX_CLASS, NIL_CLASS,
    NUMERIC_CLASS, PROC_CLASS, QUEUE_CLASS, RACTOR_CLASS, RANGE_CLASS, RATIONAL_CLASS,
    REGEXP_CLASS, SIZED_QUEUE_CLASS, STRING_CLASS, STRUCT_CLASS, SYMBOL_CLASS, THREAD_CLASS,
    TRUE_CLASS, YIELDER_CLASS,
};

impl RubyObject for Object {
    fn class_id(&self) -> ClassId {
        Self::CLASS_ID
    }
    fn as_any(&self) -> &dyn Any {
        self
    }
    fn as_any_rc(self: Arc<Self>) -> Arc<dyn Any + Send + Sync> {
        self
    }
    fn is_frozen(&self) -> bool {
        self.frozen.load(std::sync::atomic::Ordering::Relaxed)
    }
    fn set_frozen(&self) {
        self.frozen
            .store(true, std::sync::atomic::Ordering::Relaxed);
    }
    fn ivar_values(&self) -> Vec<RubyValue> {
        self.ivars.lock().values().cloned().collect()
    }
    fn ivar_pairs(&self) -> Vec<(String, RubyValue)> {
        // The root object's keys are stored WITHOUT the `@` (see
        // `ivar_get_named`); paired in a single lock so name/value order can't
        // diverge. Insertion order isn't preserved (a plain `HashMap`) -- a
        // minor divergence limited to the name-keyed main object, which is
        // rarely inspected with ivars.
        self.ivars
            .lock()
            .iter()
            .map(|(k, v)| (format!("@{k}"), v.clone()))
            .collect()
    }
    fn ivar_get_named(&self, name: &str) -> Option<RubyValue> {
        // A never-assigned ivar reads `nil` rather than raising -- Ruby's
        // rule, and the reason this answers `Some(Nil)` instead of `None`
        // (`None` means "this class has no such slot", which for a
        // name-keyed object is never true).
        Some(
            self.ivars
                .lock()
                .get(name)
                .cloned()
                .unwrap_or(RubyValue::Nil),
        )
    }
    fn ivar_set_named(&self, name: &str, v: RubyValue) -> bool {
        self.ivars.lock().insert(name.to_string(), v);
        true
    }
    fn ivar_remove_named(&self, name: &str) -> Option<RubyValue> {
        // Name-keyed: a missing key is genuinely absent, so `None` cleanly
        // signals CRuby's `NameError` case.
        self.ivars.lock().remove(name)
    }
    fn dup_object(&self, copy_frozen: bool) -> RObj {
        Arc::new(Object {
            ivars: parking_lot::Mutex::new(self.ivars.lock().clone()),
            frozen: std::sync::atomic::AtomicBool::new(copy_frozen && self.is_frozen()),
        })
    }
}

/// [`bind_dynamic_kwargs`]'s result: `(positional, required_values,
/// optional_values, rest_pairs)`.
pub type BoundKwargs<'a> = (
    &'a [RubyValue],
    Vec<RubyValue>,
    Vec<Option<RubyValue>>,
    Vec<(RubyValue, RubyValue)>,
);

/// Binds a DYNAMIC call's keyword arguments for a keyword-declaring callee
/// (the G2 trailing-kwargs-hash convention): when the last argument is a
/// Hash, it's the keyword set; otherwise there are no keywords. Returns
/// `(positional, required_values, optional_values, rest_pairs)` for the
/// generated trampoline to splice into the direct call -- optional `None`s
/// let the callee's own prologue lazily evaluate defaults, exactly like
/// Path 1.
///
/// Documented approximation (plan G2): no `ruby2_keywords` flagging, so a
/// bare trailing Hash passed positionally through `send` to a
/// keyword-declaring method binds as keywords.
pub fn bind_dynamic_kwargs<'a>(
    method: &str,
    args: &'a [RubyValue],
    required: &[&str],
    optional: &[&str],
    has_kwrest: bool,
) -> Result<BoundKwargs<'a>, Signal> {
    let (positional, kw_hash) = match args.split_last() {
        Some((RubyValue::Hash(h), rest)) => (rest, Some(h.clone())),
        _ => (args, None),
    };
    let mut req_values = Vec::with_capacity(required.len());
    let mut opt_values = Vec::with_capacity(optional.len());
    let mut rest_pairs = Vec::new();

    let pairs: Vec<(RubyValue, RubyValue)> = match &kw_hash {
        Some(h) => h.lock().values().cloned().collect(),
        None => Vec::new(),
    };
    let lookup = |name: &str| -> Option<RubyValue> {
        pairs.iter().find_map(|(k, v)| match k {
            RubyValue::Symbol(s) if s.name() == name => Some(v.clone()),
            _ => None,
        })
    };
    let mut missing = Vec::new();
    for name in required {
        match lookup(name) {
            Some(v) => req_values.push(v),
            None => missing.push(name.to_string()),
        }
    }
    if !missing.is_empty() {
        return Err(kw_names_error("missing", &missing));
    }
    for name in optional {
        opt_values.push(lookup(name));
    }
    let mut unknown = Vec::new();
    for (k, v) in &pairs {
        if let RubyValue::Symbol(s) = k {
            let n = s.name();
            if required.contains(&n.as_str()) || optional.contains(&n.as_str()) {
                continue;
            }
            if has_kwrest {
                rest_pairs.push((k.clone(), v.clone()));
                continue;
            }
            unknown.push(n.to_string());
            continue;
        }
        // A non-Symbol key in the trailing hash lands in `**kwrest` as-is (Ruby
        // allows non-symbol keys there); without kwrest it can't bind as a
        // keyword -- real Ruby treats the hash as positional then, but this
        // convention already committed it as keywords (the documented
        // no-ruby2_keywords approximation).
        if has_kwrest {
            rest_pairs.push((k.clone(), v.clone()));
        } else {
            return Err(arg_error!("wrong number of arguments (in `{method}')"));
        }
    }
    if !unknown.is_empty() {
        return Err(kw_names_error("unknown", &unknown));
    }
    Ok((positional, req_values, opt_values, rest_pairs))
}

/// CRuby's keyword-error wording: `missing keyword: :a` / `unknown keywords:
/// :c, :d` -- singular or plural by count, each name a `:sym`, no `(in ...)`
/// suffix. `kind` is `"missing"` or `"unknown"`.
fn kw_names_error(kind: &str, names: &[String]) -> Signal {
    let plural = if names.len() == 1 { "" } else { "s" };
    let list = names
        .iter()
        .map(|n| format!(":{n}"))
        .collect::<Vec<_>>()
        .join(", ");
    arg_error!("{kind} keyword{plural}: {list}")
}

/// The top-level `self` -- CRuby's `main`, a plain `Object` instance.
/// Generated code passes it as the receiver of top-level-defined methods
/// (which live on `Object`, exactly like real Ruby's private-on-Object
/// rule) and as the value of a top-level `self` expression. One shared
/// instance so identity is stable across the program, lazily built since
/// most programs never touch it.
pub fn main_object() -> RubyValue {
    static MAIN: std::sync::OnceLock<RubyValue> = std::sync::OnceLock::new();
    MAIN.get_or_init(|| RubyValue::Object(Arc::new(Object::default())))
        .clone()
}

/// Read `@name` off a receiver whose concrete class isn't statically known
/// -- what codegen emits for an ivar access when `self` is a `RubyValue`
/// rather than an `Arc<Concrete>` (top level, or a block whose self
/// `instance_exec` may rebind). `name` excludes the `@`.
///
/// A non-Object receiver (`5.instance_exec { @x }`) answers nil rather than
/// raising: real Ruby lets you READ an ivar off any object, and immediates
/// simply never have one. An Object whose class declares no such ivar is the
/// same never-assigned case.
pub fn ivar_get_dyn(recv: &RubyValue, name: &str) -> RubyValue {
    match recv {
        RubyValue::Object(o) => o.ivar_get_named(name).unwrap_or(RubyValue::Nil),
        // A CLASS object's own ivars live in their own table (see
        // `civars`' docs for why they can't share `cvars`'). Reached when a
        // class-method body's `self` is dynamic rather than the static class
        // id codegen usually emits -- e.g. `def self.x; [1].each { @n } end`,
        // where the block captures `self` as a plain `RubyValue::Class`.
        RubyValue::Class(cid) => crate::civars::class_ivar_get(cid.0, name),
        _ => RubyValue::Nil,
    }
}

/// Write `@name` on a statically-unknown receiver -- `ivar_get_dyn`'s
/// counterpart, carrying Ruby's frozen check (`rb_check_frozen`) and its
/// can't-modify-frozen raise, which the static field-write path emits
/// inline instead.
pub fn ivar_set_dyn(recv: &RubyValue, name: &str, v: RubyValue) -> Result<RubyValue, Signal> {
    match recv {
        RubyValue::Object(o) => {
            crate::builtins::check_frozen(recv)?;
            o.ivar_set_named(name, v.clone());
            Ok(v)
        }
        // See `ivar_get_dyn`'s Class arm. The frozen-class guard lives
        // inside `class_ivar_set` itself.
        RubyValue::Class(cid) => {
            crate::civars::class_ivar_set(cid.0, name, v.clone())?;
            Ok(v)
        }
        // Real Ruby raises here (immediates are frozen and have no ivar
        // table), and the message names the receiver's class.
        _ => Err(frozen_error!(
            "can't modify frozen {}: {}",
            crate::builtins::class_name_of(recv),
            recv.inspect_string()
        )),
    }
}

/// Downcasts an erased `RObj` to an owned `Arc<T>` -- the Path 2 trampoline
/// counterpart to `as_any().downcast_ref()`, needed because every generated
/// method takes `self: Arc<Self>` now (see `ruby_class!`'s docs). Cloning
/// `recv` first is a cheap `Arc` refcount bump, not a deep copy.
pub fn downcast_robj<T: RubyObject>(recv: &RObj) -> Option<Arc<T>> {
    recv.clone().as_any_rc().downcast::<T>().ok()
}

/// Every generated method/trampoline returns `Result<RubyValue, Signal>`, not
/// a bare `RubyValue` -- see `Signal`'s docs for why this is fixed from the
/// start rather than retrofitted once `break`/`raise`/non-local `return`
/// exist. The third parameter is the call's block, if any (`None` when no
/// block was given) -- see `signal.rs`'s `catch_break` and `codegen::params`'s
/// docs for how a block crosses the Path 2 boundary.
pub type MethodFn = fn(&RObj, &[RubyValue], Option<RubyValue>) -> Result<RubyValue, Signal>;

/// A method body no bare `fn` pointer can represent: a closure carrying
/// captured state (a runtime `define_method` block today; interpreted eval-VM
/// bodies when that phase lands).
pub type DynMethodFn =
    Arc<dyn Fn(&RObj, &[RubyValue], Option<RubyValue>) -> Result<RubyValue, Signal> + Send + Sync>;

/// A registered instance method's implementation. Statically-registered
/// methods are `Static` -- a bare `fn` pointer -- so the hot path is a direct
/// indirect call with one folded discriminant branch, no allocation.
#[derive(Clone)]
pub enum MethodImpl {
    Static(MethodFn),
    // The runtime-metaprogramming seam: a compiled block captured as an
    // `Arc<dyn Fn>`, built by `runtime_meta::dynamic_from_proc` for a runtime
    // `define_method`. `Clone` is cheap on both arms (a `fn` copy / an `Arc`
    // bump) -- the overlay resolvers clone an entry out and drop their lock
    // BEFORE dispatching, so a runtime method that itself defines another
    // method can't deadlock.
    Dynamic(DynMethodFn),
}

impl MethodImpl {
    #[inline(always)]
    pub fn call(
        &self,
        recv: &RObj,
        args: &[RubyValue],
        block: Option<RubyValue>,
    ) -> Result<RubyValue, Signal> {
        match self {
            MethodImpl::Static(f) => f(recv, args, block),
            MethodImpl::Dynamic(f) => f(recv, args, block),
        }
    }

    #[inline(always)]
    pub fn from_fn(f: MethodFn) -> Self {
        MethodImpl::Static(f)
    }
}

/// A class's dynamic constructor: allocates a fresh instance
/// and runs its `initialize` (if any) -- what makes `x = Widget;
/// x.new(...)` work when the class is only known at runtime as a
/// `RubyValue::Class` value. Generated per class by `ruby_class!`
/// (`__construct`, which ignores the id and uses its own `Self::CLASS_ID`);
/// `None` for modules and builtins.
///
/// The leading `ClassId` lets ONE constructor back many classes -- the native
/// exception hierarchy registers every exception class with the same
/// `RubyException`-allocating fn, which reads the id from here instead of a
/// per-class Rust type (see `crate::builtins::exception`).
pub type ConstructorFn = fn(ClassId, &[RubyValue], Option<RubyValue>) -> Result<RubyValue, Signal>;

/// Allocates a fresh, ZERO-INITIALIZED instance of a class WITHOUT running
/// `initialize` -- backs `Class#allocate`. Mirrors `ConstructorFn`'s
/// id-passing shape (one allocator can back many classes) but returns the
/// bare `RObj` (every ivar `Nil`, frozen `false`); the caller wraps it in
/// `RubyValue::Object`. `None` for modules/builtins (which have no generated
/// struct); `Class#allocate` on those either yields a builtin empty value or
/// raises, handled at the call site.
pub type AllocatorFn = fn(ClassId) -> RObj;

/// A method defined by REOPENING a builtin class (`class String;
/// def blank?; ...`): the receiver is the builtin VALUE itself (`&RubyValue`,
/// not an `RObj` -- builtins have no generated struct to downcast to), which
/// is exactly what the generated free-function bodies take as `__self`.
/// Consulted FIRST by `send_value` (before even the universal `==`/`dup`
/// arms and the curated tables), because a user redefinition must OVERRIDE
/// the builtin behavior -- real Ruby's rule, oracle-verified (`class String;
/// def length; 42; end` wins everywhere). Per-box overlays key off
/// this same table.
pub type ValueMethodFn =
    fn(&RubyValue, &[RubyValue], Option<RubyValue>) -> Result<RubyValue, Signal>;

struct ClassEntry {
    /// The Ruby-visible, fully-qualified name (`"Store::Item"`) -- what
    /// `Class#name`/`#to_s`/`puts Widget` print, and what `NoMethodError`
    /// messages cite (retiring the class-id-in-the-message
    /// approximation).
    name: String,
    is_module: bool,
    /// The full, already-linearized MRO (this class first, then prepends/
    /// includes/superclass in resolution order) -- computed at COMPILE time
    /// by `zeo::analyze::mro::compute_ancestors` and baked in as a
    /// literal list by `ruby_class!`'s generated `__register`. Method
    /// dispatch itself never needs to walk this (every reachable method is
    /// already MATERIALIZED directly onto this class -- see the plan's Part
    /// 6), but `is_a`/rescue-by-class matching does.
    ancestors: Vec<ClassId>,
    methods: HashMap<Symbol, MethodImpl>,
    /// Methods added by reopening a BUILTIN class -- keyed off
    /// the receiver's `class_id()` with no ancestor walk needed (the only
    /// reopenable builtins are leaf value classes; Object/module reopens are
    /// rejected at zeo compile time). Empty for every user class, whose
    /// methods live in `methods` above. Keyed `(box_id, name)`: a builtin
    /// reopened INSIDE a `Ruby::Box` registers its methods under that box's
    /// id, and dispatch probes `(caller's box, name)` then `(0, name)` -- the
    /// AOT translation of CRuby's `cme->def->box` stamping, root reopens
    /// visible everywhere.
    ///
    /// KNOWN DIVERGENCE (box-only, bundler-irrelevant): this `(box_id, name)`
    /// dimension covers INSTANCE methods on a reopened builtin. A per-box
    /// SINGLETON method (`class String; def self.count; end` inside a box) and
    /// a per-box CLASS VARIABLE / class-ivar on a shared builtin are keyed by
    /// `ClassId` alone (see `cvars`/`civars`), which for a shared builtin is
    /// the same id in every box -- so, unlike CRuby, they are not isolated
    /// per box. Per-box state on distinct USER classes (their own `ClassId`
    /// per box) and per-box instance-method monkeypatches both work.
    value_methods: HashMap<(u32, Symbol), ValueMethodFn>,
    /// This class's OWN method implementations -- what `super` resolution
    /// walks. `methods` above is the FLATTENED instance-dispatch set (an
    /// entry's winner can be a prepended module's or an ancestor's copy),
    /// which is exactly wrong for `super`: resuming an MRO walk needs each
    /// position's own contribution, or a prepended method's `super` finds
    /// itself again. Filled three ways: `promote_own_impl` (the common
    /// case -- the flattened winner IS the own def), `define_method_own`
    /// (native exception sets), and `define_super_target_value` (a
    /// dynamic-self bridge for an own def shadowed in its own class's
    /// flattened table).
    own_impls: HashMap<Symbol, MethodImpl>,
    /// The names in `methods`/`value_methods` that Ruby considers PRIVATE
    /// (`private def x`, and every top-level `def` -- which is a private
    /// method of Object). Dispatch itself ignores this (an implicit-self
    /// call and `send` both reach privates, and codegen enforces the
    /// explicit-receiver rule statically where it can); it exists so
    /// `respond_to?` can skip them, matching CRuby's "the default ignores
    /// private methods" rule. Kernel's own C-implemented privates
    /// (`puts`/`p`/...) aren't here -- they have no registry entry at all
    /// and are special-cased in `responds_to`.
    private_methods: HashSet<Symbol>,
    /// The names in `methods`/`value_methods` this class marks PROTECTED
    /// (`protected def x`, a bare `protected` section, `protected :x`). Parallel
    /// to `private_methods`; a name in neither set is public. Materialization
    /// stamps the mark onto every descendant that inherits the method, so this
    /// set is authoritative for the class itself (no ancestor walk needed to
    /// answer "is THIS class's `name` protected"). Consumed by the
    /// `protected_*` reflection and the `*_method_defined?` family.
    protected_methods: HashSet<Symbol>,
    /// Names this class's body `undef`'d. Mirrors CRuby, where `undef`
    /// inserts an "undefined" method entry that TERMINATES the lookup
    /// rather than deleting anything -- so an inherited name stops
    /// resolving here while staying live on the ancestor that defined it.
    ///
    /// Dispatch itself needs no check: `mro::materialize_methods` already
    /// refuses to materialize an undef'd name onto this class, and dispatch
    /// only ever reads this class's own table. `respond_to?` is the one
    /// consumer, because it WALKS the ancestors and would otherwise find
    /// the ancestor's still-live definition.
    undefined_methods: HashSet<Symbol>,
    /// `new -> old` NAME indirections for aliases of INHERITED BUILTIN
    /// methods (`alias_method :raise!, :raise`): the source has no user
    /// `Scope` to clone a body from -- it lives in the static builtin
    /// tables -- so the alias is recorded as a name rewrite instead. The
    /// send miss paths consult this via `alias_target` (closest ancestor
    /// first, so subclasses inherit it through the ordinary MRO walk) and
    /// re-dispatch under `old`. Entries are TERMINAL: the compiler resolves
    /// an alias-of-an-alias before emitting `register_alias`, and
    /// `validate_aliases` raises `NameError` at program start for a source
    /// that resolves nowhere (real Ruby's timing -- the class body
    /// executing).
    aliases: HashMap<Symbol, Symbol>,
    /// This class's own CLASS methods (`def self.x`, `class << self`,
    /// `extend`) -- reached when a `RubyValue::Class` receiver is sent to
    /// dynamically (`handler.run(...)`, where `handler` holds a class), the
    /// one path where the callee isn't statically known and so can't be a
    /// direct `Foo::__cm_run(...)` call.
    ///
    /// `ValueMethodFn`-shaped like `value_methods`, but with a DROPPED
    /// receiver rather than a passed one (`params::RecvMode`): the emitted
    /// class-method free function takes no receiver parameter.
    ///
    /// No ancestor walk on lookup, for the same reason `methods` needs
    /// none: `analyze::mro::materialize_class_methods` already copies every
    /// inherited class method onto each subclass at compile time, so a hit
    /// here is always this exact class's own entry. That is also what keeps
    /// class-level `@x` storage correct through this path -- each copy
    /// carries its own class id (see `civars`' docs).
    class_methods: HashMap<Symbol, ValueMethodFn>,
    /// Per-POSITION singleton-chain super targets, keyed `(module id,
    /// name)`: one emitted copy of every `extend`ed module's method (winner
    /// AND shadowed -- the flattened `class_methods` above keeps only
    /// winners, which is exactly wrong for `super` the same way `methods`
    /// is vs `own_impls`). `call_singleton_super_target` probes this before
    /// the module's generic bridge, so a sibling-extend chain (`extend A`
    /// then `extend B`, each `super`ing to the next) resolves every hop
    /// with the RECEIVER's context.
    singleton_super_targets: HashMap<(u32, Symbol), ValueMethodFn>,
    /// The names DEFINED DIRECTLY on this class (not materialized from an
    /// ancestor) -- what `instance_methods(false)` needs, since `methods`
    /// above holds the flattened, fully-materialized set (dispatch's own
    /// requirement -- see `ancestors`' docs). Populated by codegen's
    /// `mark_own` beside `mark_private`. Empty means "unknown/none recorded",
    /// in which case reflection falls back to the materialized set.
    own_methods: HashSet<Symbol>,
    /// `own_methods`' class-method twin: the names whose `def self.x` is
    /// written HERE, as opposed to materialized down from an ancestor. Only
    /// reflection needs the distinction -- `Cache.method(:open).owner` has to
    /// answer `Store` even though materialization gave `Cache` a copy.
    own_class_methods: HashSet<Symbol>,
    constructor: Option<ConstructorFn>,
    /// The no-`initialize` allocator backing `Class#allocate` -- registered by
    /// `ruby_class!`'s `__register` beside the constructor. `None` for
    /// modules/builtins.
    allocator: Option<AllocatorFn>,
}

#[derive(Default)]
pub struct ClassRegistry {
    entries: HashMap<u32, ClassEntry>,
    /// Fully-qualified class NAME -> id, so the runtime can construct an
    /// exception by name (`raise_error("ArgumentError", ...)`) without the
    /// generated program installing a name->constructor factory. Populated by
    /// `register` alongside `entries`. See `construct_exception`.
    by_name: HashMap<String, u32>,
}

impl ClassRegistry {
    pub fn new() -> ClassRegistry {
        ClassRegistry::default()
    }

    /// Mirrors declaring a class's place in the hierarchy -- called once per
    /// class from that class's generated `__register` (or directly from
    /// generated `main()` for modules/builtins, which have no struct), with
    /// `ancestors` already fully linearized at zeo compile time.
    pub fn register(
        &mut self,
        id: ClassId,
        name: &str,
        is_module: bool,
        ancestors: Vec<ClassId>,
        constructor: Option<ConstructorFn>,
    ) {
        self.by_name.insert(name.to_string(), id.0);
        self.entries.insert(
            id.0,
            ClassEntry {
                name: name.to_string(),
                is_module,
                ancestors,
                methods: HashMap::new(),
                own_impls: HashMap::new(),
                value_methods: HashMap::new(),
                private_methods: HashSet::new(),
                protected_methods: HashSet::new(),
                undefined_methods: HashSet::new(),
                aliases: HashMap::new(),
                class_methods: HashMap::new(),
                singleton_super_targets: HashMap::new(),
                own_methods: HashSet::new(),
                own_class_methods: HashSet::new(),
                constructor,
                allocator: None,
            },
        );
    }

    /// Registers the no-`initialize` allocator backing `Class#allocate` --
    /// called once per user class from its generated `__register`, right after
    /// `register`. See `ClassEntry::allocator`.
    pub fn define_allocator(&mut self, id: ClassId, f: AllocatorFn) {
        if let Some(e) = self.entries.get_mut(&id.0) {
            e.allocator = Some(f);
        }
    }

    /// Builds a fresh uninitialized instance of `id` via its registered
    /// allocator (`Class#allocate`), or `None` if the class registered none
    /// (a module/builtin). Does NOT run `initialize`.
    pub fn allocate_instance(&self, id: ClassId) -> Option<RubyValue> {
        let alloc = self.entries.get(&id.0).and_then(|e| e.allocator)?;
        Some(RubyValue::Object(alloc(id)))
    }

    /// Build an exception instance from a class NAME + message. Every built-in
    /// exception class registers its constructor `ConstructorFn` through
    /// `register_exceptions`, so the runtime constructs the object itself:
    /// allocate the struct and run `initialize(msg)` through the SAME trampoline
    /// `SomeError.new(msg)` uses. An unknown name is a zeo-rt bug (a `raise_error`
    /// site naming a class no exception defines). `Exception#initialize` only
    /// assigns `@message` and cannot signal, so a `Signal` here is a bug.
    pub fn construct_exception(&self, class_name: &str, msg: String) -> RubyValue {
        let id = self.by_name.get(class_name).copied();
        let ctor = id
            .and_then(|id| self.entries.get(&id))
            .and_then(|entry| entry.constructor);
        match (id, ctor) {
            (Some(id), Some(ctor)) => {
                ctor(ClassId(id), &[RubyValue::Str(crate::string_new(msg))], None)
                    .expect("Exception#initialize can't signal")
            }
            // No such class registered: a `raise_error` site naming a class no
            // exception defines (a zeo-rt bug), or a partial test registry.
            // Panic with the full message -- the same uncatchable fallback the
            // old registry-less `raise_error` used, so the real error still
            // surfaces rather than being masked by an "unknown class" note.
            _ => panic!("{class_name}: {msg}"),
        }
    }

    /// Records `name` as DEFINED DIRECTLY on `id` (not inherited) -- emitted by
    /// codegen for each of the class's own `def`s, beside `mark_private`. See
    /// `ClassEntry::own_methods`.
    pub fn mark_own(&mut self, id: ClassId, name: Symbol) {
        if let Some(e) = self.entries.get_mut(&id.0) {
            e.own_methods.insert(name);
        }
    }

    /// [`mark_own`](Self::mark_own) for a `def self.x` -- see
    /// `ClassEntry::own_class_methods`.
    pub fn mark_own_class_method(&mut self, id: ClassId, name: Symbol) {
        if let Some(e) = self.entries.get_mut(&id.0) {
            e.own_class_methods.insert(name);
        }
    }

    /// Registers a builtin-reopen method -- called from
    /// generated `main()` right after the builtin's own `register`, one call
    /// per `def` in a `class String ... end` reopen. `box_id` is the box the
    /// reopen was written in (0 for the root program; a box's
    /// overlay methods register under its id and are visible only from that
    /// box's code). See `ValueMethodFn`'s docs for the precedence contract.
    /// Records `name` as PRIVATE on `id` -- emitted by codegen right after
    /// the method's own registration, for each `def` whose resolved
    /// visibility is private. See `ClassEntry::private_methods`.
    pub fn mark_private(&mut self, id: ClassId, name: Symbol) {
        self.entries
            .get_mut(&id.0)
            .expect("class must be registered before marking its methods private")
            .private_methods
            .insert(name);
    }

    fn is_private(&self, id: ClassId, name: Symbol) -> bool {
        self.entries
            .get(&id.0)
            .is_some_and(|e| e.private_methods.contains(&name))
    }

    fn is_protected(&self, id: ClassId, name: Symbol) -> bool {
        self.entries
            .get(&id.0)
            .is_some_and(|e| e.protected_methods.contains(&name))
    }

    /// Records `name` as PROTECTED on `id` -- emitted by codegen beside
    /// `mark_private` for each `def` whose resolved visibility is protected.
    /// See `ClassEntry::protected_methods`.
    pub fn mark_protected(&mut self, id: ClassId, name: Symbol) {
        if let Some(e) = self.entries.get_mut(&id.0) {
            e.protected_methods.insert(name);
        }
    }

    /// Restores `name` to PUBLIC on `id` -- clears any private/protected mark.
    /// Emitted for a `public :m` that promotes an inherited private/protected
    /// method (materialization first stamps it with the ancestor's visibility;
    /// this override wins). See `ClassEntry::visibility_overrides` in zeo.
    pub fn mark_public(&mut self, id: ClassId, name: Symbol) {
        if let Some(e) = self.entries.get_mut(&id.0) {
            e.private_methods.remove(&name);
            e.protected_methods.remove(&name);
        }
    }

    /// The visibility `id` records for `name` IF it defines or materializes it
    /// (an own `def`, a builtin reopen, or an inherited method flattened in),
    /// else `None`. Answers only THIS class's table -- the MRO walk is the
    /// caller's (`instance_method_visibility`).
    fn own_method_visibility(&self, id: ClassId, name: Symbol) -> Option<MethodVisibility> {
        let e = self.entries.get(&id.0)?;
        let defines = e.own_methods.contains(&name)
            || e.methods.contains_key(&name)
            || e.value_methods.keys().any(|(_, n)| *n == name);
        if !defines {
            return None;
        }
        Some(if e.protected_methods.contains(&name) {
            MethodVisibility::Protected
        } else if e.private_methods.contains(&name) {
            MethodVisibility::Private
        } else {
            MethodVisibility::Public
        })
    }

    pub fn define_value_method(
        &mut self,
        id: ClassId,
        box_id: u32,
        name: Symbol,
        f: ValueMethodFn,
    ) {
        self.entries
            .get_mut(&id.0)
            .unwrap_or_else(|| {
                panic!(
                    "class {} must be registered before defining `{}` on it",
                    id.0,
                    name.name()
                )
            })
            .value_methods
            .insert((box_id, name), f);
    }

    /// Records an `undef name` -- see `ClassEntry::undefined_methods`.
    pub fn mark_undefined(&mut self, id: ClassId, name: Symbol) {
        self.entries
            .get_mut(&id.0)
            .expect("class must be registered before undefining methods on it")
            .undefined_methods
            .insert(name);
    }

    /// Records an alias of an inherited BUILTIN method (see
    /// `ClassEntry::aliases`) -- emitted by codegen next to the class's
    /// registration. Pure data here; `validate_aliases` (run at program
    /// start, inside the fallible closure) is what raises `NameError` for a
    /// source that resolves nowhere.
    /// The NEW names `id`'s own builtin-alias rows define -- what reflection
    /// has to list, since an alias is a name indirection here rather than a
    /// copied method entry. Empty for an unregistered or aliasless id.
    fn alias_names(&self, id: ClassId) -> Vec<Symbol> {
        self.entries
            .get(&id.0)
            .map(|e| e.aliases.keys().copied().collect())
            .unwrap_or_default()
    }

    pub fn register_alias(&mut self, id: ClassId, new: &str, old: &str) {
        self.entries
            .get_mut(&id.0)
            .expect("class must be registered before aliasing methods on it")
            .aliases
            .insert(Symbol::intern(new), Symbol::intern(old));
    }

    /// Whether `id`'s own body `undef`'d `name` -- the lookup TERMINATOR
    /// `respond_to?`'s ancestor walk consults.
    fn is_undefined(&self, id: ClassId, name: Symbol) -> bool {
        self.entries
            .get(&id.0)
            .is_some_and(|e| e.undefined_methods.contains(&name))
    }

    /// Registers one `def self.x` for dynamic dispatch -- see
    /// `ClassEntry::class_methods`' docs.
    pub fn define_class_method(&mut self, id: ClassId, name: Symbol, f: ValueMethodFn) {
        self.entries
            .get_mut(&id.0)
            .expect("class must be registered before defining class methods on it")
            .class_methods
            .insert(name, f);
    }

    /// Registers one `extend`ed-module method copy as a singleton-chain
    /// super target on the EXTENDING class -- see
    /// `ClassEntry::singleton_super_targets`.
    pub fn define_singleton_super_target(
        &mut self,
        id: ClassId,
        module: ClassId,
        name: Symbol,
        f: ValueMethodFn,
    ) {
        self.entries
            .get_mut(&id.0)
            .expect("class must be registered before defining class methods on it")
            .singleton_super_targets
            .insert((module.0, name), f);
    }

    /// The runtime-mutable path `define_method`/`define_singleton_method`
    /// actually go through: a real `HashMap` insert, no compile-time
    /// literal-name restriction (contrast zeo's `walk_scope`, which can
    /// only register a `define_method` as a scope if the name is a literal).
    pub fn define_method(&mut self, id: ClassId, name: Symbol, f: MethodFn) {
        self.entries
            .get_mut(&id.0)
            .expect("class must be registered before defining methods on it")
            .methods
            .insert(name, MethodImpl::from_fn(f));
    }

    /// `define_method` that ALSO records the row as this class's own
    /// `super` target -- the native exception method sets use this (every
    /// exception id carries the natives, so a `super` walk finds them at
    /// the first ancestor, behaviorally identical to CRuby finding them on
    /// `Exception`).
    pub fn define_method_own(&mut self, id: ClassId, name: Symbol, f: MethodFn) {
        let e = self
            .entries
            .get_mut(&id.0)
            .expect("class must be registered before defining methods on it");
        e.methods.insert(name, MethodImpl::from_fn(f));
        e.own_impls.insert(name, MethodImpl::from_fn(f));
    }

    /// Copies the flattened `methods` row for `name` into `own_impls` --
    /// emitted by codegen for each method a class defines DIRECTLY whose
    /// flattened winner is that own definition (everything except a
    /// prepend-shadowed own def), after all registration/delta rows landed.
    pub fn promote_own_impl(&mut self, id: ClassId, name: Symbol) {
        if let Some(e) = self.entries.get_mut(&id.0) {
            if let Some(m) = e.methods.get(&name).cloned() {
                e.own_impls.insert(name, m);
            }
        }
    }

    /// Registers a dynamic-self free function as an own `super` target --
    /// the bridge shape for an own def SHADOWED in its own class's
    /// flattened table (its body exists only as a `RubyValue`-self fn).
    pub fn define_super_target_value(&mut self, id: ClassId, name: Symbol, f: ValueMethodFn) {
        let e = self
            .entries
            .get_mut(&id.0)
            .expect("class must be registered before defining methods on it");
        e.own_impls.insert(
            name,
            MethodImpl::Dynamic(Arc::new(
                move |recv: &RObj, args: &[RubyValue], block: Option<RubyValue>| {
                    f(&RubyValue::Object(recv.clone()), args, block)
                },
            )),
        );
    }

    /// This class's OWN contribution to an MRO walk -- see
    /// `ClassEntry::own_impls`.
    fn super_target(&self, id: ClassId, name: Symbol) -> Option<&MethodImpl> {
        self.entries.get(&id.0)?.own_impls.get(&name)
    }

    fn lookup(&self, id: ClassId, name: Symbol) -> Option<&MethodImpl> {
        self.entries.get(&id.0)?.methods.get(&name)
    }

    /// `lookup` with CRuby's real resolution shape behind it: the flat
    /// materialized probe first (the hot path -- compile-time
    /// materialization flattens every reachable method onto each class, so
    /// this hit rate is ~100%), then a genuine ANCESTOR WALK over the
    /// registry entries as insurance for any row materialization missed.
    /// An `undef`'d name TERMINATES the walk at the class that undefined
    /// it (CRuby inserts a lookup-stopping "undefined" entry, it never
    /// deletes) -- checked per ancestor, so an ancestor's undef shadows a
    /// definition above it while the receiver's own materialized set stays
    /// authoritative below it. This is the dispatch shape `Ruby::Box`'s
    /// per-box overlays extend later (the walk gains a box dimension).
    fn lookup_mro(&self, id: ClassId, name: Symbol) -> Option<&MethodImpl> {
        // A RUNTIME `undef_method` (`undef :m if <cond>`) tombstones the name in
        // the overlay, which this frozen table was built too early to know
        // about. Each position is checked there first so a tombstone terminates
        // the walk exactly as a compile-time `undef` does -- gated on
        // `is_live`, so the ordinary lock-free path is untouched.
        let overlay_live = crate::runtime_meta::is_live();
        let tombstoned =
            |cid: ClassId| overlay_live && crate::runtime_meta::overlay_is_undefined(cid, name);
        if tombstoned(id) {
            return None;
        }
        if let Some(e) = self.entries.get(&id.0) {
            if let Some(m) = e.methods.get(&name) {
                return Some(m);
            }
            if e.undefined_methods.contains(&name) {
                return None;
            }
        }
        for &anc in self.ancestors_of(id).iter().skip(1) {
            if tombstoned(anc) {
                return None;
            }
            let Some(e) = self.entries.get(&anc.0) else {
                continue;
            };
            if let Some(m) = e.methods.get(&name) {
                return Some(m);
            }
            if e.undefined_methods.contains(&name) {
                return None;
            }
        }
        None
    }

    /// Whether `name` is defined DIRECTLY on `id` (a `def` here, or a builtin
    /// reopen), as opposed to materialized in from an ancestor. This is the
    /// signal `Method#owner` needs: materialization copies an inherited method
    /// onto every descendant's `methods` table, so `lookup` can't tell where it
    /// originated, but `own_methods`/`value_methods` record only local defs.
    fn defines_own(&self, id: ClassId, name: Symbol) -> bool {
        let Some(e) = self.entries.get(&id.0) else {
            return false;
        };
        e.own_methods.contains(&name) || e.value_methods.keys().any(|(_, n)| *n == name)
    }

    /// This class's registered instance-method names, each tagged private/not,
    /// excluding `undef`'d names -- the registry half of `instance_methods`/
    /// `methods` reflection. `own_only` narrows the user-method set to those
    /// DEFINED DIRECTLY on the class (for `instance_methods(false)`); builtin
    /// reopens (`value_methods`) are always own. When `own_only` is set but the
    /// class recorded no own-set (e.g. a builtin with no reopens), nothing is
    /// dropped only because there is nothing to drop.
    fn own_instance_method_names(
        &self,
        id: ClassId,
        own_only: bool,
    ) -> Vec<(Symbol, MethodVisibility)> {
        let Some(e) = self.entries.get(&id.0) else {
            return Vec::new();
        };
        let mut seen = HashSet::new();
        let mut out = Vec::new();
        let consider = |name: Symbol,
                        seen: &mut HashSet<Symbol>,
                        out: &mut Vec<(Symbol, MethodVisibility)>| {
            if e.undefined_methods.contains(&name) || !seen.insert(name) {
                return;
            }
            let vis = if e.protected_methods.contains(&name) {
                MethodVisibility::Protected
            } else if e.private_methods.contains(&name) {
                MethodVisibility::Private
            } else {
                MethodVisibility::Public
            };
            out.push((name, vis));
        };
        // `own_methods` is the authoritative "defined directly here" set --
        // and the ONLY reliable source for a MODULE, whose instance methods
        // live on its includers rather than its own `methods` map.
        for &name in &e.own_methods {
            consider(name, &mut seen, &mut out);
        }
        // Builtin-reopen methods are always own to the reopened class.
        for (_, name) in e.value_methods.keys() {
            consider(*name, &mut seen, &mut out);
        }
        if !own_only {
            // The materialized set adds the inherited methods flattened onto a
            // concrete class at compile time.
            for name in e.methods.keys().copied() {
                consider(name, &mut seen, &mut out);
            }
        }
        out
    }

    /// This class's OWN `def self.x` names -- the registry half of
    /// `SomeClass.singleton_methods`/`.methods`.
    fn own_class_method_names(&self, id: ClassId) -> Vec<Symbol> {
        self.entries
            .get(&id.0)
            .map(|e| e.class_methods.keys().copied().collect())
            .unwrap_or_default()
    }

    /// The `(caller's box, name)` probe with the root fallback -- CRuby's
    /// def->box resolution rule: a box's own patch wins inside the box,
    /// root patches are visible everywhere, and nothing else is.
    fn lookup_value_method(&self, id: ClassId, box_id: u32, name: Symbol) -> Option<ValueMethodFn> {
        let entry = self.entries.get(&id.0)?;
        if box_id != 0 {
            if let Some(f) = entry.value_methods.get(&(box_id, name)) {
                return Some(*f);
            }
        }
        entry.value_methods.get(&(0, name)).copied()
    }

    fn ancestors_of(&self, id: ClassId) -> &[ClassId] {
        self.entries.get(&id.0).map_or(&[], |e| &e.ancestors)
    }
}

/// `recv_class.is_a?(target)` -- a real ancestry check against the SAME
/// linearized `ancestors` list `super`/reflection uses at compile time (see
/// `analyze::mro::compute_ancestors`'s docs), not zeo's own two-tier
/// "transplant for dispatch, shallower list for reflection" split (confirmed
/// to diverge on a module-of-module diamond -- see the plan). The one
/// runtime surface this needs for `Signal::Raise`/`rescue` matching:
/// there's no first-class `Class`/`Module` runtime VALUE (can't be stored in
/// a variable or reflected on generally), just this narrow "is this concrete
/// class id ancestor-compatible with that one" check.
pub fn is_a(recv_class: ClassId, target: ClassId) -> bool {
    ancestors_of_value(recv_class).contains(&target)
}

/// `rescue *list => e` matching: does the raised `exc` match any class in the
/// splatted `list`? `list` is the EVALUATED splat expression -- an Array of
/// exception classes (`rescue *errs`), or, splatting a non-array, a single
/// class (`rescue *ArgumentError`). An empty array matches nothing. A
/// non-Module element is CRuby's `TypeError: class or module required for
/// rescue clause`. OR'd in after a clause's static class list by codegen.
pub fn rescue_matches_any(exc: &RubyValue, list: &RubyValue) -> Result<bool, Signal> {
    match list {
        RubyValue::Array(a) => {
            for el in a.lock().to_vec() {
                if rescue_class_matches(&el, exc)? {
                    return Ok(true);
                }
            }
            Ok(false)
        }
        single => rescue_class_matches(single, exc),
    }
}

fn rescue_class_matches(cls: &RubyValue, exc: &RubyValue) -> Result<bool, Signal> {
    match cls {
        RubyValue::Class(cid) => Ok(is_a(exc.as_object_unchecked().class_id(), *cid)),
        _ => Err(raise_error(
            "TypeError",
            "class or module required for rescue clause".to_string(),
        )),
    }
}

/// `Module#<=>`-style ordering of two class/module ids by the ancestry
/// relation (CRuby `rb_class_cmp`): `Less` when `a` is a proper descendant of
/// `b`, `Greater` when a proper ancestor, `Equal` when the same class, and
/// `None` when the two are unrelated (neither appears in the other's
/// linearized ancestors). Backs `Module`'s `<`/`<=`/`>`/`>=`/`<=>` rows.
pub fn module_cmp(a: ClassId, b: ClassId) -> Option<std::cmp::Ordering> {
    use std::cmp::Ordering;
    let a_le_b = is_a(a, b); // b in a's ancestors: a is b-or-below
    let b_le_a = is_a(b, a);
    match (a_le_b, b_le_a) {
        (true, true) => Some(Ordering::Equal),
        (true, false) => Some(Ordering::Less),
        (false, true) => Some(Ordering::Greater),
        (false, false) => None,
    }
}

/// The DIRECT subclasses of `cid` (CRuby `Class#subclasses`): every registered
/// non-module class whose immediate superclass -- the first non-module entry
/// after itself in its linearized ancestry -- is `cid`. Order is unspecified
/// in CRuby, so callers that need determinism sort by name.
pub fn direct_subclasses(cid: ClassId) -> Vec<ClassId> {
    let Some(r) = REGISTRY.get() else {
        return Vec::new();
    };
    r.entries
        .iter()
        .filter(|(_, e)| !e.is_module)
        .filter_map(|(&id, e)| {
            let self_id = ClassId(id);
            if self_id == cid {
                return None;
            }
            let sup = e
                .ancestors
                .iter()
                .skip_while(|&&a| a != self_id)
                .skip(1)
                .find(|&&a| !class_is_module(a).unwrap_or(false))?;
            (*sup == cid).then_some(self_id)
        })
        .collect()
}

/// The bare ivar name (`x`) from a `:@x`/`"@x"` reflection argument. A
/// non-symbol/string is a `TypeError`; a name without the leading `@` is a
/// `NameError` -- both mirroring CRuby's own messages. Shared by the
/// universal `Object#instance_variable_*` helpers below (the class-object
/// table in `builtins::class_module` keeps its own parallel copy).
pub fn ivar_name_arg(v: &RubyValue) -> Result<String, Signal> {
    let raw = match v {
        RubyValue::Symbol(s) => s.name().to_string(),
        RubyValue::Str(s) => s.lock().to_utf8_lossy().into_owned(),
        _ => {
            return Err(type_error!(
                "{} is not a symbol nor a string",
                v.inspect_string()
            ));
        }
    };
    match raw.strip_prefix('@') {
        Some(name) => Ok(name.to_string()),
        None => Err(name_error!(
            "'{raw}' is not allowed as an instance variable name"
        )),
    }
}

/// `Object#instance_variable_get(:@x)` over ANY receiver: an `Object`'s named
/// ivar, a class object's own ivar (`civars`), or `nil` for a builtin/
/// immediate (which expose no Ruby-visible ivars in this runtime).
pub fn instance_variable_get(recv: &RubyValue, name_arg: &RubyValue) -> Result<RubyValue, Signal> {
    let name = ivar_name_arg(name_arg)?;
    Ok(match recv {
        RubyValue::Object(o) => o.ivar_get_named(&name).unwrap_or(RubyValue::Nil),
        RubyValue::Class(cid) => crate::civars::class_ivar_get(cid.0, &name),
        _ => RubyValue::Nil,
    })
}

/// `Object#instance_variable_set(:@x, v)` -- writes the named ivar (of an
/// object or a class object), answering the value. A no-op on a
/// non-Object, non-Class receiver with no slot for the name. Carries
/// CRuby's `rb_check_frozen` (a frozen receiver raises before writing --
/// the same guard `ivar_set_dyn` and the static write path emit).
pub fn instance_variable_set(
    recv: &RubyValue,
    name_arg: &RubyValue,
    v: RubyValue,
) -> Result<RubyValue, Signal> {
    let name = ivar_name_arg(name_arg)?;
    match recv {
        RubyValue::Object(o) => {
            crate::builtins::check_frozen(recv)?;
            o.ivar_set_named(&name, v.clone());
        }
        RubyValue::Class(cid) => crate::civars::class_ivar_set(cid.0, &name, v.clone())?,
        // A frozen builtin (immediates always; a frozen Str/Array/Hash)
        // raises like CRuby; an UNFROZEN builtin keeps the documented
        // no-generic-ivar-storage no-op.
        other if other.is_frozen() => crate::builtins::check_frozen(other)?,
        _ => {}
    }
    Ok(v)
}

/// `Object#remove_instance_variable(:@x)` -- removes the named ivar and
/// answers its former value, raising `NameError` if the object has no such
/// ivar. A frozen object raises `FrozenError` first (CRuby's order).
pub fn remove_instance_variable(
    recv: &RubyValue,
    name_arg: &RubyValue,
) -> Result<RubyValue, Signal> {
    let name = ivar_name_arg(name_arg)?;
    match recv {
        RubyValue::Object(o) => {
            crate::builtins::check_frozen(recv)?;
            match o.ivar_remove_named(&name) {
                Some(v) => Ok(v),
                None => Err(name_error!("instance variable @{name} not defined")),
            }
        }
        _ => Err(name_error!("instance variable @{name} not defined")),
    }
}

/// `Object#instance_variables` -- the receiver's ivar names as `:@name`
/// symbols in declaration order (empty for a builtin/immediate).
/// Whether `recv` has instance variable `@{bare_name}` actually set -- backs
/// `defined?(@iv)`, which answers `"instance-variable"` only for an assigned
/// ivar and `nil` otherwise. `bare_name` is the name without the leading `@`.
pub fn ivar_defined(recv: &RubyValue, bare_name: &str) -> bool {
    let want = Symbol::intern(&format!("@{bare_name}"));
    let RubyValue::Array(vars) = instance_variables(recv) else {
        return false;
    };

    vars.lock()
        .iter()
        .any(|v| matches!(v, RubyValue::Symbol(s) if *s == want))
}

pub fn instance_variables(recv: &RubyValue) -> RubyValue {
    let names: Vec<RubyValue> = match recv {
        // `ivar_pairs` already yields `@`-prefixed names (it backs the
        // default `Object#inspect`); `class_ivar_names` yields bare ones.
        RubyValue::Object(o) => o
            .ivar_pairs()
            .into_iter()
            .map(|(n, _)| RubyValue::Symbol(Symbol::intern(&n)))
            .collect(),
        RubyValue::Class(cid) => crate::civars::class_ivar_names(cid.0)
            .into_iter()
            .map(|n| RubyValue::Symbol(Symbol::intern(&format!("@{n}"))))
            .collect(),
        _ => Vec::new(),
    };
    RubyValue::Array(crate::array_new(names))
}

/// `recv.respond_to?(:name)` -- MRO-faithful: walks the
/// receiver's real ancestor chain probing, per ancestor, the registry
/// (materialized user methods live flat on the OWN class -- the first
/// ancestor -- and builtin reopens hang off whichever ancestor was
/// reopened), the builtin method tables, and the Enumerable/Comparable
/// name sets. Kernel PRIVATE functions (`puts`, ...) are deliberately
/// invisible, real Ruby's rule. Doesn't consult
/// `method_missing`/`respond_to_missing?`, which this runtime doesn't model.
/// `respond_to?`'s answer: does `recv_class` (or any ancestor) provide
/// `name`? `include_all` is the method's own second parameter -- false (the
/// default) skips PRIVATE methods, exactly as in CRuby.
/// `respond_to?` on a VALUE receiver -- like `responds_to` but also honors a
/// per-object singleton method, which is keyed by object identity and
/// so invisible to the class-id-only `responds_to`. Codegen's `respond_to?`
/// fast path routes here so a `def obj.foo` singleton answers `true`.
pub fn responds_to_value(recv: &RubyValue, name: Symbol, include_all: bool) -> bool {
    if crate::runtime_meta::is_live()
        && crate::runtime_meta::object_has_singleton_method(recv, name)
    {
        return true;
    }
    // A class/module receiver also responds to its class methods -- a user
    // `def self.x`, a `module_function`, or a `class << self` accessor (stored
    // as class methods), plus a builtin class-method table (`File.read`) -- none
    // of which the instance-method MRO walk over Class/Module below can see.
    // Mirrors the class-receiver dispatch order in `send_value_in`.
    if let RubyValue::Class(cid) = recv {
        if class_receiver_responds(*cid, name) {
            return true;
        }
    }
    responds_to(recv.class_id(), name, include_all)
}

/// `respond_to?`'s FULL protocol (CRuby's `rb_obj_respond_to`): the plain
/// value-aware walk, then -- on a miss -- the receiver's USER-DEFINED
/// `respond_to_missing?(name, include_all)` hook (never the builtin
/// default row, which only exists for an override's `super` to reach).
/// Fallible because the hook is user code whose raise must propagate.
/// Wired at the `respond_to?` surfaces (codegen's two folds + the Kernel
/// row); internal duck-type probes (convert protocol, `Array#zip`'s
/// `:each` check, ...) keep the plain bool walk -- CRuby's own internal
/// probes are a mix, and the hook firing there is not oracle-pinned.
pub fn responds_to_or_missing(
    recv: &RubyValue,
    name: Symbol,
    include_all: bool,
) -> Result<bool, Signal> {
    if responds_to_value(recv, name, include_all) {
        return Ok(true);
    }
    let rtm = Symbol::intern("respond_to_missing?");
    let args = [RubyValue::Symbol(name), RubyValue::Bool(include_all)];
    let id = recv.class_id();
    if let RubyValue::Object(o) = recv {
        if crate::runtime_meta::is_live() {
            if let Some(m) = crate::runtime_meta::resolve_dynamic(o, id, rtm) {
                return Ok(m.call(o, &args, None)?.truthy());
            }
        }
        if let Some(f) = registry().lookup_mro(id, rtm) {
            return Ok(f.call(o, &args, None)?.truthy());
        }
    } else {
        // A builtin-value receiver's hook can only come from a reopen
        // (`class Integer; def respond_to_missing?...`) -- the value-method
        // probe per ancestor.
        for &anc in ancestors_of_value(id) {
            if let Some(f) = value_method(anc, 0, rtm) {
                return Ok(f(recv, &args, None)?.truthy());
            }
        }
    }
    Ok(false)
}

/// CRuby's `rb_obj_dig` (object.c): recurse `cur.dig(rest)` after a container's
/// own first-level lookup. A nil short-circuits to nil; an intermediate that
/// doesn't respond to `dig` raises TypeError -- which is why
/// `[1,[2]].dig(1,0,3)` raises (the `2` Integer has no `#dig`) instead of
/// silently indexing an Integer's bits through `[]`. Callers (`Array#dig`,
/// `Hash#dig`) perform their own first index, then hand the remaining keys here.
pub(crate) fn obj_dig(cur: RubyValue, rest: &[RubyValue]) -> Result<RubyValue, Signal> {
    if cur.is_nil() {
        return Ok(RubyValue::Nil);
    }
    let dig = Symbol::intern("dig");
    if !responds_to_value(&cur, dig, false) {
        return Err(type_error!(
            "{} does not have #dig method",
            crate::class_name_of_value(&cur)
        ));
    }
    send_value(&cur, dig, rest, None)
}

/// Whether a class/module VALUE responds to `name` via a class-method source
/// (runtime singleton overlay, registered `def self.x`/`module_function`/
/// `class << self` methods, a builtin class-method table, or a native struct
/// class's own methods) -- the reflection counterpart of `send_value_in`'s
/// `RubyValue::Class` dispatch probes.
fn class_receiver_responds(cid: ClassId, name: Symbol) -> bool {
    if crate::runtime_meta::is_live()
        && crate::runtime_meta::overlay_class_method(cid, name).is_some()
    {
        return true;
    }
    if REGISTRY
        .get()
        .and_then(|r| r.entries.get(&cid.0))
        .is_some_and(|e| e.class_methods.contains_key(&name))
    {
        return true;
    }
    let n = name.name();
    let n = n.as_str();
    if crate::builtins::class_method_table(cid).is_some_and(|lookup| lookup(n).is_some()) {
        return true;
    }
    crate::builtins::rstruct::is_struct_class(cid)
        && crate::builtins::rstruct::class_lookup(n).is_some()
}

/// Whether `cid` has an OWN class method `name` -- a `def self.x` materialized
/// into the registry, or a runtime singleton def -- as opposed to one merely
/// inherited from `Class`/`Module`. `extend` consults this so a receiver's own
/// singleton methods keep outranking a mixed-in module's copy (CRuby's "closest
/// singleton" rule); the inherited builtin `Class`/`Module` methods deliberately
/// don't count, because an extended module SHOULD override those.
pub fn class_defines_own_class_method(cid: ClassId, name: Symbol) -> bool {
    (crate::runtime_meta::is_live()
        && crate::runtime_meta::overlay_class_method(cid, name).is_some())
        || REGISTRY
            .get()
            .and_then(|r| r.entries.get(&cid.0))
            .is_some_and(|e| e.class_methods.contains_key(&name))
}

/// The class in `cid`'s ancestry whose `def self.<name>` a `cid.<name>` call
/// reaches -- `Method#owner` for a class-method lookup, and what tells a class
/// receiver's `method(:x)` that it found a class method rather than an
/// instance method of `Class`/`Module`. `None` when nothing up the chain
/// defines one.
pub fn class_method_owner(cid: ClassId, name: Symbol) -> Option<ClassId> {
    scan_class_method_owner(cid, 0, name)
}

/// [`class_method_owner`]'s `#super_method` companion: the next definer
/// strictly after `after`.
pub fn class_method_owner_after(
    cid: ClassId,
    after: ClassId,
    name: Symbol,
) -> Option<ClassId> {
    let at = ancestors_of_value(cid).iter().position(|&a| a == after)?;
    scan_class_method_owner(cid, at + 1, name)
}

/// The shared scan. Wider than [`class_defines_own_class_method`], which
/// deliberately ignores a builtin's own `def self.x` rows so an `extend`ed
/// module can override them -- reflection has no such stake and must report
/// `Array.method(:try_convert).owner` too.
fn scan_class_method_owner(cid: ClassId, skip: usize, name: Symbol) -> Option<ClassId> {
    let n = name.name();
    ancestors_of_value(cid).iter().skip(skip).copied().find(|&anc| {
        (crate::runtime_meta::is_live()
            && crate::runtime_meta::overlay_class_method(anc, name).is_some())
            || REGISTRY
                .get()
                .and_then(|r| r.entries.get(&anc.0))
                .is_some_and(|e| e.own_class_methods.contains(&name))
            || crate::builtins::class_method_table(anc).is_some_and(|lookup| lookup(&n).is_some())
    })
}

/// `Module#method_defined?` -- true when `name` resolves to a public OR
/// protected instance method of `recv_class` (private and nonexistent answer
/// false). Unlike `respond_to?`'s default, protected counts. `instance_method_
/// visibility` supplies the private/public/protected verdict for a registered
/// method; a builtin/Enumerable method (never private) has no registry entry,
/// so its `None` verdict is correctly treated as "not private".
pub fn method_defined(recv_class: ClassId, name: Symbol) -> bool {
    responds_to(recv_class, name, true)
        && instance_method_visibility(recv_class, name) != Some(MethodVisibility::Private)
}

/// `Module#method_defined?(name, inherit)` -- with `inherit` false the lookup is
/// restricted to methods `recv_class` defines DIRECTLY (its own `def`s and attr
/// accessors), skipping the ancestor walk. A private own method still answers
/// false, matching the inherit-true contract.
pub fn method_defined_inherit(recv_class: ClassId, name: Symbol, inherit: bool) -> bool {
    if inherit {
        return method_defined(recv_class, name);
    }
    let Some(r) = REGISTRY.get() else {
        return false;
    };
    r.defines_own(recv_class, name)
        && r.own_method_visibility(recv_class, name) != Some(MethodVisibility::Private)
}

pub fn responds_to(recv_class: ClassId, name: Symbol, include_all: bool) -> bool {
    let n = name.name();
    let n = n.as_str();
    let overlay_live = crate::runtime_meta::is_live();
    for &anc in ancestors_of_value(recv_class) {
        // A method defined at runtime (`define_method`, a runtime class's
        // own method) answers `respond_to?` on every ancestor it lands on.
        // An explicit runtime visibility mark (`class_eval { private :m }`)
        // is checked first: it can target a frozen-registry or builtin
        // method the overlay carries no body for, and only ever exists for
        // a name that resolved when the mark was made -- so it is
        // authoritative for both existence and visibility.
        if overlay_live {
            if crate::runtime_meta::overlay_is_undefined(anc, name) {
                return false;
            }
            if let Some(v) = crate::runtime_meta::overlay_method_visibility(anc, name) {
                return include_all || v == MethodVisibility::Public;
            }
            if crate::runtime_meta::overlay_has_instance_method(anc, name) {
                return true;
            }
        }
        if let Some(r) = REGISTRY.get() {
            // `undef` TERMINATES the walk at the class that wrote it --
            // an ancestor's still-live definition must not answer for a
            // descendant that undef'd the name.
            if r.is_undefined(anc, name) {
                return false;
            }
            if r.lookup(anc, name).is_some() || r.lookup_value_method(anc, 0, name).is_some() {
                // This is the NEAREST ancestor defining `name` (materialization
                // flattens the resolved method, with its effective visibility,
                // onto the receiver's own class), so its visibility is
                // authoritative -- a private/protected redefinition here shadows
                // a public copy farther up the chain (CRuby's nearest-wins rule).
                if !include_all && (r.is_private(anc, name) || r.is_protected(anc, name)) {
                    return false;
                }
                return true;
            }
        }
        if let Some(table) = crate::builtins::class_table(anc) {
            if table(n).is_some() {
                // Hidden builtin privates (Kernel's print family,
                // BasicObject's `initialize`) are reachable via
                // implicit self / `send` / `super` -- all through the
                // table -- but `respond_to?`'s default ignores privates,
                // so they answer false unless `include_all`.
                if !include_all && is_hidden_builtin_private(n) {
                    continue;
                }
                return true;
            }
        }
    }
    // A builtin-alias row answers through its SOURCE name -- which also
    // carries the source's visibility (a Ruby alias copies it): `dup!` for
    // `dup` answers true, `raise!` for the hidden-private `raise` answers
    // false unless `include_all`. See `alias_target`.
    if let Some(old) = alias_target(recv_class, name) {
        return responds_to(recv_class, old, include_all);
    }
    false
}

/// The class or module that actually defines `name` for an instance of
/// `recv_class` -- the first ancestor in the MRO carrying a definition.
/// Backs `Method#owner`/`UnboundMethod#owner`. Reflection sees privates, so
/// this is the `include_all` walk. `None` when nothing in the chain defines
/// it (callers construct the method only after a `responds_to` check, so this
/// is the belt-and-suspenders arm).
pub fn method_owner(recv_class: ClassId, name: Symbol) -> Option<ClassId> {
    scan_owner(recv_class, 0, name)
}

/// The next class up that defines `name` -- the one strictly AFTER `after` in
/// `recv_class`'s MRO. Backs `Method#super_method`: `nil` once the chain runs
/// out, and `nil` too for an `after` that isn't in this chain at all.
pub fn method_owner_after(recv_class: ClassId, after: ClassId, name: Symbol) -> Option<ClassId> {
    let at = ancestors_of_value(recv_class)
        .iter()
        .position(|&a| a == after)?;
    scan_owner(recv_class, at + 1, name)
}

/// The shared MRO scan: the first ancestor from `skip` positions in that
/// carries a definition of `name` itself.
fn scan_owner(recv_class: ClassId, skip: usize, name: Symbol) -> Option<ClassId> {
    let n = name.name();
    let n = n.as_str();
    let overlay_live = crate::runtime_meta::is_live();
    for &anc in ancestors_of_value(recv_class).iter().skip(skip) {
        if overlay_live {
            if crate::runtime_meta::overlay_is_undefined(anc, name) {
                return None;
            }
            if crate::runtime_meta::overlay_has_instance_method(anc, name) {
                return Some(anc);
            }
        }
        if let Some(r) = REGISTRY.get() {
            if r.is_undefined(anc, name) {
                return None;
            }
            // `defines_own`, not `lookup`: materialization flattens an inherited
            // method onto every descendant's table, so only the direct-def set
            // pins down where it actually originated.
            if r.defines_own(anc, name) {
                return Some(anc);
            }
        }
        if let Some(table) = crate::builtins::class_table(anc) {
            if table(n).is_some() {
                return Some(anc);
            }
        }
    }
    None
}

/// The ancestor chain the MRO walk runs over: the registry's (richer --
/// user classes, and reopens may have `include`d user modules into a
/// builtin) when installed and populated for `id`, else the ABI-derived
/// fallback chain (this crate's own unit tests; identical for builtins by
/// construction -- both derive from `zeo_abi::BUILTINS`).
pub(crate) fn ancestors_of_value(id: ClassId) -> &'static [ClassId] {
    // `REGISTRY` is a `static OnceLock`, so `get()` hands out `&'static`
    // borrows directly -- no lifetime gymnastics needed.
    if let Some(r) = REGISTRY.get() {
        let chain = r.ancestors_of(id);
        if !chain.is_empty() {
            return chain;
        }
    }
    // A class BORN AT RUNTIME (`Class.new`) has no frozen entry; its linearized
    // chain lives (leaked to `&'static`) in the overlay.
    if crate::runtime_meta::is_live() {
        if let Some(chain) = crate::runtime_meta::overlay_ancestors(id) {
            return chain;
        }
    }
    crate::builtins::fallback_ancestors(id)
}

/// The resolved visibility of a single method (`private`/`protected`/public).
#[derive(Clone, Copy, PartialEq, Eq)]
pub enum MethodVisibility {
    Public,
    Private,
    Protected,
}

/// A reflection filter over method visibility -- what each `*_instance_methods`
/// / `*_method_defined?` query keeps. `instance_methods` and `Object#methods`
/// keep public+protected (`NotPrivate`); the prefixed forms match exactly one
/// visibility.
#[derive(Clone, Copy, PartialEq, Eq)]
pub enum VisFilter {
    NotPrivate,
    Public,
    Protected,
    Private,
}

impl VisFilter {
    fn matches(self, v: MethodVisibility) -> bool {
        match self {
            VisFilter::NotPrivate => v != MethodVisibility::Private,
            VisFilter::Public => v == MethodVisibility::Public,
            VisFilter::Protected => v == MethodVisibility::Protected,
            VisFilter::Private => v == MethodVisibility::Private,
        }
    }
}

/// Builtin-table methods that CRuby defines as PRIVATE, so they are reachable
/// via implicit self / `send` / `super` (all of which go through the table)
/// but are invisible to `respond_to?` and raise `NoMethodError: private
/// method` on an explicit-receiver call. The table itself carries no
/// visibility metadata, so this is the one place the runtime knows.
///
/// `initialize` (`BasicObject`'s, `object.c`'s `rb_obj_dummy`) is the load-
/// bearing case: `super` from any `initialize` must reach it, but
/// `obj.initialize` must raise. Kernel's print family is the same shape.
fn is_hidden_builtin_private(name: &str) -> bool {
    matches!(
        name,
        "initialize"
            | "puts"
            | "print"
            | "p"
            | "pp"
            | "warn"
            | "system"
            | "`"
            | "raise"
            | "fail"
            | "method_missing"
            | "respond_to_missing?"
    )
}

/// The instance-method names of `class` and -- when `inherit` -- its
/// ancestors, as interned Symbols in MRO order, deduped (a nearer class's
/// definition shadows a farther one). Combines the registry (user methods +
/// builtin reopens) with the builtin method tables and the
/// Enumerable/Comparable/Math name sets. `vis` selects public(+protected) or
/// private-only.
///
/// The builtin tables are a SUBSET of CRuby's (this runtime implements a
/// subset of each class's methods), so a builtin class's list won't equal
/// CRuby's exactly -- reflection callers assert membership, not equality. A
/// user class's own list (`inherit=false`) is exact.
pub fn instance_method_names(class: ClassId, filter: VisFilter, inherit: bool) -> Vec<Symbol> {
    let chain: Vec<ClassId> = if inherit {
        ancestors_of_value(class).to_vec()
    } else {
        vec![class]
    };
    let reg = REGISTRY.get();
    let mut seen = HashSet::new();
    let mut out = Vec::new();
    for anc in chain {
        // The overlay first, and it CLAIMS every name it has an opinion about
        // (`seen.insert` before the filter): a runtime `private :m` has to beat
        // the registry's compile-time public flag below, and an `undef_method`
        // tombstone has to keep an ancestor's definition off the list entirely.
        if crate::runtime_meta::is_live() {
            for (name, vis) in crate::runtime_meta::overlay_instance_method_names(anc) {
                if seen.insert(name) && vis.is_some_and(|v| filter.matches(v)) {
                    out.push(name);
                }
            }
        }
        if let Some(r) = reg {
            // `inherit=false` restricts the user-method set to this class's own
            // definitions (materialization otherwise flattens inherited in).
            for (name, vis) in r.own_instance_method_names(anc, !inherit) {
                if filter.matches(vis) && seen.insert(name) {
                    out.push(name);
                }
            }
        }
        // Builtin-table methods are all public; keep them only when the filter
        // admits public names.
        if filter.matches(MethodVisibility::Public) {
            for &n in crate::builtins::class_table_names(anc) {
                // Hidden builtin privates (Kernel's print family, BasicObject's
                // `initialize`) are reflection-invisible, exactly as in CRuby.
                if is_hidden_builtin_private(n) {
                    continue;
                }
                let sym = Symbol::intern(n);
                if seen.insert(sym) {
                    out.push(sym);
                }
            }
        }
        // A builtin alias is stored as a NAME INDIRECTION rather than a copied
        // entry (see `ClassInfo::builtin_aliases`), so nothing above lists it --
        // but `alias_method :gems, :specs` defines `gems` as far as Ruby is
        // concerned, and reflection has to say so. Aliases are public.
        if filter.matches(MethodVisibility::Public) {
            if let Some(r) = reg {
                for new in r.alias_names(anc) {
                    if seen.insert(new) {
                        out.push(new);
                    }
                }
            }
        }
    }
    out
}

/// The resolved visibility of instance method `name` on `class` (walking the
/// MRO, nearest definition winning), or `None` if `class` has no such instance
/// method. Backs `private_method_defined?`/`public_method_defined?`/
/// `protected_method_defined?`.
pub fn instance_method_visibility(class: ClassId, name: Symbol) -> Option<MethodVisibility> {
    let reg = REGISTRY.get()?;
    let name_str = name.name();
    for anc in ancestors_of_value(class) {
        // Runtime marks first: an explicit `class_eval { private :m }` (or an
        // alias's inherited visibility) on the nearest ancestor beats the
        // frozen registry's compile-time flags, and a runtime-defined method
        // with no mark is public.
        if crate::runtime_meta::is_live() {
            if crate::runtime_meta::overlay_is_undefined(*anc, name) {
                return None;
            }
            if let Some(vis) = crate::runtime_meta::overlay_method_visibility(*anc, name) {
                return Some(vis);
            }
            if crate::runtime_meta::overlay_has_instance_method(*anc, name) {
                return Some(MethodVisibility::Public);
            }
        }
        // A user/reopen definition on this ancestor carries its own visibility;
        // `undef` here terminates the search with "no such method".
        if reg.is_undefined(*anc, name) {
            return None;
        }
        if let Some(vis) = reg.own_method_visibility(*anc, name) {
            return Some(vis);
        }
        // A builtin-table method is public.
        if crate::builtins::class_table_names(*anc).contains(&name_str.as_str())
            && !is_hidden_builtin_private(&name_str)
        {
            return Some(MethodVisibility::Public);
        }
    }
    None
}

/// The CLASS-method (`def self.x` + builtin class-method) names of `class`,
/// deduped -- backs `SomeClass.singleton_methods` and the class-method half
/// of `SomeClass.methods`.
pub fn class_method_names(class: ClassId) -> Vec<Symbol> {
    let mut seen = HashSet::new();
    let mut out = Vec::new();
    // A class minted at runtime keeps its `def self.x`/`define_singleton_method`/
    // `module_function` methods in the overlay, never in the frozen registry.
    if crate::runtime_meta::is_live() {
        for name in crate::runtime_meta::overlay_class_method_names(class) {
            if seen.insert(name) {
                out.push(name);
            }
        }
    }
    if let Some(r) = REGISTRY.get() {
        for name in r.own_class_method_names(class) {
            if seen.insert(name) {
                out.push(name);
            }
        }
    }
    for &n in crate::builtins::class_method_table_names(class) {
        let sym = Symbol::intern(n);
        if seen.insert(sym) {
            out.push(sym);
        }
    }
    out
}

/// The registry's dynamic constructor for `id` (`Class#new`'s row) --
/// `None` for modules, builtins without allocators, or a missing registry.
pub(crate) fn constructor_of(id: ClassId) -> Option<ConstructorFn> {
    if let Some(c) = REGISTRY
        .get()
        .and_then(|r| r.entries.get(&id.0))
        .and_then(|e| e.constructor)
    {
        return Some(c);
    }
    // A runtime class (`Class.new`) registers its generic constructor in the
    // overlay, so `RuntimeClass.new` flows through the same `Class#new` ->
    // `construct_by_class_id` path frozen classes use.
    if crate::runtime_meta::is_live() {
        return crate::runtime_meta::overlay_constructor(id);
    }
    None
}

/// A fresh uninitialized instance of `id` (`Class#allocate`) -- a user class's
/// registered allocator, or a runtime (`Class.new`) class's name-keyed object.
/// `None` for modules/builtins (handled at the `allocate` call site).
pub(crate) fn allocate_of(id: ClassId) -> Option<RubyValue> {
    if let Some(v) = REGISTRY.get().and_then(|r| r.allocate_instance(id)) {
        return Some(v);
    }
    if crate::runtime_meta::is_live() {
        return crate::runtime_meta::runtime_allocate(id);
    }
    None
}

/// Construct an instance of the class with id `id`, running its `initialize`.
/// Codegen calls this at every raise/construct site for a BOOTSTRAP exception
/// class, since those classes have no generated Rust struct to name --
/// the native exceptions registered their `ConstructorFn` (see
/// `crate::builtins::exception`).
/// A missing constructor is a zeo bug (a bootstrap id with no registrar).
pub fn construct_by_class_id(
    id: ClassId,
    args: &[RubyValue],
    block: Option<RubyValue>,
) -> Result<RubyValue, Signal> {
    match constructor_of(id) {
        Some(ctor) => ctor(id, args, block),
        None => panic!("no constructor registered for class id {}", id.0),
    }
}

/// The `super` dispatch for an exception-backed receiver (D3): resume the MRO
/// walk in the RECEIVER's own ancestors at the entry AFTER `defining_class`
/// (the class whose body this `super` is lexically written in) and invoke the
/// first `name` registered there -- a native default or a user delta,
/// uniformly. This is the runtime counterpart of codegen's `emit_super_inline`
/// HIR splice, which CANNOT serve a `super` into a native exception method: an
/// exception's message lives in a hidden slot, independent of any `@message`
/// ivar, so the retained `Exception#initialize` HIR (a fictional `@message =
/// msg`) would set a visible ivar and leave the real message untouched. Walking
/// the registry -- where every exception id carries the native `exc_*` fns --
/// runs the true behavior instead. Also the exact shape the eval VM needs for
/// `super`, so it lands here rather than as a codegen special case.
pub fn send_super_from(
    recv: &RubyValue,
    defining_class: ClassId,
    name: Symbol,
    args: &[RubyValue],
    block: Option<RubyValue>,
) -> Result<RubyValue, Signal> {
    // Resume AFTER the class this `super` is written in; an unrecognized
    // `defining_class` (never expected) degrades to a full walk from the top.
    let ancestors = ancestors_of_value(recv.class_id());
    let start = ancestors
        .iter()
        .position(|&a| a == defining_class)
        .map_or(0, |p| p + 1);
    send_walking(recv, start, name, args, block)
}

/// Invoke `name` AS `owner` defines it, against `recv` -- what a `Method`
/// that `#super_method` re-seated calls, so
/// `Sub.new.method(:greet).super_method.call` runs `Base#greet` rather than
/// re-dispatching to the `Sub#greet` it was reached through.
///
/// It reads the same `own_impls` set a `super` walk does, and for the same
/// reason: a user class's materialized `methods` row downcasts `self` to that
/// class's own generated struct, so `Base`'s row cannot run against a `Sub`
/// instance. `own_impls` holds the receiver-generic bridge instead. Codegen
/// emits those bridges for every method name a `super` -- or a
/// `#super_method` anywhere in the program -- can reach.
pub fn send_as_defined_in(
    recv: &RubyValue,
    owner: ClassId,
    name: Symbol,
    args: &[RubyValue],
    block: Option<RubyValue>,
) -> Result<RubyValue, Signal> {
    if let RubyValue::Object(obj) = recv {
        if crate::runtime_meta::is_live() {
            if let Some(m) = crate::runtime_meta::overlay_own_method(owner, name) {
                return m.call(obj, args, block);
            }
        }
        if let Some(m) = registry().super_target(owner, name) {
            return m.call(obj, args, block);
        }
    }
    if let Some(f) = value_method(owner, 0, name) {
        return f(recv, args, block);
    }
    if let Some(f) = crate::builtins::class_table(owner).and_then(|t| t(&name.to_string())) {
        return f(recv, args, block);
    }
    // Nothing receiver-generic at the owner: fall back to ordinary dispatch
    // rather than raising, so the call still answers SOMETHING.
    send_value(recv, name, args, block)
}

/// The shared body of [`send_super_from`] and [`send_as_defined_in`]: walk
/// the receiver's ancestors from `start`, invoking the first OWN definition
/// of `name`. Only the entry position differs between them.
fn send_walking(
    recv: &RubyValue,
    start: usize,
    name: Symbol,
    args: &[RubyValue],
    block: Option<RubyValue>,
) -> Result<RubyValue, Signal> {
    // The two `MethodImpl` arms below take an `RObj`; a non-Object receiver
    // (an Integer, a String) never has one, and never reaches them either --
    // its definitions live in the value-method and builtin tables.
    let obj = match recv {
        RubyValue::Object(o) => Some(o.clone()),
        _ => None,
    };
    let ancestors = ancestors_of_value(recv.class_id());
    let method_name = name.to_string();
    for &anc in ancestors.iter().skip(start) {
        // Each position contributes its OWN definitions only -- never the
        // flattened `methods` table, whose winner at a position can be a
        // PREPENDED module's copy sitting BEFORE this position in the MRO
        // (probing it made a prepended method's `super` find itself,
        // recursing forever). Per position, most-derived source first:
        // a runtime-defined own method (the overlay), the registered own
        // implementation (`own_impls`), a user module's bridge / builtin
        // reopen (`value_methods` on that id), then the ancestor's native
        // builtin table (`BasicObject#initialize` is the one every `super`
        // chain bottoms out on).
        // An `undef_method` at this position terminates the walk, exactly as
        // it does for ordinary dispatch -- `super` must not reach past it into
        // a still-live ancestor definition.
        if crate::runtime_meta::is_live() && crate::runtime_meta::overlay_is_undefined(anc, name) {
            break;
        }
        if let Some(obj) = &obj {
            if crate::runtime_meta::is_live() {
                if let Some(m) = crate::runtime_meta::overlay_own_method(anc, name) {
                    return m.call(obj, args, block);
                }
            }
            if let Some(m) = registry().super_target(anc, name) {
                return m.call(obj, args, block);
            }
        }
        if let Some(f) = value_method(anc, 0, name) {
            return f(recv, args, block);
        }
        if let Some(f) = crate::builtins::class_table(anc).and_then(|t| t(&method_name)) {
            return f(recv, args, block);
        }
    }
    Err(raise_method_missing(
        recv,
        &method_name,
        args,
        MissingReason::Super,
    ))
}

/// `super` inside a CLASS method (`def self.x`) -- the class-method channel
/// `send_super_from` (object receivers only) can't serve. Walks the
/// receiver class's ancestry resuming AFTER `defining_class`, probing per
/// ancestor: a runtime-defined class method (overlay), the registered
/// flattened `class_methods` table (each ancestor's table is resolution
/// from ITS OWN viewpoint -- own `def self.x`, extends, and
/// inherited-from-above copies in the right priority, so the first
/// non-module ancestor's winner IS the correct super target), then that
/// ancestor's builtin class-method table. `include`d modules never join a
/// singleton chain, so module ancestors are skipped. A `defining_class`
/// missing from the chain (a `super` inside an `extend`ed module's method)
/// starts right past the receiver's own entry -- the nearest runtime
/// approximation of "after the extended module" (sibling extends of the
/// same receiver are not modeled at runtime; the registry records no
/// per-class extends list).
pub fn send_super_class_from(
    recv_class: ClassId,
    defining_class: ClassId,
    name: Symbol,
    args: &[RubyValue],
    block: Option<RubyValue>,
) -> Result<RubyValue, Signal> {
    let start = ancestors_of_value(recv_class)
        .iter()
        .position(|&a| a == defining_class)
        .map_or(1, |p| p + 1);
    send_class_walking(recv_class, start, name, args, block)
}

/// Invoke the CLASS method `name` starting the walk AT `from` -- the
/// class-method twin of [`send_from`], for a `Method` that `#super_method`
/// re-seated onto an ancestor's `def self.x`.
pub fn send_class_from(
    recv_class: ClassId,
    from: ClassId,
    name: Symbol,
    args: &[RubyValue],
    block: Option<RubyValue>,
) -> Result<RubyValue, Signal> {
    let start = ancestors_of_value(recv_class)
        .iter()
        .position(|&a| a == from)
        .unwrap_or(0);
    send_class_walking(recv_class, start, name, args, block)
}

/// The shared body of [`send_super_class_from`] and [`send_class_from`]:
/// walk `recv_class`'s ancestors from `start`, invoking the first own
/// `def self.<name>`. Only the entry position differs.
fn send_class_walking(
    recv_class: ClassId,
    start: usize,
    name: Symbol,
    args: &[RubyValue],
    block: Option<RubyValue>,
) -> Result<RubyValue, Signal> {
    let recv = RubyValue::Class(recv_class);
    let method_name = name.to_string();
    for &anc in ancestors_of_value(recv_class).iter().skip(start) {
        if registry().entries.get(&anc.0).is_some_and(|e| e.is_module) {
            continue;
        }
        if crate::runtime_meta::is_live() {
            if let Some(p) = crate::runtime_meta::overlay_class_method(anc, name) {
                return p.call_with_self_and_block(&recv, args, block);
            }
        }
        if let Some(f) = registry()
            .entries
            .get(&anc.0)
            .and_then(|e| e.class_methods.get(&name).copied())
        {
            return f(&recv, args, block);
        }
        if let Some(f) =
            crate::builtins::class_method_table(anc).and_then(|lookup| lookup(&method_name))
        {
            return f(&recv, args, block);
        }
    }
    // The singleton chain does not stop at the last ancestor: `#<Class:
    // BasicObject>` inherits from `Class` itself, so a class-method `super`
    // with nothing above it continues into `Class`'s own INSTANCE methods,
    // with the class object as `self`. That is where the default
    // allocate-then-`initialize` lives -- what a `def self.new` wrapping
    // construction reaches by `super` (rubygems'
    // `Gem::Package::TarWriter.new`). `send_walking` raises the same
    // `MissingReason::Super` if that comes up empty too.
    send_walking(&recv, 0, name, args, block)
}

/// Dispatch a `super` whose target the COMPILER resolved against the
/// receiver's singleton chain (the `extend M` shape -- sibling extends
/// interleave in an order only the compile-time chain knows; the runtime
/// registry records no per-class extends list). The target is either a
/// module's instance method serving as a class method (`module_instance`,
/// reached through the module's own value-method bridge) or an ancestor's
/// own `def self.x` (its registered `class_methods` row / builtin table).
/// `self` stays the RECEIVER class object throughout, like every `super`.
pub fn call_singleton_super_target(
    target: ClassId,
    module_instance: bool,
    recv_class: ClassId,
    name: Symbol,
    args: &[RubyValue],
    block: Option<RubyValue>,
) -> Result<RubyValue, Signal> {
    let recv = RubyValue::Class(recv_class);
    let method_name = name.to_string();
    if module_instance {
        // The RECEIVER's own emitted copy of the module's method first --
        // its `super` resolves the receiver's singleton chain, which the
        // module's generic bridge (emitted in the module's own context)
        // cannot. See `ClassEntry::singleton_super_targets`.
        if let Some(f) = registry()
            .entries
            .get(&recv_class.0)
            .and_then(|e| e.singleton_super_targets.get(&(target.0, name)).copied())
        {
            return f(&recv, args, block);
        }
        if let Some(f) = value_method(target, 0, name) {
            return f(&recv, args, block);
        }
    } else {
        if crate::runtime_meta::is_live() {
            if let Some(p) = crate::runtime_meta::overlay_class_method(target, name) {
                return p.call_with_self_and_block(&recv, args, block);
            }
        }
        if let Some(f) = registry()
            .entries
            .get(&target.0)
            .and_then(|e| e.class_methods.get(&name).copied())
        {
            return f(&recv, args, block);
        }
        if let Some(f) = crate::builtins::class_method_table(target).and_then(|t| t(&method_name)) {
            return f(&recv, args, block);
        }
    }
    Err(raise_method_missing(
        &recv,
        &method_name,
        args,
        MissingReason::Super,
    ))
}

/// Coerces a dynamic method-name value the way `send`/`__send__` do:
/// Symbol or String (real Ruby accepts both), anything else raising
/// CRuby's exact TypeError shape.
pub fn method_name_symbol(v: &RubyValue) -> Result<Symbol, Signal> {
    match v {
        RubyValue::Symbol(s) => Ok(*s),
        RubyValue::Str(s) => Ok(Symbol::intern(&s.lock().to_utf8_lossy())),
        other => Err(type_error!(
            "{} is not a symbol nor a string",
            other.inspect_string()
        )),
    }
}

/// `recv.send(name, ...)` / `#public_send` where the compiler could not prove
/// WHICH `send` the receiver's chain resolves to.
///
/// CRuby has no `send` intrinsic: `send` is an ordinary method on `Kernel`,
/// so a class defining its own -- `BasicSocket#send` writing bytes,
/// `Ractor#send` passing a message, any `def send` of your own -- simply wins
/// the lookup because it sits earlier in the MRO. Only when the lookup lands
/// on Kernel's does the first argument get reinterpreted as a method name.
/// This asks that question once, then does whichever of the two the answer
/// calls for.
///
/// `send_name` is the name as WRITTEN (`:send` or `:public_send`), which is
/// both what the MRO is asked about and what an ordinary call dispatches.
pub fn send_dispatch_in(
    box_id: u32,
    recv: &RubyValue,
    send_name: Symbol,
    args: &[RubyValue],
    block: Option<RubyValue>,
) -> Result<RubyValue, Signal> {
    let shadowed = !matches!(
        method_owner(recv.class_id(), send_name),
        Some(KERNEL_CLASS) | Some(BASIC_OBJECT_CLASS) | None
    );
    if shadowed {
        return send_value_in(box_id, recv, send_name, args, block);
    }
    let Some((target, rest)) = args.split_first() else {
        return Err(crate::builtins::arg_error!("no method name given"));
    };
    let target = method_name_symbol(target)?;
    if send_name == Symbol::intern("public_send") {
        send_value_public_in(box_id, recv, target, rest, block)
    } else {
        send_value_in(box_id, recv, target, rest, block)
    }
}

/// A registry-OPTIONAL probe for a builtin-reopen method --
/// `None` when no registry is installed (this crate's own unit tests) or
/// the class carries no such method. The lookup key is the receiver's own
/// `class_id()`; see `ValueMethodFn`'s docs for why no ancestor walk is
/// needed. Used by `send_value`'s override-first stage and by
/// `display_with`/`inspect_with`'s `to_s`/`inspect` probes in `value.rs`.
pub(crate) fn value_method(id: ClassId, box_id: u32, name: Symbol) -> Option<ValueMethodFn> {
    REGISTRY.get()?.lookup_value_method(id, box_id, name)
}

/// The frozen registry's own instance method for `id`, CLONED out (a `fn`
/// copy or an `Arc` bump). The runtime overlay (`runtime_meta`) uses this to
/// walk a runtime class's frozen ancestors -- a `RuntimeClass < SomeUserClass`
/// instance inherits `SomeUserClass`'s materialized methods, which live in the
/// frozen table and can't be reached by the overlay's own maps. `None` when no
/// registry is installed (this crate's unit tests) or the class has no such
/// method.
pub(crate) fn registry_lookup_cloned(id: ClassId, name: Symbol) -> Option<MethodImpl> {
    REGISTRY.get()?.lookup(id, name).cloned()
}

/// A module/class's OWN value-method (the `ValueMethodFn` shape builtin modules
/// -- `Comparable`/`Enumerable`/`Kernel` -- register their instance methods
/// as), wrapped as a `MethodImpl` so `Object#extend` can copy it into an
/// object's singleton table. `box_id` 0 (the unboxed method set).
pub(crate) fn registry_value_method_impl(id: ClassId, name: Symbol) -> Option<MethodImpl> {
    let f: ValueMethodFn = REGISTRY.get()?.lookup_value_method(id, 0, name)?;
    Some(MethodImpl::Dynamic(std::sync::Arc::new(
        move |recv: &RObj, args: &[RubyValue], block: Option<RubyValue>| {
            f(&RubyValue::Object(recv.clone()), args, block)
        },
    )))
}

/// The registered Ruby-visible (fully-qualified) name of `id` -- `None`
/// when the registry isn't installed yet or has no such entry (this
/// crate's own unit tests; a real generated program registers everything
/// before any statement runs). See `RubyValue::Class`'s display arms for
/// the fallback rendering.
pub fn class_name(id: ClassId) -> Option<String> {
    if let Some(name) = REGISTRY
        .get()
        .and_then(|r| r.entries.get(&id.0))
        .map(|e| e.name.clone())
    {
        return Some(name);
    }
    if crate::runtime_meta::is_live() {
        return crate::runtime_meta::overlay_class_name(id);
    }
    None
}

/// The ids of classes/modules an explicit `Foo.freeze` has frozen -- a
/// side registry keyed by class id (NOT a pointer-keyed table: ids are
/// minted once and never reused, so there is no ABA hazard), covering both
/// AOT-registered classes and `runtime_meta`'s overlay classes with one
/// mechanism. Empty in the overwhelmingly common no-`freeze` program: the
/// guard paths (cvar/civar writes, runtime method definition) pay one
/// short-held lock + hash probe only when actually reached.
static FROZEN_CLASSES: std::sync::LazyLock<parking_lot::Mutex<HashSet<u32>>> =
    std::sync::LazyLock::new(|| parking_lot::Mutex::new(HashSet::new()));

/// `Foo.frozen?`'s storage half -- see `FROZEN_CLASSES`.
pub fn class_frozen(id: ClassId) -> bool {
    FROZEN_CLASSES.lock().contains(&id.0)
}

/// The `FrozenError` every mutation of a frozen class/module raises --
/// CRuby's exact shape (`can't modify frozen Class: Foo` /
/// `can't modify frozen Module: Bar`, oracle-verified): the receiver's own
/// class kind, then the frozen class's name (its inspect).
pub fn frozen_class_error(id: ClassId) -> Signal {
    let kind = if class_is_module(id).unwrap_or(false) {
        "Module"
    } else {
        "Class"
    };
    let name = class_name(id).unwrap_or_else(|| format!("#<Class:{}>", id.0));
    frozen_error!("can't modify frozen {kind}: {name}")
}

/// `Foo.freeze`'s storage half -- see `FROZEN_CLASSES`. Repeat calls are
/// harmless no-ops (CRuby's already-frozen guard).
pub fn class_set_frozen(id: ClassId) {
    FROZEN_CLASSES.lock().insert(id.0);
}

/// Reverse of `class_name`: the id a fully-qualified class/module NAME is
/// registered under (`"Integer"`, `"Math"`, a user `"Widget"`), or `None`.
/// The eval VM uses this to resolve a bare class-name constant like
/// `eval("Integer")` -- codegen resolves those statically and so never
/// `const_set`s them, leaving the runtime constants table without them.
pub fn class_id_by_name(name: &str) -> Option<ClassId> {
    REGISTRY
        .get()
        .and_then(|r| r.by_name.get(name))
        .map(|&id| ClassId(id))
        // Runtime-defined classes (e.g. `Struct.new` assigned to a constant)
        // live in the overlay, not the frozen registry -- fall back so
        // `Marshal.load` resolves them by name too.
        .or_else(|| crate::runtime_meta::runtime_class_id_by_name(name))
}

/// Whether `id` names a MODULE (drives `Widget.class` -> `Class` vs
/// `Enumerable.class` -> `Module`) -- same graceful `None` as `class_name`.
pub fn class_is_module(id: ClassId) -> Option<bool> {
    if let Some(m) = REGISTRY
        .get()
        .and_then(|r| r.entries.get(&id.0))
        .map(|e| e.is_module)
    {
        return Some(m);
    }
    if crate::runtime_meta::is_live() {
        return crate::runtime_meta::overlay_is_module(id);
    }
    None
}

/// A registry probe-and-call for the runtime PROTOCOL dispatches (Phase
/// 16.2): user `==`/`<=>`/`to_s`/`inspect`/`hash` reached from deep inside
/// pure helpers (`rb_eq`, `display_with`, `hash_key`) that can't route
/// through `send` (whose `method_missing`/NoMethodError fallbacks must NOT
/// fire for a protocol probe). `None` = no such method (or no registry --
/// this crate's own unit tests), letting each caller apply its own
/// default; the method, when present, is the MATERIALIZED entry, so
/// inherited/mixed-in definitions resolve exactly like a real call.
pub(crate) fn call_user_method(
    recv: &RObj,
    name: &str,
    args: &[RubyValue],
) -> Option<Result<RubyValue, Signal>> {
    let id = recv.class_id();
    if let Some(f) = REGISTRY
        .get()
        .and_then(|r| r.lookup_mro(id, Symbol::intern(name)))
    {
        return Some(f.call(recv, args, None));
    }
    // A RUNTIME-defined method on the receiver's OWN class (a `define_method`
    // delta, or a native `Struct`/`Data` class's `inspect`/`to_s`/`hash`
    // forwarder) -- so `p`/interpolation honour it, not just `send`. THIS
    // class only, no ancestor walk (see the reentrancy note below).
    if crate::runtime_meta::is_live() {
        if let Some(m) = crate::runtime_meta::overlay_own_method(id, Symbol::intern(name)) {
            return Some(m.call(recv, args, None));
        }
    }
    // A RUNTIME-RESIDENT class (`Time`, `File`, ... -- plan P-B) is an
    // `Object(RObj)` with no registry entry, but it does have a builtin
    // table. Without this probe its own `to_s`/`inspect`/`hash` would be
    // invisible to every caller here -- stringifying a Time would answer
    // `#<Time>` rather than running `Time#to_s`.
    //
    // The receiver's OWN class only, deliberately NOT its ancestors: this is
    // called from `display_with`/`inspect_with`, and `Kernel`'s own `to_s`
    // row renders via `to_display_string` -- walking up to it would recurse
    // until the stack died (it did). The ancestor walk belongs to `send_in`,
    // which has no such reentrancy; what this needs is only "does THIS class
    // define the method itself".
    if let Some(f) = crate::builtins::class_table(id).and_then(|lookup| lookup(name)) {
        return Some(f(&RubyValue::Object(recv.clone()), args, None));
    }
    None
}

/// A registry-optional ancestry probe -- `false` when no
/// registry is installed (this crate's own unit tests), where `is_a`'s
/// hard `registry()` access would panic. Used by `rb_eq`'s Comparable
/// fallback, which must stay callable from anywhere.
pub(crate) fn ancestors_contain(id: ClassId, target: ClassId) -> bool {
    REGISTRY
        .get()
        .is_some_and(|r| r.ancestors_of(id).contains(&target))
}

/// Runs `initialize` on a freshly-constructed instance IF the class
/// defines one -- the shared tail of every `ConstructorFn` (`ruby_class!`'s
/// `__construct`). Deliberately a direct registry lookup, NOT `send`: a
/// class with no `initialize` must not trip the `method_missing` fallback.
/// With no `initialize`, arguments are rejected (real Ruby's
/// `Object#initialize` takes none) with a rescuable `ArgumentError`.
pub fn run_initialize(
    class: ClassId,
    recv: &RObj,
    args: &[RubyValue],
    block: Option<RubyValue>,
) -> Result<(), Signal> {
    if let Some(f) = registry().lookup_mro(class, Symbol::intern("initialize")) {
        f.call(recv, args, block)?;
        return Ok(());
    }
    // No user `initialize` at all, so the inherited `Object#initialize`
    // takes no arguments. A RAISE, not a panic (plan G1): real Ruby resolves
    // arity at runtime and the error is rescuable -- `rescue ArgumentError`
    // around a bad `.new` is a corpus idiom, and a panic is uncatchable.
    // Message shape oracle-verified: CRuby says "wrong number of arguments
    // (given 2, expected 0)" with no method name in it, and the backtrace's
    // innermost row is `'BasicObject#initialize'` at the caller's line.
    if !args.is_empty() {
        let __frame = crate::frames::synthetic_c_frame("BasicObject#initialize");
        return Err(arg_error!(
            "wrong number of arguments (given {}, expected 0)",
            args.len()
        ));
    }
    Ok(())
}

/// The class registry is installed exactly once, from generated `main()`,
/// before any `Thread`/`Ractor` spawns anything (Part 9) -- a `OnceLock`
/// (not a `thread_local!`, unlike before the Send+Sync migration) gives
/// lock-free reads forever after that single write, and is itself the
/// correct semantic choice regardless of concurrency: classes/methods are
/// genuinely process-wide-shared in real Ruby, not per-thread state.
static REGISTRY: OnceLock<ClassRegistry> = OnceLock::new();

fn registry() -> &'static ClassRegistry {
    REGISTRY
        .get()
        .expect("class registry not installed -- install_class_registry must run first")
}

/// Whether an instance method `name` is registered directly on class `id` (its
/// flat, materialized `methods` table) -- the value-subclass constructor uses
/// this to decide whether to run a user `initialize` or seed the payload from
/// the args directly.
pub fn has_instance_method(id: ClassId, name: Symbol) -> bool {
    registry().lookup(id, name).is_some()
}

/// Called once from generated `main()`, after every class's `__register` has
/// populated the registry passed in.
pub fn install_class_registry(registry: ClassRegistry) {
    REGISTRY
        .set(registry)
        .unwrap_or_else(|_| panic!("class registry installed twice"));
}

thread_local! {
    /// The method most recently entered via `send_in`/`send_value_in` -- the
    /// diagnostic breadcrumb `ZEO_ARITY_DEBUG` reads to name which method an
    /// "wrong number of arguments" error came from (the message CRuby, and so
    /// we, deliberately leave method-less). Set at dispatch entry, so at the
    /// point a builtin's `arity!` guard raises it still names that builtin.
    static CURRENT_METHOD: std::cell::Cell<Option<Symbol>> = const { std::cell::Cell::new(None) };
}

/// Record the method being dispatched (for `ZEO_ARITY_DEBUG`). Cheap enough
/// (a thread-local `Cell` set) to run unconditionally on every dispatch.
fn note_dispatch(name: Symbol) {
    CURRENT_METHOD.with(|c| c.set(Some(name)));
}

/// Under `ZEO_ARITY_DEBUG`, append ` [method: X]` to an arity error so the
/// conformance triage can attribute the otherwise method-less
/// "wrong number of arguments" pile. A no-op (and no env lookup on the common
/// path) unless the message is an arity error.
fn arity_debug_context(msg: String) -> String {
    if !msg.starts_with("wrong number of arguments")
        || std::env::var_os("ZEO_ARITY_DEBUG").is_none()
    {
        return msg;
    }
    match CURRENT_METHOD.with(|c| c.get()) {
        Some(sym) => format!("{msg} [method: {}]", sym.name().as_str()),
        None => msg,
    }
}

/// THE runtime raise channel: a rescuable `Signal::Raise` carrying a
/// `class_name` exception once the registry is installed (every generated
/// program), a loud panic otherwise (this crate's own unit tests, which run
/// registry-less). The registry constructs the object itself via the class's
/// registered `ConstructorFn` -- see `ClassRegistry::construct_exception`.
pub fn raise_error(class_name: &str, msg: String) -> Signal {
    let msg = arity_debug_context(msg);
    match REGISTRY.get() {
        Some(reg) => {
            let exc = reg.construct_exception(class_name, msg);
            crate::builtins::exception::attach_cause(&exc);
            crate::builtins::exception::attach_backtrace(&exc);
            Signal::Raise(exc)
        }
        None => panic!("{class_name}: {msg}"),
    }
}

/// [`raise_error`] plus typed introspection details stamped onto the freshly
/// built exception -- `KeyError#key`/`#receiver`, `NameError#name`/`#receiver`,
/// `NoMethodError#name`/`#args`/`#receiver`. The message is built the same way;
/// each `(slot, value)` is attached before cause chaining so the reader methods
/// see it.
pub fn raise_error_details(
    class_name: &str,
    msg: String,
    details: &[(&'static str, RubyValue)],
) -> Signal {
    let msg = arity_debug_context(msg);
    match REGISTRY.get() {
        Some(reg) => {
            let exc = reg.construct_exception(class_name, msg);
            for (slot, value) in details {
                crate::builtins::exception::set_exception_detail(&exc, slot, value.clone());
            }
            crate::builtins::exception::attach_cause(&exc);
            crate::builtins::exception::attach_backtrace(&exc);
            Signal::Raise(exc)
        }
        None => panic!("{class_name}: {msg}"),
    }
}

/// The `LocalJumpError` a `yield` with no block raises, carrying `#reason`
/// `:noreason` (CRuby's reason for a missing block). Shared by every
/// no-block-yield site so the accessor is populated uniformly.
pub fn raise_no_block_yield() -> Signal {
    raise_error_details(
        "LocalJumpError",
        "no block given (yield)".to_string(),
        &[("reason", RubyValue::Symbol(Symbol::intern("noreason")))],
    )
}

/// Build (do not raise) a `NameError` VALUE carrying the typed `#name` (a
/// Symbol) and `#receiver` an `uninitialized constant` reference exposes.
/// Codegen emits this for a const miss so the boxed error the branch raises or
/// stores answers `e.name`/`e.receiver`, matching CRuby. `receiver` is
/// `RubyValue::Nil` where the lexical scope isn't statically known (a bare
/// top-level reference), which reads back as `nil` -- the same as an unset slot.
pub fn make_name_error(message: String, name: &str, receiver: RubyValue) -> RubyValue {
    match REGISTRY.get() {
        Some(reg) => {
            let exc = reg.construct_exception("NameError", message);
            crate::builtins::exception::set_exception_detail(
                &exc,
                "name",
                RubyValue::Symbol(Symbol::intern(name)),
            );
            crate::builtins::exception::set_exception_detail(&exc, "receiver", receiver);
            exc
        }
        None => panic!("NameError: {message}"),
    }
}

/// Why a method lookup failed, mirroring CRuby's `method_missing_reason`
/// (`internal/vm.h:32`). CRuby routes every one of these through a SINGLE
/// raiser (`raise_method_missing`, `vm_eval.c:968`) that picks a format string
/// per reason, rather than growing a separate error site per failure mode --
/// so a `super` that finds nothing above its defining class and a
/// `public_send` aimed at a private method produce their messages from one
/// place, and stay in step by construction.
#[derive(Clone, Copy, PartialEq, Eq, Debug)]
pub enum MissingReason {
    /// No entry anywhere in the receiver's ancestry.
    NoEntry,
    /// Found, but private and reached with an explicit receiver
    /// (`obj.secret`, or any `public_send`).
    Private,
    /// Found, but protected and the CALLER's `self` isn't a kind of the
    /// method's owner -- a receiver-sensitive test, hence runtime-only.
    Protected,
    /// A bare identifier that resolved to neither a local nor a method.
    /// The one reason that raises `NameError` instead of `NoMethodError`.
    VCall,
    /// `super` found no definition above the defining class.
    Super,
}

impl MissingReason {
    /// The exception class and message template CRuby pairs with this reason
    /// (`vm_eval.c:985-1006`). `{name}` is the method, `{recv}` the
    /// [`describe_receiver`] rendering.
    fn format(self) -> (&'static str, &'static str) {
        match self {
            Self::NoEntry => ("NoMethodError", "undefined method '{name}' for {recv}"),
            Self::Private => ("NoMethodError", "private method '{name}' called for {recv}"),
            Self::Protected => (
                "NoMethodError",
                "protected method '{name}' called for {recv}",
            ),
            Self::VCall => (
                "NameError",
                "undefined local variable or method '{name}' for {recv}",
            ),
            Self::Super => (
                "NoMethodError",
                "super: no superclass method '{name}' for {recv}",
            ),
        }
    }
}

/// CRuby's receiver description for a method-missing message -- the
/// `"%3$s%4$s"` prefix+name pair built in `name_err_mesg_to_str`
/// (`error.c:2660`).
///
/// This deliberately NEVER calls `inspect` on the receiver. None of CRuby's
/// five default formats contains the receiver-inspect directive (`%2$s`), and
/// the formatter only computes one when the format actually asks for it
/// (`error.c:2641`). That is precisely what lets a `BasicObject` subclass --
/// whose blank slate has no `inspect` -- raise a `NoMethodError` describing
/// itself, instead of failing a second lookup while building the message for
/// the first.
pub fn describe_receiver(recv: &RubyValue) -> String {
    // Real Ruby names the class of an anonymous/unregistered receiver with
    // its id rather than raising while building an error message.
    let named = |id: ClassId| class_name(id).unwrap_or_else(|| format!("#<Class:{}>", id.0));
    match recv {
        // nil/true/false render bare -- no "an instance of" prefix.
        RubyValue::Nil => "nil".to_string(),
        RubyValue::Bool(b) => b.to_string(),
        // A class or module receiver gets its own shape ("for class Widget" /
        // "for module Helper"), oracle-verified.
        RubyValue::Class(cid) => {
            let kind = if class_is_module(*cid).unwrap_or(false) {
                "module"
            } else {
                "class"
            };
            format!("{kind} {}", named(*cid))
        }
        // The top-level `self` is rendered literally as `main`
        // (`error.c:2678`), not as `#<Object:0x...>`.
        RubyValue::Object(o) => match main_object() {
            RubyValue::Object(m) if Arc::ptr_eq(&m, o) => "main".to_string(),
            _ => format!("an instance of {}", named(o.class_id())),
        },
        // Every remaining variant maps to a builtin ClassId via the ABI table.
        _ => format!(
            "an instance of {}",
            zeo_abi::builtin_name(recv.class_id()).unwrap_or("Object")
        ),
    }
}

/// THE method-missing raise: CRuby's single `raise_method_missing`
/// (`vm_eval.c:968`), reason-selected message and all.
///
/// Every failed lookup -- a plain miss, a visibility rejection, a bare
/// identifier, a `super` with nothing above it -- ends here, so the five
/// message shapes cannot drift apart.
pub fn raise_method_missing(
    recv: &RubyValue,
    name: &str,
    args: &[RubyValue],
    reason: MissingReason,
) -> Signal {
    let (class_name, template) = reason.format();
    let msg = template
        .replace("{name}", name)
        .replace("{recv}", &describe_receiver(recv));
    // Populate the raised error's introspection slots (`NameError#name`/
    // `#receiver`, `NoMethodError#args`). A `VCall` (bare undefined identifier)
    // is a `NameError` with no call arguments; every other reason is a
    // `NoMethodError` whose `#args` is the failed call's argument list -- `[]`
    // for a zero-arg call, matching CRuby.
    let name_detail = ("name", RubyValue::Symbol(Symbol::intern(name)));
    let receiver_detail = ("receiver", recv.clone());
    match reason {
        MissingReason::VCall => {
            raise_error_details(class_name, msg, &[name_detail, receiver_detail])
        }
        _ => {
            let args_detail = ("args", RubyValue::Array(crate::array_new(args.to_vec())));
            raise_error_details(
                class_name,
                msg,
                &[name_detail, receiver_detail, args_detail],
            )
        }
    }
}

/// Thread the currently-handled exception (`$!`) into `exc`'s `cause` slot
/// (CRuby's automatic cause chaining) and return `exc` unchanged, for use at a
/// `raise` site: `Err(Signal::Raise(raise_with_cause(exc)))`. A no-op for a
/// bare re-raise or a non-exception operand (see `attach_cause`).
pub fn raise_with_cause(exc: RubyValue) -> RubyValue {
    crate::builtins::exception::attach_cause(&exc);
    crate::builtins::exception::attach_backtrace(&exc);
    exc
}

/// The backtrace stamp ALONE -- for codegen's internal error constructors
/// (`emit_boxed_new`), which run at their raise sites but must NOT chain a
/// cause (that is `raise`'s job, and an explicit `cause: nil` SUPPRESSES
/// chaining precisely by never calling `raise_with_cause`).
pub fn stamp_backtrace(exc: RubyValue) -> RubyValue {
    crate::builtins::exception::attach_backtrace(&exc);
    exc
}

/// Coerce a `raise <value>` operand to the exception value to raise:
/// an Exception object raises itself, a String becomes a `RuntimeError` with
/// that message, and anything else is CRuby's `TypeError: exception
/// class/object expected` -- instead of panicking when the raise machinery
/// later unwraps a non-Object. `Exception`'s id is fixed (`zeo-abi`), so
/// codegen need not bake it in.
pub fn coerce_raise_arg(value: RubyValue) -> RubyValue {
    let build = |class_name: &str, msg: String| match REGISTRY.get() {
        Some(reg) => reg.construct_exception(class_name, msg),
        None => panic!("{class_name}: {msg}"),
    };
    match &value {
        RubyValue::Object(o) if is_a(o.class_id(), zeo_abi::EXCEPTION_CLASS) => value,
        RubyValue::Str(s) => build("RuntimeError", s.lock().to_utf8_lossy().into_owned()),
        _ => build("TypeError", "exception class/object expected".to_string()),
    }
}

/// `raise <class-or-exception>, message` with a RUNTIME-computed first operand
/// (a variable/call zeo couldn't resolve to a literal class). Mirrors
/// `Kernel#raise`'s two-arg coercion: an Exception CLASS or INSTANCE becomes
/// `obj.exception(msg)` (running any custom `#exception`/`#initialize`), and
/// anything else is CRuby's `TypeError`. Returns the exception value to raise.
pub fn coerce_raise_arg_with_message(
    value: RubyValue,
    msg: RubyValue,
) -> Result<RubyValue, Signal> {
    let msg = std::slice::from_ref(&msg);
    let is_exc = match &value {
        RubyValue::Class(cid) => is_a(*cid, zeo_abi::EXCEPTION_CLASS),
        RubyValue::Object(o) => is_a(o.class_id(), zeo_abi::EXCEPTION_CLASS),
        _ => false,
    };
    if !is_exc {
        return Err(raise_error(
            "TypeError",
            "exception class/object expected".to_string(),
        ));
    }
    send_value(&value, Symbol::intern("exception"), msg, None)
}

/// The exhausted-iteration raise: a rescuable `StopIteration`
/// whose `result` is `result` (a fresh instance per raise -- CRuby rebuilds
/// one from `stop_exc` each time too). Constructs `StopIteration.new(msg)` via
/// the registry, then stamps the result through the exception class's own
/// `__set_result`. Loud panic registry-less (unit tests).
pub fn raise_stop_iteration(result: RubyValue) -> Signal {
    match REGISTRY.get() {
        Some(reg) => {
            let exc =
                reg.construct_exception("StopIteration", "iteration reached an end".to_string());
            send(
                &exc.as_object_unchecked(),
                Symbol::intern("__set_result"),
                std::slice::from_ref(&result),
                None,
            )
            .expect("StopIteration#__set_result can't signal");
            crate::builtins::exception::attach_cause(&exc);
            crate::builtins::exception::attach_backtrace(&exc);
            Signal::Raise(exc)
        }
        None => panic!("StopIteration: iteration reached an end"),
    }
}

/// The general dispatcher -- reached only on Path 2 (see module docs).
/// Since every reachable method (own, inherited, or mixed-in) is already
/// MATERIALIZED directly onto its receiver's own class at zeo compile
/// time (see the plan's Part 6 -- no cloning-with-shadow-names,
/// monomorphization instead), this is now a FLAT lookup on the receiver's
/// own class -- no ancestor walk needed here at all, only for `is_a`
/// (above), which real dispatch doesn't need.
///
/// `block` is threaded through to whichever `MethodFn` is actually found --
/// including the `method_missing` fallback, matching real Ruby's own
/// `method_missing(name, *args, &block)` protocol.
/// Dynamic dispatch against ANY `RubyValue` receiver (closing
/// the long-standing "Poly-dispatch gap"): an `Object` goes through `send`'s
/// registry exactly as before; a BUILT-IN receiver (Array/Hash/String/...)
/// dispatches against a curated method table over the existing collection
/// helpers -- what makes `@items << x`, `@hash[k] = v`, `ks.length` work on
/// ivars/params/any dynamically-typed value. Codegen's every Poly-receiver
/// fallback (ordinary calls, `send`/`public_send`, safe-nav, and the
/// runtime OPERATOR fallback's non-numeric case) routes here.
///
/// The table is deliberately curated, not exhaustive: entries exist for the
/// operations the static `try_collection_dispatch` fast path also supports
/// (extended as packages need them); anything else raises the same real,
/// rescuable `NoMethodError` an unknown Object method does -- with the
/// builtin class's REAL name in the message (better than `send`'s
/// documented class-id approximation, since builtin names are known here).
pub fn send_value(
    recv: &RubyValue,
    name: Symbol,
    args: &[RubyValue],
    block: Option<RubyValue>,
) -> Result<RubyValue, Signal> {
    send_value_in(0, recv, name, args, block)
}

/// A `def` in expression position (inside a block) installs on the block's
/// runtime "default definee": for a Class/Module `self` (a `class_eval` /
/// `Class.new` body) an ordinary instance method; for any other `self` (an
/// `instance_exec` on a plain object) a SINGLETON method on that object. Which
/// one only the runtime `self` decides, so codegen routes an instance `def`
/// here rather than committing to `define_method`.
pub fn define_in_default_definee(
    recv: &RubyValue,
    name: Symbol,
    body: RubyValue,
) -> Result<RubyValue, Signal> {
    let installer = if matches!(recv, RubyValue::Class(_)) {
        "define_method"
    } else {
        "define_singleton_method"
    };
    send_value(
        recv,
        Symbol::intern(installer),
        &[RubyValue::Symbol(name), body],
        None,
    )
}

/// `recv.class` for the codegen `.class` fast path on a dynamically-typed
/// receiver: normally the receiver's class value, but a Struct/Data instance
/// with a member literally named `class` (`Data.define(:class, :hash)`) has
/// that accessor shadow Kernel#class -- the fold that emits this can't see the
/// runtime-minted member, so the shadow is resolved here. Infallible (a member
/// read), so the fold stays a plain expression.
pub fn value_class(recv: &RubyValue) -> RubyValue {
    if let RubyValue::Object(o) = recv {
        if let Some(v) = crate::builtins::rstruct::member_value_named(o, "class") {
            return v;
        }
    }
    RubyValue::Class(recv.class_id())
}

/// The `old` name behind a builtin-alias row visible to instances of `id` --
/// closest ancestor wins, so a subclass resolves an alias its parent (or an
/// included module) declared. `None` for every ordinary name; consulted only
/// on the send MISS paths, so a real method of the same name always beats it.
/// See `ClassEntry::aliases`.
pub(crate) fn alias_target(id: ClassId, name: Symbol) -> Option<Symbol> {
    let r = REGISTRY.get()?;
    for &anc in ancestors_of_value(id) {
        if let Some(e) = r.entries.get(&anc.0) {
            if let Some(&old) = e.aliases.get(&name) {
                return Some(old);
            }
        }
    }
    None
}

/// Parse-special Kernel names with NO runtime dispatch row: statically-
/// resolved call sites compile them directly, so an alias of one is valid
/// even though no table can prove it. `validate_aliases` skips them.
pub(crate) const PARSE_SPECIAL_KERNEL: &[&str] = &[
    "block_given?",
    "iterator?",
    "__method__",
    "__callee__",
    "binding",
];

/// Validates every registered builtin-alias row (see `register_alias`) --
/// called once from generated `main`'s fallible closure, right after the
/// registry installs: an alias whose source resolves NOWHERE for instances
/// of its class is `NameError`, raised at program start exactly when real
/// Ruby raises it (the `alias_method` in the class body executing). Walked
/// in id order (superclasses precede subclasses) with sorted names, so the
/// first error is deterministic.
pub fn validate_aliases() -> Result<(), Signal> {
    let Some(r) = REGISTRY.get() else {
        return Ok(());
    };
    let mut ids: Vec<u32> = r.entries.keys().copied().collect();
    ids.sort_unstable();
    for id in ids {
        validate_class_aliases(ClassId(id))?;
    }
    Ok(())
}

/// One class's builtin-alias sources, checked where CRuby checks them: as that
/// class's BODY runs. A source can be created by the body itself -- bundler's
/// `Runtime` does `definition_method :specs` (a `define_method` wrapper) and
/// then `alias_method :gems, :specs` -- so a single sweep before any body has
/// run answers "undefined" for a method that is about to exist.
pub fn validate_class_aliases(id: ClassId) -> Result<(), Signal> {
    let Some(r) = REGISTRY.get() else {
        return Ok(());
    };
    let Some(entry) = r.entries.get(&id.0) else {
        return Ok(());
    };
    if entry.aliases.is_empty() {
        return Ok(());
    }
    let mut olds: Vec<Symbol> = entry.aliases.values().copied().collect();
    olds.sort_by_key(|s| s.name());
    olds.dedup();
    for old in olds {
        let n = old.name();
        let n = n.as_str();
        if PARSE_SPECIAL_KERNEL.contains(&n) {
            continue;
        }
        let resolves = ancestors_of_value(id).iter().any(|&anc| {
            r.lookup(anc, old).is_some()
                || r.lookup_value_method(anc, 0, old).is_some()
                || crate::builtins::class_table(anc).is_some_and(|t| t(n).is_some())
                || crate::runtime_meta::overlay_own_method(anc, old).is_some()
        });
        if !resolves {
            let kind = if entry.is_module { "module" } else { "class" };
            return Err(crate::builtins::name_error!(
                "undefined method '{n}' for {kind} '{}'",
                entry.name
            ));
        }
    }
    Ok(())
}

/// `send_value` with the CALLER's box -- the statically-known
/// defining box every codegen dynamic-dispatch site passes, the AOT
/// translation of CRuby's `cme->def->box` (no frame walk). Only the
/// per-ancestor value-method probe consumes it: a box's builtin patches
/// resolve from that box's code, root patches everywhere. This crate's own
/// internal callers (Enumerable driving `each`, Comparable driving `<=>`,
/// ...) go through the box-0 wrapper above -- builtins run in ROOT, which
/// is CRuby's own documented builtins-call-builtins leak, faithfully.
/// `public_send`'s dispatch: `send_value_in` plus the visibility gate.
///
/// CRuby implements `public_send` as an ordinary send carrying the
/// `CALL_PUBLIC` scope, and `rb_method_call_status` (`vm_eval.c:837`) then
/// rejects private AND protected targets. Protected is rejected
/// unconditionally here -- normally it is receiver-sensitive, allowed when the
/// CALLER's `self` is a kind of the method's owner, but `public_send` passes
/// `Qundef` as that self (`vm_eval.c:1230`), a sentinel nothing can ever be a
/// kind of. Hence the plain `!= Public` test: no relatedness relaxation
/// applies, which is what makes `public_send` stricter than a plain
/// explicit-receiver call.
///
/// This is a RUNTIME check by necessity, not by preference: visibility can be
/// changed after the fact (`private :foo`), and the method name reaching
/// `public_send` is frequently a runtime value.
pub fn send_value_public_in(
    box_id: u32,
    recv: &RubyValue,
    name: Symbol,
    args: &[RubyValue],
    block: Option<RubyValue>,
) -> Result<RubyValue, Signal> {
    let reason = match instance_method_visibility(recv.class_id(), name) {
        Some(MethodVisibility::Private) => Some(MissingReason::Private),
        Some(MethodVisibility::Protected) => Some(MissingReason::Protected),
        _ => None,
    };
    match reason {
        Some(reason) => Err(raise_method_missing(recv, &name.to_string(), args, reason)),
        None => send_value_in(box_id, recv, name, args, block),
    }
}

pub fn send_value_in(
    box_id: u32,
    recv: &RubyValue,
    name: Symbol,
    args: &[RubyValue],
    block: Option<RubyValue>,
) -> Result<RubyValue, Signal> {
    send_value_in_reason(box_id, recv, name, args, block, MissingReason::NoEntry)
}

/// A bareword VCALL (`foo` -- implicit self, no args, no parens, could have
/// been a local): a miss raises `NameError`, not `NoMethodError`, per Ruby.
/// Everything else (method_missing, alias re-dispatch) is identical to a
/// normal send; only the terminal "nothing matched" raise differs.
pub fn send_value_vcall_in(
    box_id: u32,
    recv: &RubyValue,
    name: Symbol,
) -> Result<RubyValue, Signal> {
    send_value_in_reason(box_id, recv, name, &[], None, MissingReason::VCall)
}

fn send_value_in_reason(
    box_id: u32,
    recv: &RubyValue,
    name: Symbol,
    args: &[RubyValue],
    block: Option<RubyValue>,
    reason: MissingReason,
) -> Result<RubyValue, Signal> {
    if let RubyValue::Object(o) = recv {
        return send_in_reason(box_id, o, name, args, block, reason);
    }
    // A singleton method installed directly on this VALUE (`def SOME_ARRAY.[]`)
    // is closer than anything its class offers, so it is probed first -- and,
    // like every other overlay probe, only once something was defined at
    // runtime, so the ordinary path is untouched.
    if crate::runtime_meta::is_live() {
        if let Some(m) = crate::runtime_meta::value_singleton_method(recv, name) {
            return m.call_with_self_and_block(recv, args, block);
        }
    }
    note_dispatch(name);
    let n = name.name();
    let n = n.as_str();
    // CLASS/MODULE-level methods (`File.read`, `Time.now`, `Math.sqrt`):
    // this runtime has no singleton-method tables, so a class value gets its
    // own table probed ahead of the walk. The walk itself describes INSTANCE
    // methods, and a `RubyValue::Class`'s own chain runs over Class/Module --
    // it would never reach File's or Math's rows.
    if let RubyValue::Class(cid) = recv {
        // A class/singleton method DEFINED AT RUNTIME
        // (`define_singleton_method` on a class, a runtime `def self.x`) wins
        // over both the frozen `def self.x` and the builtin `Class#new`/`#name`,
        // matching Ruby's "closest singleton" placement. Runs under the class
        // value itself. Only probed once something is defined at runtime.
        if crate::runtime_meta::is_live() {
            if let Some(p) = crate::runtime_meta::overlay_class_method(*cid, name) {
                // The caller's block must ride along: `def M.wrap; yield; end`
                // desugars to a method-body lambda whose `yield` reads the
                // block the METHOD was called with. Dropping it here made
                // `M.wrap { "hi" }` raise LocalJumpError.
                return p.call_with_self_and_block(recv, args, block);
            }
        }
        // A USER `def self.x` first -- ahead of the builtin table below, so
        // a class defining its own `self.name`/`self.new` overrides
        // `Class#name`/`Class#new` rather than being shadowed by them. Real
        // Ruby's placement rule: the singleton method is strictly closer
        // than the one inherited from Class/Module.
        if let Some(f) = REGISTRY
            .get()
            .and_then(|r| r.entries.get(&cid.0))
            .and_then(|e| e.class_methods.get(&name).copied())
        {
            return f(recv, args, block);
        }
        if let Some(lookup) = crate::builtins::class_method_table(*cid) {
            if let Some(f) = lookup(n) {
                return f(recv, args, block);
            }
        }
        // Class methods on a MINTED native struct/data class (`Point.members`,
        // `Point[1, 2]`): these hang off `STRUCT_CLASS`/`DATA_CLASS` but are NOT
        // reached by the MRO walk below (which runs over the class VALUE's own
        // ancestry -- Class/Module -- not the struct's). Gated on the receiver
        // actually being a struct class, so no other class is affected.
        if crate::builtins::rstruct::is_struct_class(*cid) {
            if let Some(f) = crate::builtins::rstruct::class_lookup(n) {
                return f(recv, args, block);
            }
        }
    }
    // THE MRO WALK -- the receiver's real ancestor chain, most
    // derived first. Per ancestor: user reopens (the value
    // methods) beat that ancestor's builtin table -- real Ruby's placement
    // rule (a `class Numeric; def foo` reopen is found on `5`, but a
    // builtin `Integer#foo` row would beat it). Everything -- including
    // the Kernel universals, BasicObject's `==`, and the
    // `Enumerable`/`Comparable` module tables (whose rows drive the
    // receiver's own `each`/`<=>`) -- is an ordinary `class_table` hit.
    for &anc in ancestors_of_value(recv.class_id()) {
        if let Some(f) = value_method(anc, box_id, name) {
            return f(recv, args, block);
        }
        // `Math`'s module functions reach here too when `Math` is mixed in
        // (`include Math` -> a private `sqrt(x)`), as an ordinary `class_table`
        // hit on its registered instance table -- no special arm needed.
        if let Some(table) = crate::builtins::class_table(anc) {
            if let Some(f) = table(n) {
                return f(recv, args, block);
            }
        }
    }
    // A builtin-alias row (`alias_method :dup!, :dup`): rewrite the name and
    // re-dispatch. Probed only after every real method missed -- a real
    // definition of the alias name always wins -- and rows are terminal, so
    // the re-entry can't loop. See `alias_target`.
    if let Some(old) = alias_target(recv.class_id(), name) {
        return send_value_in_reason(box_id, recv, old, args, block, reason);
    }
    // Every receiver shape -- class, module, immediate, object -- gets its
    // message from the one method-missing raiser, so the class/module form
    // ("for class Widget") and the instance form stay in step.
    Err(raise_method_missing(recv, &name.to_string(), args, reason))
}

pub fn send(
    recv: &RObj,
    name: Symbol,
    args: &[RubyValue],
    block: Option<RubyValue>,
) -> Result<RubyValue, Signal> {
    send_in(0, recv, name, args, block)
}

/// `send` with the caller's box -- see `send_value_in`'s docs.
pub fn send_in(
    box_id: u32,
    recv: &RObj,
    name: Symbol,
    args: &[RubyValue],
    block: Option<RubyValue>,
) -> Result<RubyValue, Signal> {
    send_in_reason(box_id, recv, name, args, block, MissingReason::NoEntry)
}

fn send_in_reason(
    box_id: u32,
    recv: &RObj,
    name: Symbol,
    args: &[RubyValue],
    block: Option<RubyValue>,
    reason: MissingReason,
) -> Result<RubyValue, Signal> {
    let id = recv.class_id();
    note_dispatch(name);
    // Runtime metaprogramming: a per-object singleton, a runtime
    // `define_method` override, or a runtime-class instance's own/inherited
    // methods -- probed first (Ruby: a runtime `define_method` REPLACES), but
    // only once anything has been defined at runtime (`is_live`), so the frozen
    // lock-free fast path below is untouched for all existing code.
    if crate::runtime_meta::is_live() {
        if let Some(m) = crate::runtime_meta::resolve_dynamic(recv, id, name) {
            return m.call(recv, args, block);
        }
    }
    // ENV's methods are probed by IDENTITY, not by class: `ENV.class` is
    // `Object` (real Ruby -- it is a lone singleton with Hash-shaped methods,
    // not a Hash). Its OWN explicitly-defined methods must be checked BEFORE
    // the registry, because several (`dup`/`clone`/`freeze`) OVERRIDE Kernel
    // universals that ENV's `Object` identity would otherwise match first --
    // `ENV.dup` must raise, not shallow-copy. The Hash-snapshot fallback for
    // ENV's read-only Enumerable surface stays AFTER the registry walk, so ENV
    // still inherits `object_id`/`equal?`/etc. from Object.
    let boxed = RubyValue::Object(recv.clone());
    let is_env = crate::builtins::env::is_env(&boxed);
    if is_env {
        if let Some(f) = crate::builtins::env::lookup(name.name().as_str()) {
            return f(&boxed, args, block);
        }
    }
    if let Some(f) = registry().lookup_mro(id, name) {
        return f.call(recv, args, block);
    }

    if is_env {
        // ENV's read-only Hash/Enumerable surface (`count`, `min`, `value?`,
        // `each_value`, `grep`, `lazy`, `tally`, ...) is served by dispatching
        // to a fresh Hash snapshot. Mutators are in `env::lookup` above (they
        // must write the real environment), so only non-mutating methods reach
        // here -- a snapshot answers them faithfully without a per-method stub.
        let snapshot = crate::builtins::env::snapshot();
        return send_value(&snapshot, name, args, block);
    }

    // The SAME MRO walk `send_value` runs, over a boxed
    // handle: Kernel's universals, BasicObject's `==`, and the
    // Enumerable/Comparable module tables all resolve as real ancestor
    // methods, so `method_missing` fires only AFTER them -- real Ruby finds
    // a real (module) method first, always.
    let n = name.name();
    let n = n.as_str();
    // Value-subclass payload bridge (D3): `class Stack < Array` carries a
    // `RubyValue::Array` payload; at its payload root the inherited builtin
    // method runs against that value, not the boxed object. `None` for every
    // ordinary object, so this costs one field read on the miss path.
    let payload = recv.builtin_payload();
    let payload_root = recv.builtin_root();
    for &anc in ancestors_of_value(id) {
        if let Some(f) = value_method(anc, box_id, name) {
            return f(&boxed, args, block);
        }
        // `include Math` reaches its module functions here as an ordinary
        // `class_table` hit on Math's registered instance table.
        if let Some(table) = crate::builtins::class_table(anc) {
            if let Some(f) = table(n) {
                // At the payload root, run against the wrapped value and
                // re-wrap a self-return (`push`/`<<`) back to the subclass.
                if payload_root == Some(anc) {
                    if let Some(ref p) = payload {
                        let result = f(p, args, block)?;
                        return Ok(crate::builtins::value_subclass::rewrap_self_return(
                            result, p, recv, n,
                        ));
                    }
                }
                return f(&boxed, args, block);
            }
        }
    }

    // A builtin-alias row (`alias_method :raise!, :raise`): rewrite the name
    // and re-dispatch -- after every real method (a real definition of the
    // alias name wins) and BEFORE `method_missing` (an alias is a real
    // method in Ruby). Rows are terminal, so the re-entry can't loop.
    if let Some(old) = alias_target(id, name) {
        return send_in_reason(box_id, recv, old, args, block, reason);
    }
    // method_missing fallback, with `name` prepended to args (mirrors
    // CRuby's own protocol) -- AFTER every real method, per real Ruby.
    let mm = Symbol::intern("method_missing");
    let mm_impl = crate::runtime_meta::is_live()
        .then(|| crate::runtime_meta::resolve_dynamic(recv, id, mm))
        .flatten()
        .or_else(|| registry().lookup(id, mm).cloned());
    if let Some(f) = mm_impl {
        let mut full_args = Vec::with_capacity(args.len() + 1);
        full_args.push(RubyValue::Symbol(name));
        full_args.extend_from_slice(args);
        return f.call(recv, &full_args, block);
    }

    // A real, catchable `NoMethodError` (replacing the original
    // eprintln-and-`process::exit(1)` shortcut): propagates like any other
    // raised exception -- rescuable at the call site, re-raised at a
    // Thread's `join`/`value` if uncaught there, and printed by the
    // top-level uncaught handler otherwise. Shares the one method-missing
    // raiser with every other failure mode.
    Err(raise_method_missing(
        &RubyValue::Object(recv.clone()),
        &name.to_string(),
        args,
        reason,
    ))
}

#[cfg(test)]
mod tests {
    use super::*;

    /// Both `MethodImpl` arms invoke through `call` with the same ABI -- the
    /// widening the eval VM depends on, verified without any registry.
    #[test]
    fn method_impl_static_and_dynamic_dispatch_through_call() {
        let recv: RObj = Arc::new(Object::default());

        fn stat(_: &RObj, _: &[RubyValue], _: Option<RubyValue>) -> Result<RubyValue, Signal> {
            Ok(RubyValue::Int(1))
        }
        let s = MethodImpl::from_fn(stat);
        assert!(matches!(s.call(&recv, &[], None), Ok(RubyValue::Int(1))));

        let d = MethodImpl::Dynamic(Arc::new(
            |_: &RObj, _: &[RubyValue], _: Option<RubyValue>| Ok(RubyValue::Int(2)),
        ));
        assert!(matches!(d.call(&recv, &[], None), Ok(RubyValue::Int(2))));
    }
}
