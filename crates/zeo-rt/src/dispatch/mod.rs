/// Identifies a Ruby class at runtime. This is the SHARED `zeo-abi` type --
/// the compiler bakes the same numbering into generated code from the same
/// source of truth, so there is nothing to keep in sync by hand.
pub use zeo_abi::ClassId;

/// Implemented (via `ruby_class!`) by every generated Ruby class, and by the
/// built-in `Object` root below. `Send + Sync` supertrait bounds:
/// satisfied automatically for every generated class once its own fields are
/// `parking_lot::Mutex`-wrapped, needing no manual `unsafe impl` anywhere.
pub trait RubyObject: Any + Send + Sync {
    fn class_id(&self) -> ClassId;

    /// Lets `send`'s dispatcher downcast an erased `RObj` back to its
    /// concrete type. No default body: a default `{ self }` here would be
    /// type-checked generically over an unsized `Self` (rustc checks default
    /// bodies once, not per-impl) and fail to coerce to `&dyn Any`. Each
    /// concrete impl provides the one-line body instead (`ruby_class!`
    /// generates it), where `Self` is always a concrete, sized type.
    fn as_any(&self) -> &dyn Any;

    /// The owned-handle counterpart to `as_any` -- needed because every
    /// generated method now takes `self: Arc<Self>` (not `&self`, see
    /// `ruby_class!`'s docs), so Path 2's dynamic trampolines need an
    /// `Arc<Concrete>`, not a `&Concrete`, to actually call one. `Arc<dyn Any
    /// + Send + Sync>` supports a real consuming `downcast::<T>()`; `Arc<dyn
    /// RubyObject>` doesn't (there's no such inherent method on an arbitrary
    /// trait object), so this is the bridge -- same "no default body"
    /// reasoning as `as_any` above.
    fn as_any_rc(self: Arc<Self>) -> Arc<dyn Any + Send + Sync>;

    /// `.frozen?` state -- backed by the `__frozen: AtomicBool`
    /// field `ruby_class!` generates on every class struct (the per-object
    /// counterpart of `collections::Freezable`'s flag). On the trait (not
    /// just inherent) so `freeze_value`/`is_frozen_value` can reach it
    /// through an erased `RObj` without downcasting. The frozen CHECK before
    /// an ivar write is emitted by codegen (`emit_ivar_write_stmt`'s guard),
    /// which alone can construct the `FrozenError` to raise.
    fn is_frozen(&self) -> bool;

    /// Marks this object frozen -- `.freeze`'s storage half; a repeat call
    /// is a harmless no-op, matching CRuby's own already-frozen guard.
    fn set_frozen(&self);

    /// A snapshot of every ivar's current value -- the runtime
    /// ivar ENUMERATION `Ractor`'s recursive shareability check and
    /// `make_shareable`'s deep-freeze traversal need. (Ractor sends still
    /// reject an unfrozen Object rather than deep-copying it -- see
    /// `ractor`'s module docs for that documented divergence.) Generated by
    /// `ruby_class!` from its own ivar list.
    fn ivar_values(&self) -> Vec<RubyValue>;

    /// Every ivar as an ordered `("@name", value)` pair -- what the default
    /// `Object#inspect` rendering and `instance_variables` reflection need,
    /// with names and values paired in ONE pass (so a name-keyed root
    /// `Object`'s map can't desync the two). Generated by `ruby_class!` in
    /// field-declaration order; the default is empty for the runtime's
    /// hand-written objects, which expose no Ruby-visible ivars.
    fn ivar_pairs(&self) -> Vec<(String, RubyValue)> {
        Vec::new()
    }

    /// Read one ivar BY NAME (without the `@`), for the paths where the
    /// receiver's concrete class isn't statically known and codegen
    /// therefore couldn't emit a direct field access: `instance_exec`'s
    /// rebound self, and the top-level `main` object. `None` means this
    /// class declares no such ivar -- distinct from `Some(Nil)`, which is a
    /// declared-but-unassigned one. Generated by `ruby_class!` from its own
    /// ivar list; the default keeps the trait total for the runtime's
    /// hand-written objects, which have no Ruby-visible ivars.
    ///
    /// An ivar the class never names statically (`obj.instance_exec {
    /// @brand_new = 1 }`, `instance_variable_set` with a novel name) lives in
    /// the generated struct's `__overflow` map -- `ruby_class!` routes both
    /// accessors through it after the typed fields miss, so the named path is
    /// total over declared AND invented ivars.
    fn ivar_get_named(&self, _name: &str) -> Option<RubyValue> {
        None
    }

    /// Write one ivar BY NAME -- `ivar_get_named`'s counterpart, same
    /// statically-unknown-receiver paths. Answers whether the write landed
    /// (generated classes always land it, via typed field or `__overflow`;
    /// only ivar-less hand-written runtime objects answer `false`).
    fn ivar_set_named(&self, _name: &str, _v: RubyValue) -> bool {
        false
    }

    /// Remove one ivar BY NAME (without the `@`) -- `Kernel#remove_instance_variable`'s
    /// storage half. `Some(old)` is the removed value; `None` means the object
    /// has no such ivar (the caller raises `NameError`). The default keeps the
    /// trait total for the runtime's hand-written objects. See the caveat in
    /// `ivar_get_named`'s TODO: a generated struct field always physically
    /// exists, so a declared-but-never-assigned field answers `Some(Nil)` where
    /// CRuby raises -- name-keyed objects (`Object`/`DynObject`) don't have this
    /// gap because their map genuinely lacks absent keys.
    fn ivar_remove_named(&self, _name: &str) -> Option<RubyValue> {
        None
    }

    /// A `Struct`/`Data` MEMBER by position, in declaration order.
    ///
    /// Members are real slots on the generated struct but are NOT instance
    /// variables: CRuby answers `nil` to `S.new(1).instance_variable_get(:@x)`
    /// and `[]` to `instance_variables`. Every by-name path above is therefore
    /// blind to them, and the native protocol (`to_a`, `[]`, `==`, `each`,
    /// `dig`, `Marshal`) reaches them here instead, by the index it already
    /// knows. `None`/`false` for an out-of-range index and for every ordinary
    /// class, which declares no members.
    fn hidden_ivar_get(&self, _i: usize) -> Option<RubyValue> {
        None
    }

    fn hidden_ivar_set(&self, _i: usize, _v: RubyValue) -> bool {
        false
    }

    /// Read one ivar BY SLOT, the index it occupies in this class's
    /// [`crate::IvarCell`].
    ///
    /// A body SHARED by a base class and its descendants (`codegen::share`)
    /// has a `RubyValue` receiver, so it cannot name a concrete struct to
    /// index -- but the slot number is still a compile-time constant, because
    /// `analyze::mro` lays every class's slots out parent-first. This pair is
    /// what lets such a body keep indexing instead of falling back to the
    /// name scan. Out-of-range answers `nil` rather than panicking, matching
    /// the named accessors' totality.
    fn ivar_slot_get(&self, _slot: usize) -> RubyValue {
        RubyValue::Nil
    }

    /// Write one ivar BY SLOT -- `ivar_slot_get`'s counterpart. The caller has
    /// already checked frozenness, exactly as the by-name path's own guard
    /// does at its call site.
    fn ivar_slot_set(&self, _slot: usize, _value: RubyValue) {}

    /// Move every ivar holding another OBJECT into `out`, leaving `nil` behind.
    ///
    /// Only [`crate::IvarCell`]'s release path calls this, and only on an
    /// object it is about to drop as the last reference: taking the links
    /// first is what lets a long chain be released iteratively instead of one
    /// stack frame per link. The default keeps the trait total for the
    /// runtime's own hand-written objects, which hold no user ivars.
    fn take_linked_ivars(&self, _out: &mut Vec<RubyValue>) {}

    /// `Kernel#dup`/`#clone`'s per-class shallow copy: a fresh
    /// instance of the same concrete struct with every ivar's CURRENT value
    /// cloned into it (a `RubyValue` clone is a handle clone, so nested
    /// objects are SHARED -- CRuby's own shallow rule). `copy_frozen` is
    /// the one `dup`-vs-`clone` difference: `clone` carries the receiver's
    /// frozen flag over, `dup` starts unfrozen. Generated by `ruby_class!`
    /// from its own ivar list (only the concrete impl knows the fields);
    /// `initialize_copy`/singleton-state carryover are documented
    /// scope-cuts. See `RubyValue::dup_value` for the non-Object kinds.
    fn dup_object(&self, copy_frozen: bool) -> RObj;

    /// The wrapped builtin value of a value-builtin SUBCLASS instance (D3):
    /// `class Stack < Array` stores a `RubyValue::Array` here, so inherited
    /// `Array` methods run against it (the `send_in` payload bridge). `None`
    /// for every ordinary object -- only `ValueSubclass` overrides these three.
    /// Returns a HANDLE clone (cheap `Arc` bump), never holding the internal
    /// lock across the re-entrant dispatch that follows.
    fn builtin_payload(&self) -> Option<RubyValue> {
        None
    }
    /// The root builtin whose methods this subclass inherits (`Array` for
    /// `Stack < Array`) -- the ancestor the payload bridge substitutes at.
    fn builtin_root(&self) -> Option<ClassId> {
        None
    }
    /// Re-seat the whole payload (a `super`/`replace`/`initialize` that rebuilds
    /// the collection). `false` for a non-value-subclass. The single write path.
    fn set_builtin_payload(&self, _v: RubyValue) -> bool {
        false
    }

    /// A `Ractor` move's poison: re-tag this instance's class word to
    /// `Ractor::MovedObject`, so `class_id()` -- and with it dispatch,
    /// `method_missing`, `===`, inspect -- REALLY answers the husk class.
    /// `true` when the concrete type could retag (an atomic class word);
    /// the default `false` leaves a hand-written builtin `RObj` usable
    /// after a move -- the safe direction, documented on
    /// `ractor::cross_graph`.
    fn retag_moved(&self) -> bool {
        false
    }
}

/// A handle to any live Ruby object, used wherever the concrete class isn't
/// statically known. The Rust trait object's vtable *is* the tag. Mutability
/// lives on individual ivar fields (see `ruby_class!`), not on this handle, so
/// no lock layer is needed here. `Arc` (not `Rc`): every concrete `RubyObject` impl is
/// `Send + Sync` (via the trait's own supertrait bounds above), so this type
/// itself is genuinely `Send + Sync` -- no `unsafe impl` needed.
pub type RObj = Arc<dyn RubyObject>;

/// The root of every class hierarchy. `ClassId(0)`, no superclass -- the
/// base case `ruby_class!`'s `$super` bottoms out at.
///
/// Unlike a generated class, its ivars live in a NAME-KEYED map rather than
/// struct fields: this is the type behind `main_object()`, and the top level's
/// `self` has no compile-time class whose ivar list codegen could have
/// materialized into fields. `@x` at the top level (or inside a block that
/// `instance_exec` later rebinds onto some other receiver) is resolved by
/// name at runtime, so a map is the honest representation.
#[derive(Default)]
pub struct Object {
    ivars: parking_lot::Mutex<std::collections::HashMap<String, RubyValue>>,
    /// `Object.new.freeze` sets this; `main` never does. A generic Object had
    /// no frozen slot at all before, so `freeze`/`frozen?`/`clone(freeze:)`
    /// silently no-op'd (issue_3033).
    frozen: std::sync::atomic::AtomicBool,
    /// A `Ractor` move's poison bit -- this type has no per-instance class
    /// word to retag, so `class_id()` consults the flag instead (cold type;
    /// generated classes carry an atomic class word and skip this).
    moved: std::sync::atomic::AtomicBool,
}

impl Object {
    pub const CLASS_ID: ClassId = ClassId(0);
}

/// The builtin `Enumerable` MODULE -- an ordinary
/// `class_table` row (`builtins::enumerable`'s generated `lookup`), reached
/// by the MRO walk for any receiver whose ancestors contain this id. Like
/// every id above, re-exported from the shared `zeo-abi` numbering.
pub use zeo_abi::ENUMERABLE_CLASS;
/// Fixed, well-known `ClassId`s for every built-in Ruby type this runtime
/// models as a `RubyValue` variant rather than a generated `ruby_class!`
/// struct -- numerically mirrored by `zeo::compiler::BUILTIN_CLASSES`
/// (same "two `ClassId` types, on purpose" convention as `Object::CLASS_ID`/
/// `compiler::OBJECT_CLASS`). Registered into the `ClassRegistry` once, from
/// generated `main()` (`codegen::mod`'s `builtin_registrations`), with the
/// SAME linearized `ancestors` every user class gets -- what makes
/// `5.is_a?(Integer)`/`"x".is_a?(Object)`-style checks against a built-in-
/// typed receiver work uniformly through the one general `is_a`/`send`
/// mechanism, and the prerequisite for eventually `include`ing a plain-Ruby
/// `Enumerable`/`Comparable` into these types via ordinary materialization.
pub use zeo_abi::{
    ARRAY_CLASS, BASIC_OBJECT_CLASS, CLASS_CLASS, COMPARABLE_CLASS, COMPLEX_CLASS,
    ENUMERATOR_CLASS, FALSE_CLASS, FIBER_CLASS, FLOAT_CLASS, HASH_CLASS, INTEGER_CLASS,
    KERNEL_CLASS, MATCH_DATA_CLASS, MATH_CLASS, MODULE_CLASS, MUTEX_CLASS, NIL_CLASS,
    NUMERIC_CLASS, PROC_CLASS, QUEUE_CLASS, RACTOR_CLASS, RANGE_CLASS, RATIONAL_CLASS,
    REGEXP_CLASS, SIZED_QUEUE_CLASS, STRING_CLASS, STRUCT_CLASS, SYMBOL_CLASS, THREAD_CLASS,
    TRUE_CLASS, YIELDER_CLASS,
};

impl RubyObject for Object {
    fn class_id(&self) -> ClassId {
        if self.moved.load(std::sync::atomic::Ordering::Relaxed) {
            return zeo_abi::RACTOR_MOVED_OBJECT_CLASS;
        }
        Self::CLASS_ID
    }
    fn retag_moved(&self) -> bool {
        self.moved.store(true, std::sync::atomic::Ordering::Relaxed);
        true
    }
    fn as_any(&self) -> &dyn Any {
        self
    }
    fn as_any_rc(self: Arc<Self>) -> Arc<dyn Any + Send + Sync> {
        self
    }
    fn is_frozen(&self) -> bool {
        self.frozen.load(std::sync::atomic::Ordering::Relaxed)
    }
    fn set_frozen(&self) {
        self.frozen
            .store(true, std::sync::atomic::Ordering::Relaxed);
    }
    fn ivar_values(&self) -> Vec<RubyValue> {
        self.ivars.lock().values().cloned().collect()
    }
    fn ivar_pairs(&self) -> Vec<(String, RubyValue)> {
        // The root object's keys are stored WITHOUT the `@` (see
        // `ivar_get_named`); paired in a single lock so name/value order can't
        // diverge. Insertion order isn't preserved (a plain `HashMap`) -- a
        // minor divergence limited to the name-keyed main object, which is
        // rarely inspected with ivars.
        self.ivars
            .lock()
            .iter()
            .map(|(k, v)| (format!("@{k}"), v.clone()))
            .collect()
    }
    fn ivar_get_named(&self, name: &str) -> Option<RubyValue> {
        // A never-assigned ivar reads `nil` rather than raising -- Ruby's
        // rule, and the reason this answers `Some(Nil)` instead of `None`
        // (`None` means "this class has no such slot", which for a
        // name-keyed object is never true).
        Some(
            self.ivars
                .lock()
                .get(name)
                .cloned()
                .unwrap_or(RubyValue::Nil),
        )
    }
    fn ivar_set_named(&self, name: &str, v: RubyValue) -> bool {
        // Probe before inserting: an ivar is written far more often than it is
        // first created, and `insert` allocated a fresh `String` key on every
        // one of those writes only to drop it again.
        let mut ivars = self.ivars.lock();
        match ivars.get_mut(name) {
            Some(slot) => *slot = v,
            None => {
                ivars.insert(name.to_string(), v);
            }
        }
        true
    }
    fn ivar_remove_named(&self, name: &str) -> Option<RubyValue> {
        // Name-keyed: a missing key is genuinely absent, so `None` cleanly
        // signals CRuby's `NameError` case.
        self.ivars.lock().remove(name)
    }
    fn dup_object(&self, copy_frozen: bool) -> RObj {
        Arc::new(Object {
            ivars: parking_lot::Mutex::new(self.ivars.lock().clone()),
            frozen: std::sync::atomic::AtomicBool::new(copy_frozen && self.is_frozen()),
            moved: std::sync::atomic::AtomicBool::new(false),
        })
    }
}

/// [`bind_dynamic_kwargs`]'s result: `(positional, required_values,
/// optional_values, rest_pairs)`.
pub type BoundKwargs<'a> = (
    &'a [RubyValue],
    Vec<RubyValue>,
    Vec<Option<RubyValue>>,
    Vec<(RubyValue, RubyValue)>,
);

/// Binds a DYNAMIC call's keyword arguments for a keyword-declaring callee
/// (the G2 trailing-kwargs-hash convention): when the last argument is a
/// Hash, it's the keyword set; otherwise there are no keywords. Returns
/// `(positional, required_values, optional_values, rest_pairs)` for the
/// generated trampoline to splice into the direct call -- optional `None`s
/// let the callee's own prologue lazily evaluate defaults, exactly like
/// Path 1.
///
/// Documented approximation (plan G2): no `ruby2_keywords` flagging, so a
/// bare trailing Hash passed positionally through `send` to a
/// keyword-declaring method binds as keywords.
pub fn bind_dynamic_kwargs<'a>(
    method: &str,
    args: &'a [RubyValue],
    required: &[&str],
    optional: &[&str],
    has_kwrest: bool,
) -> Result<BoundKwargs<'a>, Signal> {
    // Only a MARKED trailing hash is keywords. An unmarked one arrived
    // positionally -- a plain `f(9, h)`, or a hash a splat expanded, which
    // ruby makes positional again (see `unmark_kwargs_tail`).
    let (positional, kw_hash) = match args.split_last() {
        Some((RubyValue::Hash(h), rest)) if crate::collections::hash_is_kwargs(h) => {
            (rest, Some(h.clone()))
        }
        _ => (args, None),
    };
    let mut req_values = Vec::with_capacity(required.len());
    let mut opt_values = Vec::with_capacity(optional.len());
    let mut rest_pairs = Vec::new();

    let pairs: Vec<(RubyValue, RubyValue)> = match &kw_hash {
        Some(h) => h.lock().values().cloned().collect(),
        None => Vec::new(),
    };
    let lookup = |name: &str| -> Option<RubyValue> {
        pairs.iter().find_map(|(k, v)| match k {
            RubyValue::Symbol(s) if s.name_str() == name => Some(v.clone()),
            _ => None,
        })
    };
    let mut missing = Vec::new();
    for name in required {
        match lookup(name) {
            Some(v) => req_values.push(v),
            None => missing.push(name.to_string()),
        }
    }
    if !missing.is_empty() {
        return Err(kw_names_error("missing", &missing));
    }
    for name in optional {
        opt_values.push(lookup(name));
    }
    let mut unknown = Vec::new();
    for (k, v) in &pairs {
        if let RubyValue::Symbol(s) = k {
            let n = s.name_str();
            if required.contains(&n) || optional.contains(&n) {
                continue;
            }
            if has_kwrest {
                rest_pairs.push((k.clone(), v.clone()));
                continue;
            }
            unknown.push(n.to_string());
            continue;
        }
        // A non-Symbol key in the trailing hash lands in `**kwrest` as-is (Ruby
        // allows non-symbol keys there); without kwrest it can't bind as a
        // keyword -- real Ruby treats the hash as positional then, but this
        // convention already committed it as keywords (the documented
        // no-ruby2_keywords approximation).
        if has_kwrest {
            rest_pairs.push((k.clone(), v.clone()));
        } else {
            return Err(arg_error!("wrong number of arguments (in `{method}')"));
        }
    }
    if !unknown.is_empty() {
        return Err(kw_names_error("unknown", &unknown));
    }
    Ok((positional, req_values, opt_values, rest_pairs))
}

/// A `**nil` callee reached dynamically: a kw-marked trailing Hash means the
/// caller WROTE keywords (`**h` splat or `send`'s literal kwargs -- see
/// [`crate::collections::RHashData::kw_marked`]), which the declaration
/// refuses before any arity check (CRuby `vm_args.c` order). An unmarked
/// trailing Hash is an ordinary positional and passes through. A marked
/// EMPTY hash never arrives -- every writer drops a runtime-empty keyword
/// set before pushing it.
pub fn reject_marked_kwargs(args: &[RubyValue]) -> Result<(), Signal> {
    if let Some(RubyValue::Hash(h)) = args.last()
        && crate::collections::hash_is_kwargs(h)
    {
        return Err(arg_error!("no keywords accepted"));
    }
    Ok(())
}

/// CRuby's keyword-error wording: `missing keyword: :a` / `unknown keywords:
/// :c, :d` -- singular or plural by count, each name a `:sym`, no `(in ...)`
/// suffix. `kind` is `"missing"` or `"unknown"`.
fn kw_names_error(kind: &str, names: &[String]) -> Signal {
    let plural = if names.len() == 1 { "" } else { "s" };
    let list = names
        .iter()
        .map(|n| format!(":{n}"))
        .collect::<Vec<_>>()
        .join(", ");
    arg_error!("{kind} keyword{plural}: {list}")
}

/// The top-level `self` -- CRuby's `main`, a plain `Object` instance.
/// Generated code passes it as the receiver of top-level-defined methods
/// (which live on `Object`, exactly like real Ruby's private-on-Object
/// rule) and as the value of a top-level `self` expression. One shared
/// instance so identity is stable across the program, lazily built since
/// most programs never touch it.
pub fn main_object() -> RubyValue {
    main_slot().clone()
}

fn main_slot() -> &'static RubyValue {
    static MAIN: std::sync::OnceLock<RubyValue> = std::sync::OnceLock::new();
    MAIN.get_or_init(|| RubyValue::Object(Arc::new(Object::default())))
}

/// Whether `o` IS `main`. CRuby installs `to_s`/`inspect` singletons on the
/// top-level self that answer `"main"`, so it never renders as an address;
/// zeo asks by identity instead, because installing a singleton at startup
/// would mark the runtime-overlay maps live for every program.
pub fn is_main_object(o: &RObj) -> bool {
    matches!(main_slot(), RubyValue::Object(m) if Arc::ptr_eq(m, o))
}

/// Read `@name` off a receiver whose concrete class isn't statically known
/// -- what codegen emits for an ivar access when `self` is a `RubyValue`
/// rather than an `Arc<Concrete>` (top level, or a block whose self
/// `instance_exec` may rebind). `name` excludes the `@`.
///
/// A receiver that never had `@name` assigned answers nil rather than raising,
/// which is Ruby's rule for reading any unset ivar. An immediate has nowhere to
/// store one and so is always in that case; a bare heap value has the
/// identity-keyed `value_ivars` store and may well have one.
pub fn ivar_get_dyn(recv: &RubyValue, name: &str) -> RubyValue {
    match recv {
        // The `or_else` serves the runtime's hand-written objects, which
        // declare no ivars and so decline the write in `ivar_set_dyn` -- see
        // `value_ivars::key`'s `Object` arm. A generated class never reaches
        // it: its named path is total over declared and invented ivars alike.
        RubyValue::Object(o) => o
            .ivar_get_named(name)
            .or_else(|| crate::value_ivars::get(recv, name))
            .unwrap_or(RubyValue::Nil),
        // A CLASS object's own ivars live in their own table (see
        // `civars`' docs for why they can't share `cvars`'). Reached when a
        // class-method body's `self` is dynamic rather than the static class
        // id codegen usually emits -- e.g. `def self.x; [1].each { @n } end`,
        // where the block captures `self` as a plain `RubyValue::Class`.
        RubyValue::Class(cid) => crate::civars::class_ivar_get(cid.0, name),
        // `[].instance_eval { @x }` -- see `value_ivars`.
        _ => crate::value_ivars::get(recv, name).unwrap_or(RubyValue::Nil),
    }
}

/// [`ivar_get_dyn`] behind CRuby's Ractor guard -- what codegen emits for a
/// dynamic self, the only receiver that can be a shareable object read from a
/// non-main ractor. See [`crate::ractor::ivar_isolation_check`].
pub fn ivar_get_dyn_isolated(recv: &RubyValue, name: &str) -> Result<RubyValue, Signal> {
    crate::ractor::ivar_isolation_check(recv)?;
    Ok(ivar_get_dyn(recv, name))
}

/// [`ivar_slot_get_dyn`] behind the same guard.
pub fn ivar_slot_get_dyn_isolated(
    recv: &RubyValue,
    slot: usize,
    name: &str,
) -> Result<RubyValue, Signal> {
    crate::ractor::ivar_isolation_check(recv)?;
    Ok(ivar_slot_get_dyn(recv, slot, name))
}

/// Read `@name` from a receiver whose class is one of a known set that all
/// place `@name` at `slot` -- the shared-body form of `ivar_get_dyn`.
///
/// `codegen::share` proves the index agrees across the set before it emits
/// this, and every such receiver is a generated object. `name` serves the
/// arms that reach neither (a rebound `self`), which is exactly what
/// `ivar_get_dyn` already answers.
#[inline]
pub fn ivar_slot_get_dyn(recv: &RubyValue, slot: usize, name: &str) -> RubyValue {
    match recv {
        RubyValue::Object(o) => o.ivar_slot_get(slot),
        other => ivar_get_dyn(other, name),
    }
}

/// `ivar_slot_get_dyn`'s counterpart, carrying the same frozen check
/// `ivar_set_dyn` does.
#[inline]
pub fn ivar_slot_set_dyn(
    recv: &RubyValue,
    slot: usize,
    name: &str,
    v: RubyValue,
) -> Result<RubyValue, Signal> {
    match recv {
        RubyValue::Object(o) => {
            crate::builtins::check_frozen(recv)?;
            o.ivar_slot_set(slot, v.clone());
            Ok(v)
        }
        other => ivar_set_dyn(other, name, v),
    }
}

/// Write `@name` on a statically-unknown receiver -- `ivar_get_dyn`'s
/// counterpart, carrying Ruby's frozen check (`rb_check_frozen`) and its
/// can't-modify-frozen raise, which the static field-write path emits
/// inline instead.
pub fn ivar_set_dyn(recv: &RubyValue, name: &str, v: RubyValue) -> Result<RubyValue, Signal> {
    crate::ractor::ivar_isolation_check(recv)?;
    match recv {
        RubyValue::Object(o) => {
            crate::builtins::check_frozen(recv)?;
            // A hand-written runtime object declares no ivars and answers
            // `false`. Dropping the write there would make `class StringScanner;
            // def tag=(v); @tag = v; end; end` silently read back nil, so it
            // goes to the identity-keyed store instead.
            if !o.ivar_set_named(name, v.clone()) {
                crate::value_ivars::set(recv, name, v.clone());
            }
            Ok(v)
        }
        // See `ivar_get_dyn`'s Class arm. The frozen-class guard lives
        // inside `class_ivar_set` itself.
        RubyValue::Class(cid) => {
            crate::civars::class_ivar_set(cid.0, name, v.clone())?;
            Ok(v)
        }
        // An unfrozen heap value (`[].instance_eval { @x = 1 }`) gets the
        // identity-keyed store; the permanently-frozen tier (immediates, and
        // `Range`) has nowhere to put one and raises, naming the class the way
        // CRuby's `rb_check_frozen` does.
        _ => {
            crate::builtins::check_frozen(recv)?;
            if !crate::value_ivars::set(recv, name, v.clone()) {
                return Err(frozen_error!(
                    "can't modify frozen {}: {}",
                    crate::builtins::class_name_of(recv),
                    recv.inspect_string()
                ));
            }
            Ok(v)
        }
    }
}

/// Downcasts an erased `RObj` to an owned `Arc<T>` -- the Path 2 trampoline
/// counterpart to `as_any().downcast_ref()`, needed because every generated
/// method takes `self: Arc<Self>` now (see `ruby_class!`'s docs). Cloning
/// `recv` first is a cheap `Arc` refcount bump, not a deep copy.
pub fn downcast_robj<T: RubyObject>(recv: &RObj) -> Option<Arc<T>> {
    recv.clone().as_any_rc().downcast::<T>().ok()
}

/// `downcast_robj` without the refcount traffic: a BORROW of the concrete
/// struct, for a trampoline that only reads or writes a field and never hands
/// the receiver to anything that could outlive the call. The owned form costs
/// an `Arc` clone plus its matching drop -- 4.08 ns measured, which is most of
/// an accessor call -- so an accessor trampoline (`zeo_tramp!`'s `rd`/`wr`
/// heads) takes this one instead.
#[inline]
pub fn downcast_robj_ref<T: RubyObject>(recv: &RObj) -> Option<&T> {
    recv.as_any().downcast_ref::<T>()
}

/// The frozen-receiver raise every ivar WRITE guards itself with, as one
/// out-of-line call instead of the `format!` + `construct_by_class_id`
/// codegen this used to inline at every ivar write -- thousands of them in a
/// program like prism. `#[cold]` so the caller's guard stays a
/// predictable never-taken branch around a single relaxed atomic load, and by
/// VALUE so the `Arc` bump the handle needs happens only on the raise path.
///
/// It also corrects the inlined form, which built its message from the
/// compiler's `ClassInfo::name` and carried no `receiver`: CRuby reports the
/// FULLY QUALIFIED name (`can't modify frozen M::Inner:`, not `Inner:`) and
/// answers `FrozenError#receiver`, both of which the runtime knows and a
/// literal baked at each write site did not.
#[cold]
#[inline(never)]
pub fn ivar_frozen_error(recv: RObj) -> Signal {
    crate::builtins::check_frozen(&RubyValue::Object(recv))
        .expect_err("only called once the receiver is known frozen")
}

/// Every generated method/trampoline returns `Result<RubyValue, Signal>`, not
/// a bare `RubyValue` -- see `Signal`'s docs for why this is fixed from the
/// start rather than retrofitted once `break`/`raise`/non-local `return`
/// exist. The third parameter is the call's block, if any (`None` when no
/// block was given) -- see `signal.rs`'s `catch_break` and `codegen::params`'s
/// docs for how a block crosses the Path 2 boundary.
pub type MethodFn = fn(&RObj, &[RubyValue], Option<RubyValue>) -> Result<RubyValue, Signal>;

/// A method body no bare `fn` pointer can represent: a closure carrying
/// captured state (a runtime `define_method` block today; interpreted eval-VM
/// bodies when that phase lands).
pub type DynMethodFn =
    Arc<dyn Fn(&RObj, &[RubyValue], Option<RubyValue>) -> Result<RubyValue, Signal> + Send + Sync>;

/// A registered instance method's implementation. Statically-registered
/// methods are `Static` -- a bare `fn` pointer -- so the hot path is a direct
/// indirect call with one folded discriminant branch, no allocation.
#[derive(Clone)]
pub enum MethodImpl {
    Static(MethodFn),
    // The runtime-metaprogramming seam: a compiled block captured as an
    // `Arc<dyn Fn>`, built by `runtime_meta::dynamic_from_proc` for a runtime
    // `define_method`. `Clone` is cheap on both arms (a `fn` copy / an `Arc`
    // bump) -- the overlay resolvers clone an entry out and drop their lock
    // BEFORE dispatching, so a runtime method that itself defines another
    // method can't deadlock.
    Dynamic(DynMethodFn),
}

impl MethodImpl {
    #[inline(always)]
    pub fn call(
        &self,
        recv: &RObj,
        args: &[RubyValue],
        block: Option<RubyValue>,
    ) -> Result<RubyValue, Signal> {
        match self {
            MethodImpl::Static(f) => f(recv, args, block),
            MethodImpl::Dynamic(f) => f(recv, args, block),
        }
    }

    #[inline(always)]
    pub fn from_fn(f: MethodFn) -> Self {
        MethodImpl::Static(f)
    }
}

/// A class's dynamic constructor: allocates a fresh instance
/// and runs its `initialize` (if any) -- what makes `x = Widget;
/// x.new(...)` work when the class is only known at runtime as a
/// `RubyValue::Class` value. Generated per class by `ruby_class!`
/// (`__construct`, which ignores the id and uses its own `Self::CLASS_ID`);
/// `None` for modules and builtins.
///
/// The leading `ClassId` lets ONE constructor back many classes -- the native
/// exception hierarchy registers every exception class with the same
/// `RubyException`-allocating fn, which reads the id from here instead of a
/// per-class Rust type (see `crate::builtins::exception`).
pub type ConstructorFn = fn(ClassId, &[RubyValue], Option<RubyValue>) -> Result<RubyValue, Signal>;

/// Allocates a fresh, ZERO-INITIALIZED instance of a class WITHOUT running
/// `initialize` -- backs `Class#allocate`. Mirrors `ConstructorFn`'s
/// id-passing shape (one allocator can back many classes) but returns the
/// bare `RObj` (every ivar `Nil`, frozen `false`); the caller wraps it in
/// `RubyValue::Object`. `None` for modules/builtins (which have no generated
/// struct); `Class#allocate` on those either yields a builtin empty value or
/// raises, handled at the call site.
pub type AllocatorFn = fn(ClassId) -> RObj;

/// A method defined by REOPENING a builtin class (`class String;
/// def blank?; ...`): the receiver is the builtin VALUE itself (`&RubyValue`,
/// not an `RObj` -- builtins have no generated struct to downcast to), which
/// is exactly what the generated free-function bodies take as `__self`.
/// Consulted FIRST by `send_value` (before even the universal `==`/`dup`
/// arms and the curated tables), because a user redefinition must OVERRIDE
/// the builtin behavior -- real Ruby's rule, oracle-verified (`class String;
/// def length; 42; end` wins everywhere). Per-box overlays key off
/// this same table.
pub type ValueMethodFn =
    fn(&RubyValue, &[RubyValue], Option<RubyValue>) -> Result<RubyValue, Signal>;

/// Builtin rows that push NO synthetic frame: rows whose CRuby counterpart is
/// frameless in a backtrace (`send`, `raise`), and rows whose implementation
/// reads the CALLER's frames and would see its own synthetic one instead
/// (`caller`, `binding`, `__method__`, `warn`'s uplevel). The eval family
/// stays frameless too: its frames carry `(eval)` locations built inside
/// `eval_vm`, not a dispatch-boundary label.
const NOFRAME: &[&str] = &[
    // `Proc#call`/`Method#call` are frameless in CRuby backtraces -- the
    // callee's own frame sits directly on the caller's.
    "call",
    "caller",
    "caller_locations",
    "each_caller_location",
    "raise",
    "fail",
    "throw",
    "binding",
    "local_variables",
    "__method__",
    "__callee__",
    "block_given?",
    "iterator?",
    "warn",
    "puts",
    "print",
    "p",
    "pp",
    "putc",
    "send",
    "__send__",
    "public_send",
    "eval",
    "instance_eval",
    "instance_exec",
    "class_eval",
    "class_exec",
    "module_eval",
    "module_exec",
];

/// Rows CRuby answers with a SPECIALIZED VM instruction rather than a call:
/// `opt_ltlt` and `opt_aset` push no control frame, so a raise from inside one
/// names only the caller (`"x".freeze << "y"` reports `<main>`, where a
/// hand-written `def <<` would report itself).
///
/// Keyed by (class, name), because the specialization is per receiver type and
/// the general fallback DOES frame: `opt_ltlt` covers String and Array and
/// nothing else, so `IO#<<` reports `IO#write` / `IO#<<` and must not be
/// silenced by a name-only rule. Only the rows whose fast path can RAISE are
/// listed -- the frozen checks and nothing else; an `opt_aref` or an `opt_eq`
/// has no way to reach a backtrace.
const SPECIALIZED: &[(ClassId, &str)] = &[
    (zeo_abi::STRING_CLASS, "<<"),
    (zeo_abi::ARRAY_CLASS, "<<"),
    (zeo_abi::ARRAY_CLASS, "[]="),
    (zeo_abi::HASH_CLASS, "[]="),
];

/// The interned backtrace label for a builtin row -- `'Owner#name'` for an
/// instance row, `'Owner.name'` for a class row -- or `None` for [`NOFRAME`]
/// and [`SPECIALIZED`].
/// One leak per distinct row, cached, so the cold MRO-walk paths can ask on
/// every call; the flat maps precompute it into [`FlatHit`] instead.
fn c_frame_label(owner: ClassId, name: Symbol, sep: char) -> Option<&'static str> {
    let n = name.name_str();
    if NOFRAME.contains(&n) {
        return None;
    }
    if sep == '#' && SPECIALIZED.contains(&(owner, n)) {
        return None;
    }
    type LabelKey = (u32, Symbol, bool);
    static LABELS: std::sync::Mutex<Option<crate::FMap<LabelKey, &'static str>>> =
        std::sync::Mutex::new(None);
    let key = (owner.0, name, sep == '#');
    let mut cache = LABELS.lock().expect("label cache");
    let map = cache.get_or_insert_with(crate::FMap::default);
    if let Some(&label) = map.get(&key) {
        return Some(label);
    }
    let label: &'static str = Box::leak(format!("{}{sep}{n}", class_name(owner)?).into_boxed_str());
    map.insert(key, label);
    Some(label)
}

/// Run `f` under the row's synthetic C frame, or bare for a `None` label.
#[inline]
fn with_c_frame<R>(label: Option<&'static str>, f: impl FnOnce() -> R) -> R {
    match label {
        Some(l) => {
            let _frame = crate::frames::synthetic_c_frame(l);
            f()
        }
        None => f(),
    }
}

/// Reads the FROZEN ancestry deliberately: a class whose chain was spliced at
/// runtime is covered by `GATE_ANCESTRY_MUTATED` instead, which is a stronger
/// statement than anything this could enumerate.
pub(crate) fn classes_with_ancestor(id: ClassId) -> Vec<u32> {
    let Some(reg) = REGISTRY.get() else {
        return Vec::new();
    };
    reg.entries
        .iter()
        .filter(|(_, e)| e.ancestors.contains(&id))
        .map(|(&cid, _)| cid)
        .collect()
}

/// `recv_class.is_a?(target)` -- a real ancestry check against the SAME
/// linearized `ancestors` list `super`/reflection uses at compile time (see
/// `analyze::mro::compute_ancestors`'s docs), not zeo's own two-tier
/// "transplant for dispatch, shallower list for reflection" split (confirmed
/// to diverge on a module-of-module diamond -- see the plan). The one
/// runtime surface this needs for `Signal::Raise`/`rescue` matching:
/// there's no first-class `Class`/`Module` runtime VALUE (can't be stored in
/// a variable or reflected on generally), just this narrow "is this concrete
/// class id ancestor-compatible with that one" check.
pub fn is_a(recv_class: ClassId, target: ClassId) -> bool {
    ancestors_of_value(recv_class).contains(&target)
}

/// The modules `cid`'s class body `extend`ed, or empty for a class that
/// extended nothing (and for one born at runtime -- `Class.new { extend M }`
/// records into `runtime_meta`'s map instead).
pub(crate) fn class_extends(cid: ClassId) -> &'static [ClassId] {
    REGISTRY
        .get()
        .and_then(|r| r.entries.get(&cid.0))
        .map_or(&[], |e| &e.extends)
}

/// `is_a?` over a VALUE rather than a class id -- the ancestry check plus the
/// modules `obj.extend(M)` mixed into this one object. A class id cannot
/// express those: `extend` leaves the class alone and files the module on the
/// receiver's singleton, so two objects of the same class disagree.
///
/// Every observable `is_a?` (`Kernel#is_a?`, `Module#===`, `case`/`when`, a
/// `ClassCheck` pattern) goes through here. `is_a` itself stays for the
/// internal checks that hold a class id and nothing else.
pub fn is_a_value(recv: &RubyValue, target: ClassId) -> bool {
    // A moved container answers as the husk class it now is (`class_id`
    // cannot say so for `Str`/`Array`/`Hash`, which carry no class word) --
    // `crate::value::observed_class_id` is the same probe for the callers
    // that want the id itself. Gated on the process-wide moved gate, so a
    // program that never moves pays one shared-byte load.
    if crate::runtime_meta::any_moved() && value_moved(recv) {
        return is_a(zeo_abi::RACTOR_MOVED_OBJECT_CLASS, target);
    }
    is_a(recv.class_id(), target)
        || crate::runtime_meta::value_extends(recv, target)
        || is_a_singleton_class(recv, target)
}

/// Whether `v` is a husk a `Ractor` move left behind: a gutted container
/// (its `Freezable` flags byte says so) or a retagged object. Callers gate
/// on [`crate::runtime_meta::any_moved`] first, so the flag probes only run
/// once a move has actually happened.
pub(crate) fn value_moved(v: &RubyValue) -> bool {
    match v {
        RubyValue::Str(s) => s.is_moved(),
        RubyValue::Array(a) => a.is_moved(),
        RubyValue::Hash(h) => h.is_moved(),
        RubyValue::Object(o) => o.class_id() == zeo_abi::RACTOR_MOVED_OBJECT_CLASS,
        _ => false,
    }
}

/// Codegen's guard ahead of an inlined accessor field access (emitted only
/// for a program that names `Ractor` -- the emission switch): a Path-1
/// receiver bypasses dispatch, so the husk check runs here instead.
pub fn check_not_moved_obj<T: RubyObject>(o: &T) -> Result<(), Signal> {
    if o.class_id() == zeo_abi::RACTOR_MOVED_OBJECT_CLASS {
        return Err(crate::ractor::moved_object_error());
    }
    Ok(())
}

/// `Foo.is_a?(Foo.singleton_class)` -- true in CRuby, because `CLASS_OF(Foo)`
/// IS that singleton class. zeo mints singleton classes on demand instead of
/// threading the parallel `#<Class:Sub> < #<Class:Foo>` chain, so the relation
/// is answered from the id's OWNER: a class instantiates its own singleton
/// class and every ancestor's, and any other value only its own.
fn is_a_singleton_class(recv: &RubyValue, target: ClassId) -> bool {
    if !crate::runtime_meta::is_live() {
        return false;
    }
    match crate::runtime_meta::singleton_owner_value(target) {
        Some(RubyValue::Class(owner)) => {
            matches!(recv, RubyValue::Class(cid) if is_a(*cid, owner))
        }
        // An object's singleton class has exactly one instance, so this is
        // identity, not equality.
        Some(owner) => {
            let key = crate::runtime_meta::value_identity(&owner);
            key.is_some() && key == crate::runtime_meta::value_identity(recv)
        }
        None => false,
    }
}

/// `rescue *list => e` matching: does the raised `exc` match any class in the
/// splatted `list`? `list` is the EVALUATED splat expression -- an Array of
/// exception classes (`rescue *errs`), or, splatting a non-array, a single
/// class (`rescue *ArgumentError`). An empty array matches nothing. A
/// non-Module element is CRuby's `TypeError: class or module required for
/// rescue clause`. OR'd in after a clause's static class list by codegen.
pub fn rescue_matches_any(exc: &RubyValue, list: &RubyValue) -> Result<bool, Signal> {
    match list {
        RubyValue::Array(a) => {
            for el in a.lock().to_vec() {
                if rescue_class_matches(&el, exc)? {
                    return Ok(true);
                }
            }
            Ok(false)
        }
        single => rescue_class_matches(single, exc),
    }
}

fn rescue_class_matches(cls: &RubyValue, exc: &RubyValue) -> Result<bool, Signal> {
    match cls {
        RubyValue::Class(cid) => {
            // `rescue` matches via `===` (CRuby's rule): `Module#===` is the
            // ancestry test, taken directly -- unless the matcher OVERRIDES
            // `self.===`, which is how rspec-support's
            // `AllExceptionsExceptOnesWeMustNotRescue` catches everything but
            // NoMemory/SignalException. The override is rare, the probe cheap,
            // and this path runs only while an exception is in flight.
            if class_method_owner(*cid, Symbol::intern("===")).is_some() {
                let verdict =
                    send_value(cls, Symbol::intern("==="), std::slice::from_ref(exc), None)?;
                return Ok(verdict.truthy());
            }
            Ok(is_a(exc.as_object_unchecked().class_id(), *cid))
        }
        _ => Err(raise_error(
            "TypeError",
            "class or module required for rescue clause".to_string(),
        )),
    }
}

/// `Module#<=>`-style ordering of two class/module ids by the ancestry
/// relation (CRuby `rb_class_cmp`): `Less` when `a` is a proper descendant of
/// `b`, `Greater` when a proper ancestor, `Equal` when the same class, and
/// `None` when the two are unrelated (neither appears in the other's
/// linearized ancestors). Backs `Module`'s `<`/`<=`/`>`/`>=`/`<=>` rows.
pub fn module_cmp(a: ClassId, b: ClassId) -> Option<std::cmp::Ordering> {
    use std::cmp::Ordering;
    let a_le_b = is_a(a, b); // b in a's ancestors: a is b-or-below
    let b_le_a = is_a(b, a);
    match (a_le_b, b_le_a) {
        (true, true) => Some(Ordering::Equal),
        (true, false) => Some(Ordering::Less),
        (false, true) => Some(Ordering::Greater),
        (false, false) => None,
    }
}

/// The DIRECT subclasses of `cid` (CRuby `Class#subclasses`): every registered
/// non-module class whose immediate superclass -- the first non-module entry
/// after itself in its linearized ancestry -- is `cid`. Order is unspecified
/// in CRuby, so callers that need determinism sort by name.
pub fn direct_subclasses(cid: ClassId) -> Vec<ClassId> {
    let Some(r) = REGISTRY.get() else {
        return Vec::new();
    };
    r.entries
        .iter()
        .filter(|(_, e)| !e.is_module)
        .filter_map(|(&id, e)| {
            let self_id = ClassId(id);
            if self_id == cid {
                return None;
            }
            let sup = e
                .ancestors
                .iter()
                .skip_while(|&&a| a != self_id)
                .skip(1)
                .find(|&&a| !class_is_module(a).unwrap_or(false))?;
            (*sup == cid).then_some(self_id)
        })
        .collect()
}

/// The bare ivar name (`x`) from a `:@x`/`"@x"` reflection argument. A
/// non-symbol/string is a `TypeError`; a name without the leading `@` is a
/// `NameError` -- both mirroring CRuby's own messages. Shared by the
/// universal `Object#instance_variable_*` helpers below (the class-object
/// table in `builtins::class_module` keeps its own parallel copy).
pub fn ivar_name_arg(v: &RubyValue) -> Result<String, Signal> {
    // A symbol's text is already interned and `'static`, so the strip happens
    // before any allocation: `instance_variable_get(:@x)`, which is how this
    // is almost always spelled, allocated the name TWICE (once to own the
    // symbol's text, once for the `@`-stripped tail).
    if let RubyValue::Symbol(s) = v {
        let raw = s.name_str();
        return match raw.strip_prefix('@') {
            Some(name) => Ok(name.to_string()),
            None => Err(name_error!(
                "'{raw}' is not allowed as an instance variable name"
            )),
        };
    }
    let raw = match v {
        RubyValue::Str(s) => s.lock().to_utf8_lossy().into_owned(),
        _ => {
            return Err(type_error!(
                "{} is not a symbol nor a string",
                v.inspect_string()
            ));
        }
    };
    match raw.strip_prefix('@') {
        Some(name) => Ok(name.to_string()),
        None => Err(name_error!(
            "'{raw}' is not allowed as an instance variable name"
        )),
    }
}

/// `Object#instance_variable_get(:@x)` over ANY receiver: an `Object`'s named
/// ivar, a class object's own ivar (`civars`), or `nil` for a builtin/
/// immediate (which expose no Ruby-visible ivars in this runtime).
pub fn instance_variable_get(recv: &RubyValue, name_arg: &RubyValue) -> Result<RubyValue, Signal> {
    let name = ivar_name_arg(name_arg)?;
    crate::ractor::ivar_isolation_check(recv)?;
    Ok(match recv {
        RubyValue::Object(o) => o
            .ivar_get_named(&name)
            .or_else(|| crate::value_ivars::get(recv, &name))
            .unwrap_or(RubyValue::Nil),
        RubyValue::Class(cid) => crate::civars::class_ivar_get(cid.0, &name),
        _ => crate::value_ivars::get(recv, &name).unwrap_or(RubyValue::Nil),
    })
}

/// `Object#instance_variable_set(:@x, v)` -- writes the named ivar (of an
/// object or a class object), answering the value. A no-op on a
/// non-Object, non-Class receiver with no slot for the name. Carries
/// CRuby's `rb_check_frozen` (a frozen receiver raises before writing --
/// the same guard `ivar_set_dyn` and the static write path emit).
pub fn instance_variable_set(
    recv: &RubyValue,
    name_arg: &RubyValue,
    v: RubyValue,
) -> Result<RubyValue, Signal> {
    let name = ivar_name_arg(name_arg)?;
    crate::ractor::ivar_isolation_check(recv)?;
    match recv {
        RubyValue::Object(o) => {
            crate::builtins::check_frozen(recv)?;
            if !o.ivar_set_named(&name, v.clone()) {
                crate::value_ivars::set(recv, &name, v.clone());
            }
        }
        RubyValue::Class(cid) => crate::civars::class_ivar_set(cid.0, &name, v.clone())?,
        // A frozen builtin (immediates always; a frozen Str/Array/Hash)
        // raises like CRuby; an unfrozen one gets the identity-keyed store.
        other => {
            crate::builtins::check_frozen(other)?;
            crate::value_ivars::set(other, &name, v.clone());
        }
    }
    Ok(v)
}

/// `Object#remove_instance_variable(:@x)` -- removes the named ivar and
/// answers its former value, raising `NameError` if the object has no such
/// ivar. A frozen object raises `FrozenError` first (CRuby's order).
pub fn remove_instance_variable(
    recv: &RubyValue,
    name_arg: &RubyValue,
) -> Result<RubyValue, Signal> {
    let name = ivar_name_arg(name_arg)?;
    match recv {
        RubyValue::Object(o) => {
            crate::builtins::check_frozen(recv)?;
            match o
                .ivar_remove_named(&name)
                .or_else(|| crate::value_ivars::remove(recv, &name))
            {
                Some(v) => Ok(v),
                None => Err(name_error!("instance variable @{name} not defined")),
            }
        }
        _ => {
            crate::builtins::check_frozen(recv)?;
            crate::value_ivars::remove(recv, &name)
                .ok_or_else(|| name_error!("instance variable @{name} not defined"))
        }
    }
}

/// `Object#instance_variables` -- the receiver's ivar names as `:@name`
/// symbols in declaration order (empty for a builtin/immediate).
/// Whether `recv` has instance variable `@{bare_name}` actually set -- backs
/// `defined?(@iv)`, which answers `"instance-variable"` only for an assigned
/// ivar and `nil` otherwise. `bare_name` is the name without the leading `@`.
pub fn ivar_defined(recv: &RubyValue, bare_name: &str) -> bool {
    let want = Symbol::intern(&format!("@{bare_name}"));
    let RubyValue::Array(vars) = instance_variables(recv) else {
        return false;
    };

    vars.lock()
        .iter()
        .any(|v| matches!(v, RubyValue::Symbol(s) if *s == want))
}

pub fn instance_variables(recv: &RubyValue) -> RubyValue {
    let names: Vec<RubyValue> = match recv {
        // `ivar_pairs` already yields `@`-prefixed names (it backs the
        // default `Object#inspect`); `class_ivar_names` yields bare ones.
        // `value_ivars` contributes only for a hand-written runtime object,
        // whose `ivar_pairs` is empty -- see `ivar_set_dyn`'s Object arm.
        RubyValue::Object(o) => o
            .ivar_pairs()
            .into_iter()
            .map(|(n, _)| RubyValue::Symbol(Symbol::intern(&n)))
            .chain(
                crate::value_ivars::names(recv)
                    .into_iter()
                    .map(|n| RubyValue::Symbol(Symbol::intern(&format!("@{n}")))),
            )
            .collect(),
        RubyValue::Class(cid) => crate::civars::class_ivar_names(cid.0)
            .into_iter()
            .map(|n| RubyValue::Symbol(Symbol::intern(&format!("@{n}"))))
            .collect(),
        _ => crate::value_ivars::names(recv)
            .into_iter()
            .map(|n| RubyValue::Symbol(Symbol::intern(&format!("@{n}"))))
            .collect(),
    };
    RubyValue::Array(crate::array_new(names))
}

/// A fresh, uninitialized instance of `id` through its registered allocator,
/// or `None` for a class that registered none (a module, a builtin, or a class
/// minted at runtime). Does NOT run `initialize`.
pub(crate) fn allocate_instance_of(id: ClassId) -> Option<RObj> {
    match REGISTRY.get()?.allocate_instance(id) {
        Some(RubyValue::Object(o)) => Some(o),
        _ => None,
    }
}

/// A constant MISS dispatches `const_missing` on the owning class -- a user
/// hook (compiled `def self.const_missing`, or one defined at runtime)
/// answers; Module's default row raises the same qualified NameError the
/// miss would have. CRuby's exact protocol, which nothing in this runtime
/// called before: the hook had a definition but no caller.
pub fn const_miss(cid: ClassId, name: &str) -> Result<RubyValue, Signal> {
    send_value(
        &RubyValue::Class(cid),
        Symbol::intern("const_missing"),
        &[RubyValue::Symbol(Symbol::intern(name))],
        None,
    )
}

/// The `AllocatorFn` `id` itself registered -- only `ruby_class!`-generated
/// (compiled user) classes register one, so a `Some` here identifies a class
/// whose instances are real generated structs.
pub(crate) fn registry_allocator(id: ClassId) -> Option<AllocatorFn> {
    REGISTRY.get()?.entries.get(&id.0).and_then(|e| e.allocator)
}

/// The nearest ancestor of `id` (per the live chain, self included) that
/// registered an `AllocatorFn` -- how a runtime subclass of a COMPILED class
/// allocates instances that inherited compiled methods can downcast: the
/// ancestor's struct, stamped with the SUBCLASS's id (see `ruby_class!`'s
/// `__class` field).
pub(crate) fn ancestor_allocator_of(id: ClassId) -> Option<AllocatorFn> {
    // A `Class#dup` copy's chain deliberately does NOT contain its source
    // (`K.dup.ancestors` skips `K`, as ruby's does), so the compiled struct
    // its copied bodies downcast to is reachable only through the allocator
    // the copy recorded for itself. See `OverlayEntry::allocator`.
    crate::runtime_meta::overlay_allocator(id).or_else(|| {
        ancestors_of_value(id)
            .iter()
            .find_map(|a| registry_allocator(*a))
    })
}

/// `id`'s OWN registered class-method body (`def self.x`), as the raw fn --
/// what `Class#dup` copies onto the new class. Deliberately not the flattened
/// probe: an INHERITED class method belongs to the ancestor, and the copy
/// keeps the same ancestor.
pub(crate) fn own_class_method_fn(id: ClassId, name: Symbol) -> Option<ValueMethodFn> {
    REGISTRY
        .get()?
        .entries
        .get(&id.0)?
        .class_methods
        .get(&name)
        .copied()
}

/// The registry's dynamic constructor for `id` (`Class#new`'s row) --
/// `None` for modules, builtins without allocators, or a missing registry.
pub(crate) fn constructor_of(id: ClassId) -> Option<ConstructorFn> {
    if let Some(c) = REGISTRY
        .get()
        .and_then(|r| r.entries.get(&id.0))
        .and_then(|e| e.constructor)
    {
        return Some(c);
    }
    // A runtime class (`Class.new`) registers its generic constructor in the
    // overlay, so `RuntimeClass.new` flows through the same `Class#new` ->
    // `construct_by_class_id` path frozen classes use.
    if crate::runtime_meta::is_live() {
        return crate::runtime_meta::overlay_constructor(id);
    }
    None
}

/// A fresh uninitialized instance of `id` (`Class#allocate`) -- a user class's
/// registered allocator, or a runtime (`Class.new`) class's name-keyed object.
/// `None` for modules/builtins (handled at the `allocate` call site).
pub(crate) fn allocate_of(id: ClassId) -> Option<RubyValue> {
    if let Some(v) = REGISTRY.get().and_then(|r| r.allocate_instance(id)) {
        return Some(v);
    }
    if crate::runtime_meta::is_live() {
        return crate::runtime_meta::runtime_allocate(id);
    }
    None
}

/// Construct an instance of the class with id `id`, running its `initialize`.
/// Codegen calls this at every raise/construct site for a BOOTSTRAP exception
/// class, since those classes have no generated Rust struct to name --
/// the native exceptions registered their `ConstructorFn` (see
/// `crate::builtins::exception`).
/// A missing constructor is a zeo bug (a bootstrap id with no registrar).
pub fn construct_by_class_id(
    id: ClassId,
    args: &[RubyValue],
    block: Option<RubyValue>,
) -> Result<RubyValue, Signal> {
    match constructor_of(id) {
        Some(ctor) => ctor(id, args, block),
        None => panic!("no constructor registered for class id {}", id.0),
    }
}

/// `defined?(super)`'s probe: whether a super target exists for `name` past
/// `defining_class` on `recv`'s chain -- the same resolution
/// [`send_super_from`] walks, answered as a boolean instead of a call.
pub fn super_defined(recv: &RubyValue, defining_class: ClassId, name: Symbol) -> bool {
    method_owner_after(recv.class_id(), defining_class, name).is_some()
}

/// The `super` dispatch for an exception-backed receiver.
///
/// Resumes the MRO walk in the RECEIVER's own ancestors, at the entry after
/// `defining_class` -- the class whose body this `super` is written in -- and
/// invokes the first `name` registered there, whether a native default or a
/// user delta.
///
/// Codegen's `emit_super_inline` HIR splice cannot serve a `super` into a
/// native exception method. An exception's message lives in a hidden slot,
/// independent of any `@message` ivar, so the retained `Exception#initialize`
/// HIR would set a visible ivar and leave the real message untouched. Walking
/// the registry, where every exception id carries the native `exc_*` fns,
/// runs the true behaviour instead.
///
/// This is also the shape the eval VM needs for `super`, so it lands here
/// rather than in codegen.
pub fn send_super_from(
    recv: &RubyValue,
    defining_class: ClassId,
    name: Symbol,
    args: &[RubyValue],
    block: Option<RubyValue>,
) -> Result<RubyValue, Signal> {
    // A CLASS object in the OBJECT channel means the defining body ran with a
    // class as `self` -- a module instance method serving as a class method
    // through a runtime extend/singleton-prepend wrapper. Its `super` walks
    // the receiver's CLASS-method chain; the object channel would walk
    // `Class`'s own instance ancestry and miss.
    if let RubyValue::Class(cid) = recv {
        return send_super_class_from(*cid, defining_class, name, args, block);
    }
    // Resume AFTER the class this `super` is written in; an unrecognized
    // `defining_class` (never expected) degrades to a full walk from the top.
    let ancestors = ancestors_of_value(recv.class_id());
    let start = ancestors
        .iter()
        .position(|&a| a == defining_class)
        .map_or(0, |p| p + 1);
    send_walking(recv, start, name, args, block)
}

/// Invoke `name` AS `owner` defines it, against `recv` -- what a `Method`
/// that `#super_method` re-seated calls, so
/// `Sub.new.method(:greet).super_method.call` runs `Base#greet` rather than
/// re-dispatching to the `Sub#greet` it was reached through.
///
/// It reads the same `own_impls` set a `super` walk does, and for the same
/// reason: a user class's materialized `methods` row downcasts `self` to that
/// class's own generated struct, so `Base`'s row cannot run against a `Sub`
/// instance. `own_impls` holds the receiver-generic bridge instead. Codegen
/// emits those bridges for every method name a `super` -- or a
/// `#super_method` anywhere in the program -- can reach.
/// [`send_as_defined_in`] with the runtime overlay skipped -- the body
/// `owner` defines BELOW any later runtime redefinition. What a frozen
/// `Method`/`UnboundMethod` position calls, so a wrapper installed since
/// (the `method_added` wrap idiom) cannot capture it and recurse.
pub fn send_below_overlay_at(
    recv: &RubyValue,
    owner: ClassId,
    name: Symbol,
    args: &[RubyValue],
    block: Option<RubyValue>,
) -> Result<RubyValue, Signal> {
    if let RubyValue::Object(obj) = recv
        && let Some(m) = registry().super_target(owner, name)
    {
        return m.call(obj, args, block);
    }
    if let Some(r) = probe_generic_row(recv, owner, name, args, block.clone()) {
        return r;
    }
    send_value(recv, name, args, block)
}

pub fn send_as_defined_in(
    recv: &RubyValue,
    owner: ClassId,
    name: Symbol,
    args: &[RubyValue],
    block: Option<RubyValue>,
) -> Result<RubyValue, Signal> {
    if let RubyValue::Object(obj) = recv {
        if crate::runtime_meta::is_live()
            && let Some(m) = crate::runtime_meta::overlay_own_method(owner, name)
        {
            return m.call(obj, args, block);
        }
        if let Some(m) = registry().super_target(owner, name) {
            return m.call(obj, args, block);
        }
    }
    if let Some(r) = probe_generic_row(recv, owner, name, args, block.clone()) {
        return r;
    }
    // Nothing receiver-generic at the owner: fall back to ordinary dispatch
    // rather than raising, so the call still answers SOMETHING.
    send_value(recv, name, args, block)
}

/// Probe `anc`'s receiver-generic rows -- its VALUE methods, then its
/// registered builtin table -- and run the hit. A value subclass reaching an
/// ancestor its payload owns runs the row against the PAYLOAD and re-wraps a
/// self-return, the same bridge ordinary dispatch's probes apply: a payload
/// root's native rows downcast the receiver, and the boxed subclass panicked
/// them (`super` through an included module into `Array#size`).
fn probe_generic_row(
    recv: &RubyValue,
    anc: ClassId,
    name: Symbol,
    args: &[RubyValue],
    block: Option<RubyValue>,
) -> Option<Result<RubyValue, Signal>> {
    // The FOREIGN rows on `anc` are skipped: a reopened builtin registers its
    // whole flattened table, so the row sitting at this position can be the
    // very prepended module the `super` came FROM. See
    // `ClassEntry::foreign_value_names`.
    let f = value_method(anc, 0, name)
        .filter(|_| !value_row_is_foreign(anc, name))
        .or_else(|| crate::builtins::class_table(anc).and_then(|t| t(&name.to_string())))?;
    if let RubyValue::Object(o) = recv
        && let Some(root) = o.builtin_root()
        && crate::builtins::value_subclass::payload_owns(root, anc)
        && let Some(p) = o.builtin_payload()
    {
        let result = match f(&p, args, block) {
            Ok(r) => r,
            Err(e) => return Some(Err(e)),
        };
        return Some(Ok(crate::builtins::value_subclass::rewrap_self_return(
            result,
            &p,
            o,
            name.name_str(),
        )));
    }
    Some(f(recv, args, block))
}

/// Whether `anc`'s registered value row for `name` was contributed by an
/// ANCESTOR rather than defined on `anc` -- see
/// [`ClassEntry::foreign_value_names`].
fn value_row_is_foreign(anc: ClassId, name: Symbol) -> bool {
    REGISTRY.get().is_some_and(|r| {
        r.entries
            .get(&anc.0)
            .is_some_and(|e| e.foreign_value_names.contains(&name))
    })
}

/// The shared body of [`send_super_from`] and [`send_as_defined_in`]: walk
/// the receiver's ancestors from `start`, invoking the first OWN definition
/// of `name`. Only the entry position differs between them.
fn send_walking(
    recv: &RubyValue,
    start: usize,
    name: Symbol,
    args: &[RubyValue],
    block: Option<RubyValue>,
) -> Result<RubyValue, Signal> {
    // The two `MethodImpl` arms below take an `RObj`; a non-Object receiver
    // (an Integer, a String) never has one, and never reaches them either --
    // its definitions live in the value-method and builtin tables.
    let obj = match recv {
        RubyValue::Object(o) => Some(o.clone()),
        _ => None,
    };
    let ancestors = ancestors_of_value(recv.class_id());
    let method_name = name.to_string();
    for &anc in ancestors.iter().skip(start) {
        // Each position contributes its OWN definitions only -- never the
        // flattened `methods` table, whose winner at a position can be a
        // PREPENDED module's copy sitting BEFORE this position in the MRO
        // (probing it made a prepended method's `super` find itself,
        // recursing forever). Per position, most-derived source first:
        // a runtime-defined own method (the overlay), the registered own
        // implementation (`own_impls`), a user module's bridge / builtin
        // reopen (`value_methods` on that id), then the ancestor's native
        // builtin table (`BasicObject#initialize` is the one every `super`
        // chain bottoms out on).
        // An `undef_method` at this position terminates the walk, exactly as
        // it does for ordinary dispatch -- `super` must not reach past it into
        // a still-live ancestor definition.
        if crate::runtime_meta::is_live() && crate::runtime_meta::overlay_is_undefined(anc, name) {
            break;
        }
        if let Some(obj) = &obj {
            if crate::runtime_meta::is_live()
                && let Some(m) = crate::runtime_meta::overlay_own_method(anc, name)
            {
                return m.call(obj, args, block);
            }
            if let Some(m) = registry().super_target(anc, name) {
                return m.call(obj, args, block);
            }
        }
        if let Some(r) = probe_generic_row(recv, anc, name, args, block.clone()) {
            return r;
        }
    }
    Err(raise_method_missing(
        recv,
        &method_name,
        args,
        MissingReason::Super,
    ))
}

/// `super` inside a CLASS method (`def self.x`) -- the class-method channel
/// `send_super_from` (object receivers only) can't serve. Walks the
/// receiver class's ancestry resuming AFTER `defining_class`, probing per
/// ancestor: a runtime-defined class method (overlay), the registered
/// flattened `class_methods` table (each ancestor's table is resolution
/// from ITS OWN viewpoint -- own `def self.x`, extends, and
/// inherited-from-above copies in the right priority, so the first
/// non-module ancestor's winner IS the correct super target), then that
/// ancestor's builtin class-method table. `include`d modules never join a
/// singleton chain, so module ancestors are skipped. A `defining_class`
/// missing from the chain is a module serving through a singleton: one
/// PREPENDED there sits ABOVE its host's own table, so its `super` resumes
/// AT the host (own `def self.x` first, the prepend layer skipped -- or it
/// would call itself); an `extend`ed one starts right past the receiver's
/// own entry -- the nearest runtime approximation of "after the extended
/// module" (sibling extends of the same receiver are not modeled at
/// runtime; the registry records no per-class extends list).
pub fn send_super_class_from(
    recv_class: ClassId,
    defining_class: ClassId,
    name: Symbol,
    args: &[RubyValue],
    block: Option<RubyValue>,
) -> Result<RubyValue, Signal> {
    let ancestors = ancestors_of_value(recv_class);
    if let Some(pos) = ancestors.iter().position(|&a| a == defining_class) {
        return send_class_walking(recv_class, pos + 1, name, args, block);
    }
    if let Some(pos) = ancestors
        .iter()
        .position(|&a| crate::runtime_meta::has_singleton_prepend(a, defining_class))
    {
        // Another module prepended the same name BELOW this one resumes
        // first; only past the whole stack does the host's own row answer.
        if let Some(p) =
            crate::runtime_meta::singleton_prepend_super_below(ancestors[pos], defining_class, name)
        {
            return p.call_with_self_and_block(&RubyValue::Class(recv_class), args, block);
        }
        return send_class_walking_inner(recv_class, pos, true, name, args, block);
    }
    send_class_walking(recv_class, 1, name, args, block)
}

/// Invoke the CLASS method `name` starting the walk AT `from` -- the
/// class-method twin of [`send_from`], for a `Method` that `#super_method`
/// re-seated onto an ancestor's `def self.x`.
pub fn send_class_from(
    recv_class: ClassId,
    from: ClassId,
    name: Symbol,
    args: &[RubyValue],
    block: Option<RubyValue>,
) -> Result<RubyValue, Signal> {
    let start = ancestors_of_value(recv_class)
        .iter()
        .position(|&a| a == from)
        .unwrap_or(0);
    send_class_walking(recv_class, start, name, args, block)
}

/// The shared body of [`send_super_class_from`] and [`send_class_from`]:
/// walk `recv_class`'s ancestors from `start`, invoking the first own
/// `def self.<name>`. Only the entry position differs.
fn send_class_walking(
    recv_class: ClassId,
    start: usize,
    name: Symbol,
    args: &[RubyValue],
    block: Option<RubyValue>,
) -> Result<RubyValue, Signal> {
    send_class_walking_inner(recv_class, start, false, name, args, block)
}

/// `first_below_prepends` resumes a singleton-PREPENDED module method's
/// `super`: at the entry position the overlay probe skips the prepend layer
/// (the walk got here THROUGH it -- probing it again would re-enter the same
/// copy forever) so the host's shadowed `def self.<name>` answers instead.
fn send_class_walking_inner(
    recv_class: ClassId,
    start: usize,
    first_below_prepends: bool,
    name: Symbol,
    args: &[RubyValue],
    block: Option<RubyValue>,
) -> Result<RubyValue, Signal> {
    let recv = RubyValue::Class(recv_class);
    let method_name = name.to_string();
    for (i, &anc) in ancestors_of_value(recv_class)
        .iter()
        .enumerate()
        .skip(start)
    {
        if registry().entries.get(&anc.0).is_some_and(|e| e.is_module) {
            continue;
        }
        if crate::runtime_meta::is_live() {
            let overlay = match first_below_prepends && i == start {
                true => crate::runtime_meta::overlay_class_method_below_prepends(anc, name),
                false => crate::runtime_meta::overlay_class_method(anc, name),
            };
            if let Some(p) = overlay {
                return p.call_with_self_and_block(&recv, args, block);
            }
        }
        if let Some(f) = registry()
            .entries
            .get(&anc.0)
            .and_then(|e| e.class_methods.get(&name).copied())
        {
            return f(&recv, args, block);
        }
        if let Some(f) =
            crate::builtins::class_method_table(anc).and_then(|lookup| lookup(&method_name))
        {
            return f(&recv, args, block);
        }
    }
    // The singleton chain does not stop at the last ancestor: `#<Class:
    // BasicObject>` inherits from `Class` itself, so a class-method `super`
    // with nothing above it continues into `Class`'s own INSTANCE methods,
    // with the class object as `self`. That is where the default
    // allocate-then-`initialize` lives -- what a `def self.new` wrapping
    // construction reaches by `super` (rubygems'
    // `Gem::Package::TarWriter.new`). `send_walking` raises the same
    // `MissingReason::Super` if that comes up empty too.
    send_walking(&recv, 0, name, args, block)
}

/// Dispatch a `super` whose target the COMPILER resolved against the
/// receiver's singleton chain (the `extend M` shape -- sibling extends
/// interleave in an order only the compile-time chain knows; the runtime
/// registry records no per-class extends list). The target is either a
/// module's instance method serving as a class method (`module_instance`,
/// reached through the module's own value-method bridge) or an ancestor's
/// own `def self.x` (its registered `class_methods` row / builtin table).
/// `self` stays the RECEIVER class object throughout, like every `super`.
pub fn call_singleton_super_target(
    target: ClassId,
    module_instance: bool,
    recv_class: ClassId,
    name: Symbol,
    args: &[RubyValue],
    block: Option<RubyValue>,
) -> Result<RubyValue, Signal> {
    let recv = RubyValue::Class(recv_class);
    let method_name = name.to_string();
    if module_instance {
        // The RECEIVER's own emitted copy of the module's method first --
        // its `super` resolves the receiver's singleton chain, which the
        // module's generic bridge (emitted in the module's own context)
        // cannot. See `ClassEntry::singleton_super_targets`.
        if let Some(f) = registry()
            .entries
            .get(&recv_class.0)
            .and_then(|e| e.singleton_super_targets.get(&(target.0, name)).copied())
        {
            return f(&recv, args, block);
        }
        if let Some(f) = value_method(target, 0, name) {
            return f(&recv, args, block);
        }
    } else {
        if crate::runtime_meta::is_live()
            && let Some(p) = crate::runtime_meta::overlay_class_method(target, name)
        {
            return p.call_with_self_and_block(&recv, args, block);
        }
        if let Some(f) = registry()
            .entries
            .get(&target.0)
            .and_then(|e| e.class_methods.get(&name).copied())
        {
            return f(&recv, args, block);
        }
        if let Some(f) = crate::builtins::class_method_table(target).and_then(|t| t(&method_name)) {
            return f(&recv, args, block);
        }
    }
    Err(raise_method_missing(
        &recv,
        &method_name,
        args,
        MissingReason::Super,
    ))
}

/// Coerces a dynamic method-name value the way `send`/`__send__` do:
/// Symbol or String (real Ruby accepts both), anything else raising
/// CRuby's exact TypeError shape.
pub fn method_name_symbol(v: &RubyValue) -> Result<Symbol, Signal> {
    match v {
        RubyValue::Symbol(s) => Ok(*s),
        RubyValue::Str(s) => Ok(Symbol::intern(&s.lock().to_utf8_lossy())),
        other => Err(type_error!(
            "{} is not a symbol nor a string",
            other.inspect_string()
        )),
    }
}

/// The Kernel entry a [`reflect_dispatch_in`] site was written as.
#[derive(Clone, Copy, PartialEq, Eq, Debug)]
pub enum Reflect {
    Send,
    PublicSend,
    RespondTo,
    Method,
}

impl Reflect {
    /// The name as WRITTEN, which is both what the MRO is asked about and
    /// what an ordinary call dispatches when the answer is "shadowed".
    fn symbol(self) -> Symbol {
        match self {
            Reflect::Send => crate::symbol::wk::send(),
            Reflect::PublicSend => crate::symbol::wk::public_send(),
            Reflect::RespondTo => crate::symbol::wk::respond_to(),
            Reflect::Method => crate::symbol::wk::method(),
        }
    }
}

/// `recv.send(name, …)` / `#respond_to?` / `#method` where the compiler could
/// not prove WHICH of them the receiver's chain resolves to.
///
/// CRuby has no intrinsic for any of the three: each is an ordinary method on
/// `Kernel`, so a class defining its own -- `BasicSocket#send` writing bytes,
/// `Ractor#send` passing a message, any `def respond_to?` of your own --
/// simply wins the lookup because it sits earlier in the MRO. Only when the
/// lookup lands on Kernel's does the first argument get reinterpreted as a
/// method name. This asks that question once, then does whichever the answer
/// calls for.
///
/// `candidates` are the refinements active at the site, empty where there are
/// none. All three entries honour a refinement in real Ruby, and a receiver
/// whose class is only known at run time is exactly where the compiler cannot
/// fold that away.
pub fn reflect_dispatch_in(
    box_id: u32,
    recv: &RubyValue,
    entry: Reflect,
    args: &[RubyValue],
    block: Option<RubyValue>,
    candidates: &[(ClassId, ClassId, bool)],
) -> Result<RubyValue, Signal> {
    let written = entry.symbol();
    let shadowed = !matches!(
        method_owner(recv.class_id(), written),
        Some(KERNEL_CLASS) | Some(BASIC_OBJECT_CLASS) | None
    );
    if shadowed {
        return send_value_in(box_id, recv, written, args, block);
    }
    let Some((target, rest)) = args.split_first() else {
        return Err(match entry {
            Reflect::Send | Reflect::PublicSend => {
                crate::builtins::arg_error!("no method name given")
            }
            _ => crate::builtins::arg_error!("wrong number of arguments (given 0, expected 1)"),
        });
    };
    let target = method_name_symbol(target)?;
    match entry {
        Reflect::Send | Reflect::PublicSend => refined_send_dynamic(
            box_id,
            recv,
            target,
            rest,
            block,
            candidates,
            entry == Reflect::PublicSend,
        ),
        Reflect::RespondTo => Ok(RubyValue::Bool(refined_responds_to(
            recv,
            target,
            rest.first().is_some_and(|v| v.truthy()),
            candidates,
        )?)),
        Reflect::Method => refined_method(recv, target, candidates),
    }
}

/// A registry-OPTIONAL probe for a builtin-reopen method --
/// `None` when no registry is installed (this crate's own unit tests) or
/// the class carries no such method. The lookup key is the receiver's own
/// `class_id()`; see `ValueMethodFn`'s docs for why no ancestor walk is
/// needed. Used by `send_value`'s override-first stage and by
/// `display_with`/`inspect_with`'s `to_s`/`inspect` probes in `value.rs`.
pub(crate) fn value_method(id: ClassId, box_id: u32, name: Symbol) -> Option<ValueMethodFn> {
    REGISTRY.get()?.lookup_value_method(id, box_id, name)
}

/// The frozen registry's own instance method for `id`, CLONED out (a `fn`
/// copy or an `Arc` bump). The runtime overlay (`runtime_meta`) uses this to
/// walk a runtime class's frozen ancestors -- a `RuntimeClass < SomeUserClass`
/// instance inherits `SomeUserClass`'s materialized methods, which live in the
/// frozen table and can't be reached by the overlay's own maps. `None` when no
/// registry is installed (this crate's unit tests) or the class has no such
/// method.
pub(crate) fn registry_lookup_cloned(id: ClassId, name: Symbol) -> Option<MethodImpl> {
    REGISTRY.get()?.lookup(id, name).cloned()
}

/// [`registry_lookup_cloned`]'s own-implementation twin: what `id` itself
/// DEFINES, rather than what it answers.
///
/// A compile-time MODULE's `methods` table is emptied once materialization has
/// copied its bodies onto every includer, so the flat lookup above finds
/// nothing there. That is fine for a compile-time includer, which got a copy --
/// and wrong for a class that includes or prepends the module at RUNTIME, which
/// did not. Such a class's walk reached the module's position, found an empty
/// table, and carried on to the class itself: a prepended module correctly
/// listed FIRST in `ancestors` yet never reached by dispatch.
///
/// `own_impls` is where those bodies survive -- it is the set `super` already
/// walks for exactly this reason.
pub(crate) fn registry_own_impl_cloned(id: ClassId, name: Symbol) -> Option<MethodImpl> {
    REGISTRY.get()?.super_target(id, name).cloned()
}

/// A module/class's OWN value-method (the `ValueMethodFn` shape builtin modules
/// -- `Comparable`/`Enumerable`/`Kernel` -- register their instance methods
/// as), wrapped as a `MethodImpl` so `Object#extend` can copy it into an
/// object's singleton table. `box_id` 0 (the unboxed method set).
pub(crate) fn registry_value_method_impl(id: ClassId, name: Symbol) -> Option<MethodImpl> {
    let f: ValueMethodFn = REGISTRY.get()?.lookup_value_method(id, 0, name)?;
    Some(value_fn_impl(f))
}

/// An ancestor's NATIVE builtin row (`Struct#size`, `Comparable#between?`) as
/// an object-channel `MethodImpl` -- the last probe at each position of a
/// runtime class's walk, mirroring the step `send_value_in`'s own walk makes
/// after the value methods.
///
/// Without it a native row was invisible to a class born at runtime, and the
/// walk carried on to a FARTHER ancestor: `class T < Struct.new(:b)` with a
/// `module Enumerable; def size` reopen answered `Enumerable#size`, stepping
/// over `Struct#size` two positions nearer.
pub(crate) fn builtin_row_impl(id: ClassId, name: Symbol) -> Option<MethodImpl> {
    // The root `BasicObject#method_missing` is not an answer. It exists so a
    // USER override's `super` can reach it, and `super` gets there through its
    // own walk; resolving it HERE means nothing overrode `method_missing`, and
    // the miss path would then raise through a row that carries its own
    // generic reason -- losing the VCall/private/protected distinction the
    // caller was given, and turning `NameError: undefined local variable or
    // method` back into a plain `NoMethodError`.
    if id == zeo_abi::BASIC_OBJECT_CLASS && name == crate::symbol::wk::method_missing() {
        return None;
    }
    let f = crate::builtins::class_table(id)?(name.name_str())?;
    Some(MethodImpl::Dynamic(std::sync::Arc::new(
        move |recv: &RObj, args: &[RubyValue], block: Option<RubyValue>| {
            // The same payload bridge the main walk runs: a value-subclass
            // instance (`Class.new(Array)`) carries a `RubyValue::Array`
            // payload, and at its payload root the builtin row runs against
            // that value -- handing it the boxed object instead panicked the
            // row's own receiver downcast.
            if let Some(root) = recv.builtin_root()
                && crate::builtins::value_subclass::payload_owns(root, id)
                && let Some(p) = recv.builtin_payload()
            {
                let result = f(&p, args, block)?;
                return Ok(crate::builtins::value_subclass::rewrap_self_return(
                    result,
                    &p,
                    recv,
                    name.name_str(),
                ));
            }
            f(&RubyValue::Object(recv.clone()), args, block)
        },
    )))
}

fn value_fn_impl(f: ValueMethodFn) -> MethodImpl {
    MethodImpl::Dynamic(std::sync::Arc::new(
        move |recv: &RObj, args: &[RubyValue], block: Option<RubyValue>| {
            f(&RubyValue::Object(recv.clone()), args, block)
        },
    ))
}

/// The registered Ruby-visible (fully-qualified) name of `id` -- `None`
/// when the registry isn't installed yet or has no such entry (this
/// crate's own unit tests; a real generated program registers everything
/// before any statement runs). See `RubyValue::Class`'s display arms for
/// the fallback rendering.
pub fn class_name(id: ClassId) -> Option<String> {
    // A `refine` holder renders as ruby renders it, from the pair it refines
    // -- not as the unwritable `#refinement:String` the compiler keys it by.
    // Still leading-`#`, so `Module#name` keeps answering nil.
    if let Some((module, target)) = refinement_of(id) {
        return Some(format!(
            "#<refinement:{}@{}>",
            class_name(target).unwrap_or_default(),
            class_name(module).unwrap_or_default(),
        ));
    }
    if let Some(name) = REGISTRY
        .get()
        .and_then(|r| r.entries.get(&id.0))
        .map(|e| e.name.clone())
    {
        return Some(name);
    }
    if crate::runtime_meta::is_live() {
        return crate::runtime_meta::overlay_class_name(id);
    }
    None
}

/// The name `Module#name` reports: `None` unless the class is really reachable
/// by a CONSTANT PATH. [`class_name`] always answers something printable, so an
/// anonymous or singleton class gets a `#<Class:...>` rendering there -- which
/// is exactly what tells the two apart, since no constant path begins with `#`.
pub fn class_real_name(id: ClassId) -> Option<String> {
    class_name(id).filter(|n| !n.starts_with('#'))
}

/// The ids of classes/modules an explicit `Foo.freeze` has frozen -- a
/// side registry keyed by class id (NOT a pointer-keyed table: ids are
/// minted once and never reused, so there is no ABA hazard), covering both
/// AOT-registered classes and `runtime_meta`'s overlay classes with one
/// mechanism. Empty in the overwhelmingly common no-`freeze` program: the
/// guard paths (cvar/civar writes, runtime method definition) pay one
/// short-held lock + hash probe only when actually reached.
static FROZEN_CLASSES: std::sync::LazyLock<parking_lot::Mutex<FSet<u32>>> =
    std::sync::LazyLock::new(|| parking_lot::Mutex::new(FSet::default()));

/// `Foo.frozen?`'s storage half -- see `FROZEN_CLASSES`.
pub fn class_frozen(id: ClassId) -> bool {
    FROZEN_CLASSES.lock().contains(&id.0)
}

/// The `FrozenError` every mutation of a frozen class/module raises --
/// CRuby's exact shape (`can't modify frozen Class: Foo` /
/// `can't modify frozen Module: Bar`, oracle-verified): the receiver's own
/// class kind, then the frozen class's name (its inspect).
pub fn frozen_class_error(id: ClassId) -> Signal {
    let kind = if class_is_module(id).unwrap_or(false) {
        "Module"
    } else {
        "Class"
    };
    let name = class_name(id).unwrap_or_else(|| format!("#<Class:{}>", id.0));
    frozen_error!("can't modify frozen {kind}: {name}")
}

/// A REOPEN of a class the program has since frozen -- `Fz.freeze; class Fz;
/// def x; end; end` is `FrozenError` in ruby, and the body never runs.
///
/// zeo's compile-time tables already carry that body's definitions, so the
/// raise is not enough: `names` -- the ones ONLY this body would have
/// installed -- are retired first, which is what makes `Fz.instance_methods
/// (false)` answer `[]` and a call to one raise `NoMethodError`, exactly as
/// they do when the definition never happened.
pub fn guard_class_reopen(id: ClassId, names: &[&str]) -> Result<(), Signal> {
    if !class_frozen(id) {
        return Ok(());
    }
    crate::runtime_meta::retire_names(id, names);
    Err(frozen_class_error(id))
}

/// `Foo.freeze`'s storage half -- see `FROZEN_CLASSES`. Repeat calls are
/// harmless no-ops (CRuby's already-frozen guard).
pub fn class_set_frozen(id: ClassId) {
    FROZEN_CLASSES.lock().insert(id.0);
}

/// Reverse of `class_name`: the id a fully-qualified class/module NAME is
/// registered under (`"Integer"`, `"Math"`, a user `"Widget"`), or `None`.
/// The eval VM uses this to resolve a bare class-name constant like
/// `eval("Integer")` -- codegen resolves those statically and so never
/// `const_set`s them, leaving the runtime constants table without them.
/// The compile-time box surrogates, derived ONCE from the installed
/// registry's name table: `#<Ruby::Box:N>` is the exact name the analyze
/// pass mints per box. One parse at first ask replaces a `format!` + name
/// hash (or a name parse-back) at every ask; Track 7's `BoxTable` replaces
/// this derivation with real registration. Registry-less (unit tests) asks
/// answer `None` WITHOUT caching, so a later install still populates.
fn box_surrogates() -> Option<&'static (crate::FMap<u32, u32>, crate::FMap<u32, u32>)> {
    static MAPS: OnceLock<(crate::FMap<u32, u32>, crate::FMap<u32, u32>)> = OnceLock::new();
    if let Some(m) = MAPS.get() {
        return Some(m);
    }
    let reg = REGISTRY.get()?;
    Some(MAPS.get_or_init(|| {
        let mut by_box = crate::FMap::default();
        let mut by_class = crate::FMap::default();
        for (name, id) in &reg.by_name {
            if let Some(n) = name
                .strip_prefix("#<Ruby::Box:")
                .and_then(|r| r.strip_suffix('>'))
                .and_then(|d| d.parse::<u32>().ok())
            {
                by_box.insert(n, *id);
                by_class.insert(*id, n);
            }
        }
        (by_box, by_class)
    }))
}

/// The surrogate class owning box `box_id`'s top-level constants, if one was
/// compiled in.
pub(crate) fn box_surrogate_class(box_id: u32) -> Option<ClassId> {
    box_surrogates()?.0.get(&box_id).map(|&c| ClassId(c))
}

/// The box a surrogate class belongs to -- [`box_surrogate_class`]'s reverse.
pub(crate) fn box_of_surrogate_class(cid: ClassId) -> Option<u32> {
    box_surrogates()?.1.get(&cid.0).copied()
}

pub fn class_id_by_name(name: &str) -> Option<ClassId> {
    REGISTRY
        .get()
        .and_then(|r| r.by_name.get(name))
        .map(|&id| ClassId(id))
        // A registered-but-CONCEALED class (a definition under a runtime
        // guard that has not run yet) is no constant of anyone's.
        .filter(|&ClassId(id)| !crate::constants::class_concealed(id))
        // Runtime-defined classes (e.g. `Struct.new` assigned to a constant)
        // live in the overlay, not the frozen registry -- fall back so
        // `Marshal.load` resolves them by name too.
        .or_else(|| crate::runtime_meta::runtime_class_id_by_name(name))
}

/// The classes and modules nested DIRECTLY inside `id`, by their unqualified
/// names -- `["Error", "ZStream", ...]` for `Zlib`.
///
/// A nested class IS a constant of the module it sits in, but zeo registers it
/// by qualified NAME rather than through the constant table: codegen resolves
/// `Zlib::Error` statically, so nothing ever `const_set`s it. `Module#constants`
/// is where the difference becomes visible, and this is what it consults --
/// the same shape as `class_id_by_name`, read the other way round.
pub fn nested_class_names(id: ClassId) -> Vec<String> {
    let Some(registry) = REGISTRY.get() else {
        return Vec::new();
    };
    // `Object` is the lexical parent of every TOP-LEVEL class, which the
    // registry files under a bare name rather than a `Prefix::` one -- so
    // `Object.constants` has to match the names with no separator at all.
    // Without this it listed `RUBY_VERSION` and the other seeded constants
    // while omitting `Array`, `String` and ~104 more.
    if id == crate::ClassId(0) {
        return registry
            .by_name
            .iter()
            .filter(|&(_, &cid)| !crate::constants::class_concealed(cid))
            .map(|(name, _)| name)
            .filter(|name| !name.contains("::") && !name.contains('#') && !name.contains('.'))
            .map(String::clone)
            .collect();
    }
    let Some(prefix) = class_name(id) else {
        return Vec::new();
    };
    let prefix = format!("{prefix}::");
    registry
        .by_name
        .iter()
        .filter(|&(_, &cid)| !crate::constants::class_concealed(cid))
        .filter_map(|(name, _)| name.strip_prefix(&prefix))
        // DIRECTLY nested only: `Zlib::GzipFile::Error` belongs to
        // `Zlib::GzipFile`'s list, not to `Zlib`'s.
        .filter(|rest| !rest.contains("::"))
        // A `#` marks a name the source could never have written -- a
        // `refine` holder -- which is therefore no constant of anyone's.
        .filter(|rest| !rest.contains('#'))
        .map(str::to_string)
        .collect()
}

/// Whether `id` is a `refine` holder, whose `.class` is `Refinement`
/// rather than `Module`.
pub fn class_is_refinement(id: ClassId) -> bool {
    refinement_of(id).is_some()
}

/// `(refining module, refined target)` for a `refine` holder -- `None` for
/// every ordinary module. A holder can be compiled (the registry's mark) or
/// minted by a RUNTIME `refine` (the overlay's).
pub fn refinement_of(id: ClassId) -> Option<(ClassId, ClassId)> {
    if let Some(pair) = REGISTRY
        .get()
        .and_then(|r| r.entries.get(&id.0))
        .and_then(|e| e.refinement_of)
    {
        return Some(pair);
    }
    if crate::runtime_meta::is_live() {
        return crate::runtime_meta::overlay_refinement_of(id);
    }
    None
}

/// The holders `module`'s own `refine` blocks minted, in the order the source
/// wrote them -- ids are handed out as the compiler walks the body, so id
/// order IS declaration order. What `Module#refinements` answers.
pub fn refinements_of(module: ClassId) -> Vec<ClassId> {
    let Some(r) = REGISTRY.get() else {
        return Vec::new();
    };
    let mut holders: Vec<ClassId> = r
        .entries
        .iter()
        .filter(|(_, e)| e.refinement_of.is_some_and(|(m, _)| m == module))
        .map(|(&id, _)| ClassId(id))
        .collect();
    holders.sort_by_key(|c| c.0);
    // Runtime-minted holders come after every compiled one -- their ids are
    // allocated above the frozen range, so a plain append keeps the order.
    if crate::runtime_meta::is_live() {
        holders.extend(crate::runtime_meta::overlay_refinements_of(module));
    }
    holders
}

/// Whether `id` names a MODULE (drives `Widget.class` -> `Class` vs
/// `Enumerable.class` -> `Module`) -- same graceful `None` as `class_name`.
pub fn class_is_module(id: ClassId) -> Option<bool> {
    if let Some(m) = REGISTRY
        .get()
        .and_then(|r| r.entries.get(&id.0))
        .map(|e| e.is_module)
    {
        return Some(m);
    }
    if crate::runtime_meta::is_live() {
        return crate::runtime_meta::overlay_is_module(id);
    }
    None
}

/// A registry probe-and-call for the runtime PROTOCOL dispatches (Phase
/// 16.2): user `==`/`<=>`/`to_s`/`inspect`/`hash` reached from deep inside
/// pure helpers (`rb_eq`, `display_with`, `hash_key`) that can't route
/// through `send` (whose `method_missing`/NoMethodError fallbacks must NOT
/// fire for a protocol probe). `None` = no such method (or no registry --
/// this crate's own unit tests), letting each caller apply its own
/// default; the method, when present, is the MATERIALIZED entry, so
/// inherited/mixed-in definitions resolve exactly like a real call.
pub(crate) fn call_user_method(
    recv: &RObj,
    name: &str,
    args: &[RubyValue],
) -> Option<Result<RubyValue, Signal>> {
    let id = recv.class_id();
    if let Some(f) = REGISTRY
        .get()
        .and_then(|r| r.lookup_mro(id, Symbol::intern(name)))
    {
        return Some(f.call(recv, args, None));
    }
    // A RUNTIME-defined method on the receiver's OWN class (a `define_method`
    // delta, or a native `Struct`/`Data` class's `inspect`/`to_s`/`hash`
    // forwarder) -- so `p`/interpolation honour it, not just `send`. THIS
    // class only, no ancestor walk (see the reentrancy note below).
    if crate::runtime_meta::is_live()
        && let Some(m) = crate::runtime_meta::overlay_own_method(id, Symbol::intern(name))
    {
        return Some(m.call(recv, args, None));
    }
    // A RUNTIME-RESIDENT class (`Time`, `File`, ... -- plan P-B) is an
    // `Object(RObj)` with no registry entry, but it does have a builtin
    // table. Without this probe its own `to_s`/`inspect`/`hash` would be
    // invisible to every caller here -- stringifying a Time would answer
    // `#<Time>` rather than running `Time#to_s`.
    //
    // The receiver's OWN class only, deliberately NOT its ancestors: this is
    // called from `display_with`/`inspect_with`, and `Kernel`'s own `to_s`
    // row renders via `to_display_string` -- walking up to it would recurse
    // until the stack died (it did). The ancestor walk belongs to `send_in`,
    // which has no such reentrancy; what this needs is only "does THIS class
    // define the method itself".
    if let Some(f) = crate::builtins::class_table(id).and_then(|lookup| lookup(name)) {
        return Some(f(&RubyValue::Object(recv.clone()), args, None));
    }
    // ...and an ANCESTOR's builtin table, for a builtin SUBCLASS of a builtin
    // (`DateTime < Date`, whose own table declares only the rows CRuby
    // publishes on the subclass -- `p dt` reached `Object`'s default repr
    // because `Date#inspect` sits one class up).
    //
    // Bounded at `Object`, which is the whole reason the probe above is
    // own-class-only: `Kernel`'s `to_s`/`inspect` rows render through
    // `to_display_string`, so walking into them recurses until the stack dies.
    // A value-subclass payload is excluded too -- `class Tag < String` renders
    // through the caller's payload arm, not through `String`'s rows.
    if recv.builtin_payload().is_none()
        && let Some(reg) = REGISTRY.get()
    {
        for &anc in reg.ancestors_of(id).iter().skip(1) {
            if anc == zeo_abi::OBJECT_CLASS
                || anc == zeo_abi::KERNEL_CLASS
                || anc == zeo_abi::BASIC_OBJECT_CLASS
            {
                break;
            }
            if let Some(f) = crate::builtins::class_table(anc).and_then(|lookup| lookup(name)) {
                return Some(f(&RubyValue::Object(recv.clone()), args, None));
            }
        }
    }
    // A COMPILED `Struct`/`Data` inherits its whole protocol from
    // `Struct`/`Data`'s own table, which the walk above cannot see: those rows
    // are value methods, not registry `methods`. `S.new(1) == S.new(1)`
    // reaches `Struct#==` only here, because `rb_eq` asks this function and
    // nothing else.
    //
    // Exactly those two tables, never a general ancestor walk: probing
    // `String`'s on a `class Tag < String` recurses until the stack dies.
    if crate::builtins::rstruct::meta_of(id).is_some() {
        for root in [zeo_abi::STRUCT_CLASS, zeo_abi::DATA_CLASS] {
            if !ancestors_contain(id, root) {
                continue;
            }
            if let Some(f) = crate::builtins::class_table(root).and_then(|lookup| lookup(name)) {
                return Some(f(&RubyValue::Object(recv.clone()), args, None));
            }
        }
    }
    None
}

/// A registry-optional ancestry probe -- `false` when no
/// registry is installed (this crate's own unit tests), where `is_a`'s
/// hard `registry()` access would panic. Used by `rb_eq`'s Comparable
/// fallback, which must stay callable from anywhere.
pub(crate) fn ancestors_contain(id: ClassId, target: ClassId) -> bool {
    REGISTRY
        .get()
        .is_some_and(|r| r.ancestors_of(id).contains(&target))
}

/// Runs `initialize` on a freshly-constructed instance IF the class
/// defines one -- the shared tail of every `ConstructorFn` (`ruby_class!`'s
/// `__construct`). Deliberately a direct registry lookup, NOT `send`: a
/// class with no `initialize` must not trip the `method_missing` fallback.
/// With no `initialize`, arguments are rejected (real Ruby's
/// `Object#initialize` takes none) with a rescuable `ArgumentError`.
pub fn run_initialize(
    class: ClassId,
    recv: &RObj,
    args: &[RubyValue],
    block: Option<RubyValue>,
) -> Result<(), Signal> {
    // With a live overlay, `initialize` resolves like any other instance
    // method -- overlay delta first, per ancestor (`snapshot_instance_method`).
    // A runtime `define_method :initialize` -- or a lazily-loaded unit's
    // `def initialize`, registered but not promised -- lives ONLY there, and
    // the registry walk below would fall through to `BasicObject#initialize`'s
    // zero-arity reject.
    if crate::runtime_meta::is_live()
        && let Some(f) =
            crate::runtime_meta::snapshot_instance_method(class, crate::symbol::wk::initialize())
    {
        f.call(recv, args, block)?;
        return Ok(());
    }
    let init = crate::symbol::wk::initialize();
    // Per ancestor, most-derived first, BOTH channels: the object-channel row
    // (`lookup`) and the VALUE row a builtin REOPEN registers. `lookup_mro`
    // reads only the first, so a namespace-slot builtin whose whole body is
    // Ruby (`WeakRef`, defined in the vendored gem) was walked straight past
    // into its SUPERCLASS's `initialize`.
    for &anc in ancestors_of_value(class) {
        if crate::runtime_meta::is_live() && crate::runtime_meta::overlay_is_undefined(anc, init) {
            break;
        }
        if let Some(f) = registry().lookup(anc, init) {
            f.call(recv, args, block)?;
            return Ok(());
        }
        if let Some(f) = value_method(anc, 0, init) {
            f(&RubyValue::Object(recv.clone()), args, block)?;
            return Ok(());
        }
    }
    // A RUNTIME class id (`Class.new(StandardError)`) is in no registry entry at
    // all, so the walk above cannot even reach its ancestors. Its chain lives in
    // the overlay, which is where a caller holding a bare class -- rather than a
    // receiver `send_in` could resolve from -- has to ask.
    if crate::runtime_meta::is_live()
        && let Some(f) =
            crate::runtime_meta::runtime_class_method(class, crate::symbol::wk::initialize())
    {
        f.call(recv, args, block)?;
        return Ok(());
    }
    // No user `initialize` at all, so the inherited `Object#initialize`
    // takes no arguments. A RAISE, not a panic (plan G1): real Ruby resolves
    // arity at runtime and the error is rescuable -- `rescue ArgumentError`
    // around a bad `.new` is a corpus idiom, and a panic is uncatchable.
    // Message shape oracle-verified: CRuby says "wrong number of arguments
    // (given 2, expected 0)" with no method name in it, and the backtrace's
    // innermost row is `'BasicObject#initialize'` at the caller's line.
    if !args.is_empty() {
        let __frame = crate::frames::synthetic_c_frame("BasicObject#initialize");
        return Err(arg_error!(
            "wrong number of arguments (given {}, expected 0)",
            args.len()
        ));
    }
    Ok(())
}

thread_local! {
    /// The method most recently entered via `send_in`/`send_value_in` -- the
    /// diagnostic breadcrumb `ZEO_ARITY_DEBUG` reads to name which method an
    /// "wrong number of arguments" error came from (the message CRuby, and so
    /// we, deliberately leave method-less). Set at dispatch entry, so at the
    /// point a builtin's `arity!` guard raises it still names that builtin.
    static CURRENT_METHOD: std::cell::Cell<Option<Symbol>> = const { std::cell::Cell::new(None) };
}

/// Whether `ZEO_ARITY_DEBUG` is set -- read once, so the cold attribution
/// path (`arity_debug_context`) costs a
/// bool load per dispatch instead of an unconditional thread-local write.
static ARITY_DEBUG: std::sync::LazyLock<bool> =
    std::sync::LazyLock::new(|| std::env::var_os("ZEO_ARITY_DEBUG").is_some());

/// Record the method being dispatched (for `ZEO_ARITY_DEBUG`). The guard bit
/// rides in the gate byte the dispatch path already loads
/// (`runtime_meta::gates_arity_debug`, armed once at startup) -- the old
/// `LazyLock<bool>` was a second hot-path flag word, the exact shape that
/// once measured 2.6% on dispatch.
#[inline]
fn note_dispatch(name: Symbol) {
    note_dispatch_gated(crate::runtime_meta::gates(), name);
}

/// [`note_dispatch`] for a caller that already has the gates byte in a
/// register. The two cached send paths load it once at entry to decide the
/// fast route and then called `note_dispatch`, which loaded it again -- an
/// atomic re-read per hit on the hottest path in every generated program.
#[inline]
fn note_dispatch_gated(gates: u8, name: Symbol) {
    if crate::runtime_meta::gates_arity_debug(gates) {
        CURRENT_METHOD.with(|c| c.set(Some(name)));
    }
}

/// Under `ZEO_ARITY_DEBUG`, append ` [method: X]` to an arity error so the
/// conformance triage can attribute the otherwise method-less
/// "wrong number of arguments" pile. A no-op (and no env lookup on the common
/// path) unless the message is an arity error.
fn arity_debug_context(msg: String) -> String {
    if !msg.starts_with("wrong number of arguments") || !*ARITY_DEBUG {
        return msg;
    }
    match CURRENT_METHOD.with(|c| c.get()) {
        Some(sym) => format!("{msg} [method: {}]", sym.name_str()),
        None => msg,
    }
}

/// The general dispatcher -- reached only on Path 2 (see module docs).
/// Since every reachable method (own, inherited, or mixed-in) is already
/// MATERIALIZED directly onto its receiver's own class at zeo compile
/// time -- monomorphization, not cloning-with-shadow-names -- this is a
/// FLAT lookup on the receiver's
/// own class -- no ancestor walk needed here at all, only for `is_a`
/// (above), which real dispatch doesn't need.
///
/// `block` is threaded through to whichever `MethodFn` is actually found --
/// including the `method_missing` fallback, matching real Ruby's own
/// `method_missing(name, *args, &block)` protocol.
/// Dynamic dispatch against ANY `RubyValue` receiver (closing
/// the long-standing "Poly-dispatch gap"): an `Object` goes through `send`'s
/// registry exactly as before; a BUILT-IN receiver (Array/Hash/String/...)
/// dispatches against a curated method table over the existing collection
/// helpers -- what makes `@items << x`, `@hash[k] = v`, `ks.length` work on
/// ivars/params/any dynamically-typed value. Codegen's every Poly-receiver
/// fallback (ordinary calls, `send`/`public_send`, safe-nav, and the
/// runtime OPERATOR fallback's non-numeric case) routes here.
///
/// The table is deliberately curated, not exhaustive: entries exist for the
/// operations the static `try_collection_dispatch` fast path also supports
/// (extended as packages need them); anything else raises the same real,
/// rescuable `NoMethodError` an unknown Object method does -- with the
/// builtin class's REAL name in the message (better than `send`'s
/// documented class-id approximation, since builtin names are known here).
pub fn send_value(
    recv: &RubyValue,
    name: Symbol,
    args: &[RubyValue],
    block: Option<RubyValue>,
) -> Result<RubyValue, Signal> {
    send_value_in(0, recv, name, args, block)
}

/// A `def` in expression position (inside a block) installs on the "default
/// definee", which in ruby belongs to the FRAME and is NOT `self`. An ordinary
/// block changes it not at all, so it stays the CREF's -- `cref`, which
/// codegen knows outright. Two callers replace it, and only the runtime knows
/// they are on the stack:
///
/// * `instance_eval`/`instance_exec` -- the receiver's singleton class. That
///   is how `SingleForwardable` installs its delegators: it builds a
///   `proc { def name(...) ... end }` and `instance_eval`s it.
/// * `class_eval`/`class_exec`/`Class.new`/`Module.new` -- the module itself,
///   which is why `Class.new { def built; end }` gives the ANONYMOUS class an
///   instance method though the block was written at the top level.
///
/// Deriving the definee from `self` instead answers all three of those
/// correctly and every other block wrongly: `[1].each { def m; end }` and a
/// `def` inside a `def` both came out as singleton methods of whatever object
/// happened to be self, so `Object` never gained them.
pub fn define_in_default_definee(
    cref: &RubyValue,
    slf: &RubyValue,
    name: Symbol,
    body: RubyValue,
    private: bool,
) -> Result<RubyValue, Signal> {
    // `(definee, installer, the cref's own -- the only one the caller's
    // top-level verdict is about)`.
    let (definee, installer, from_cref) = if crate::runtime_meta::singleton_definee(slf) {
        (slf.clone(), "define_singleton_method", false)
    } else if let Some(cid) = crate::runtime_meta::module_definee(slf) {
        (RubyValue::Class(cid), "define_method", false)
    } else {
        (cref.clone(), "define_method", true)
    };
    let out = send_value(
        &definee,
        Symbol::intern(installer),
        &[RubyValue::Symbol(name), body],
        None,
    )?;
    // A `def` written at the TOP LEVEL is a PRIVATE instance method of Object,
    // however it is spelled -- `p(def m; end)` is the same definition as a
    // bare one, and only the caller reads its `:m`. `define_method` installs
    // public, so the mark is a second step. The caller decides: it is a
    // question about where the `def` was WRITTEN, which is compile-time
    // knowledge, and an `*_eval` can put this same call on any object.
    if private
        && from_cref
        && let RubyValue::Class(id) = &definee
    {
        crate::runtime_meta::runtime_set_visibility(
            *id,
            &[RubyValue::Symbol(name)],
            MethodVisibility::Private,
        )?;
    }
    Ok(out)
}

/// The `alias` KEYWORD in expression position (inside a block or method
/// body): it aliases on the frame's DEFAULT DEFINEE, resolved exactly as
/// [`define_in_default_definee`] resolves a `def`'s -- the receiver's
/// SINGLETON under `instance_eval`/`instance_exec` (how rspec's top-level DSL
/// pairs `def shared_examples` with `alias shared_context shared_examples`
/// on the `RSpec` module object), the module itself under `class_eval`/
/// `class_exec`/`Class.new`, and the cref's class otherwise. Distinct from
/// `Module#alias_method`, which always operates on its RECEIVER.
pub fn alias_in_default_definee(
    cref: &RubyValue,
    slf: &RubyValue,
    new: RubyValue,
    old: RubyValue,
) -> Result<RubyValue, Signal> {
    let definee = if crate::runtime_meta::singleton_definee(slf) {
        send_value(slf, Symbol::intern("singleton_class"), &[], None)?
    } else if let Some(cid) = crate::runtime_meta::module_definee(slf) {
        RubyValue::Class(cid)
    } else {
        cref.clone()
    };
    send_value(&definee, Symbol::intern("alias_method"), &[new, old], None)
}

/// `recv.class` for the codegen `.class` fast path on a dynamically-typed
/// receiver: normally the receiver's class value, but a Struct/Data instance
/// with a member literally named `class` (`Data.define(:class, :hash)`) has
/// that accessor shadow Kernel#class -- the fold that emits this can't see the
/// runtime-minted member, so the shadow is resolved here. Infallible (a member
/// read), so the fold stays a plain expression.
pub fn value_class(recv: &RubyValue) -> RubyValue {
    if let RubyValue::Object(o) = recv
        && let Some(v) = crate::builtins::rstruct::member_value_named(o, "class")
    {
        return v;
    }
    RubyValue::Class(recv.class_id())
}

/// The `old` name behind a builtin-alias row visible to instances of `id` --
/// closest ancestor wins, so a subclass resolves an alias its parent (or an
/// included module) declared. `None` for every ordinary name; consulted only
/// on the send MISS paths, so a real method of the same name always beats it.
/// See `ClassEntry::aliases`.
pub(crate) fn alias_target(id: ClassId, name: Symbol) -> Option<Symbol> {
    let r = REGISTRY.get()?;
    for &anc in ancestors_of_value(id) {
        if let Some(e) = r.entries.get(&anc.0)
            && let Some(&old) = e.aliases.get(&name)
        {
            return Some(old);
        }
    }
    None
}

/// [`alias_target`]'s singleton-side twin: the class method `name` on `id`
/// rewrites to, from the closest ancestor that declares the row. Consulted only
/// once every real class-method probe has missed, so a genuine `def self.[]`
/// always beats an `alias [] new`. See `ClassEntry::class_aliases`.
pub(crate) fn class_alias_target(id: ClassId, name: Symbol) -> Option<Symbol> {
    let r = REGISTRY.get()?;
    for &anc in ancestors_of_value(id) {
        if let Some(e) = r.entries.get(&anc.0)
            && let Some(&old) = e.class_aliases.get(&name)
        {
            return Some(old);
        }
    }
    None
}

/// Parse-special Kernel names with NO runtime dispatch row: statically-
/// resolved call sites compile them directly, so an alias of one is valid
/// even though no table can prove it. `validate_aliases` skips them.
pub(crate) const PARSE_SPECIAL_KERNEL: &[&str] = &[
    "block_given?",
    "iterator?",
    "__method__",
    "__callee__",
    "binding",
];

/// Validates every registered builtin-alias row (see `register_alias`) --
/// called once from generated `main`'s fallible closure, right after the
/// registry installs: an alias whose source resolves NOWHERE for instances
/// of its class is `NameError`, raised at program start exactly when real
/// Ruby raises it (the `alias_method` in the class body executing). Walked
/// in id order (superclasses precede subclasses) with sorted names, so the
/// first error is deterministic.
pub fn validate_aliases() -> Result<(), Signal> {
    let Some(r) = REGISTRY.get() else {
        return Ok(());
    };
    let mut ids: Vec<u32> = r.entries.keys().copied().collect();
    ids.sort_unstable();
    for id in ids {
        validate_class_aliases(ClassId(id))?;
    }
    Ok(())
}

/// One class's builtin-alias sources, checked where CRuby checks them: as that
/// class's BODY runs. A source can be created by the body itself -- bundler's
/// `Runtime` does `definition_method :specs` (a `define_method` wrapper) and
/// then `alias_method :gems, :specs` -- so a single sweep before any body has
/// run answers "undefined" for a method that is about to exist.
pub fn validate_class_aliases(id: ClassId) -> Result<(), Signal> {
    let Some(r) = REGISTRY.get() else {
        return Ok(());
    };
    let Some(entry) = r.entries.get(&id.0) else {
        return Ok(());
    };
    if entry.aliases.is_empty() {
        return Ok(());
    }
    let mut olds: Vec<Symbol> = entry.aliases.values().copied().collect();
    olds.sort_by_key(|s| s.name_str());
    olds.dedup();
    for old in olds {
        let n = old.name_str();
        if PARSE_SPECIAL_KERNEL.contains(&n) {
            continue;
        }
        let resolves = ancestors_of_value(id).iter().any(|&anc| {
            r.lookup(anc, old).is_some()
                || r.lookup_value_method(anc, 0, old).is_some()
                || crate::builtins::class_table(anc).is_some_and(|t| t(n).is_some())
                || crate::runtime_meta::overlay_own_method(anc, old).is_some()
        });
        if !resolves {
            let kind = if entry.is_module { "module" } else { "class" };
            return Err(crate::builtins::name_error!(
                "undefined method '{n}' for {kind} '{}'",
                entry.name
            ));
        }
    }
    Ok(())
}

/// `public_send`'s dispatch: [`send_value_in`] plus the visibility gate.
///
/// CRuby implements `public_send` as an ordinary send carrying the
/// `CALL_PUBLIC` scope, and `rb_method_call_status` (`vm_eval.c:837`) then
/// rejects private AND protected targets. Protected is rejected
/// unconditionally here -- normally it is receiver-sensitive, allowed when the
/// CALLER's `self` is a kind of the method's owner, but `public_send` passes
/// `Qundef` as that self (`vm_eval.c:1230`), a sentinel nothing can ever be a
/// kind of. Hence the plain `!= Public` test: no relatedness relaxation
/// applies, which is what makes `public_send` stricter than a plain
/// explicit-receiver call.
///
/// This is a RUNTIME check by necessity, not by preference: visibility can be
/// changed after the fact (`private :foo`), and the method name reaching
/// `public_send` is frequently a runtime value.
pub fn send_value_public_in(
    box_id: u32,
    recv: &RubyValue,
    name: Symbol,
    args: &[RubyValue],
    block: Option<RubyValue>,
) -> Result<RubyValue, Signal> {
    // A CLASS receiver's class methods have their own visibility table -- the
    // instance walk below reads Class/Module's, which says nothing about them.
    if let RubyValue::Class(cid) = recv
        && class_method_is_private(*cid, name)
    {
        return Err(raise_method_missing(
            recv,
            &name.to_string(),
            args,
            MissingReason::Private,
        ));
    }
    let reason = match instance_method_visibility(recv.class_id(), name) {
        Some(MethodVisibility::Private) => Some(MissingReason::Private),
        Some(MethodVisibility::Protected) => Some(MissingReason::Protected),
        _ => None,
    };
    match reason {
        Some(reason) => Err(raise_method_missing(recv, &name.to_string(), args, reason)),
        None => send_value_in(box_id, recv, name, args, block),
    }
}

/// [`send_value`] with the CALLER's box.
///
/// The box is the statically-known defining box every codegen
/// dynamic-dispatch site passes -- the AOT translation of CRuby's
/// `cme->def->box`, with no frame walk. Only the per-ancestor value-method
/// probe consumes it: a box's builtin patches resolve from that box's code,
/// and root patches resolve everywhere.
///
/// This crate's own internal callers, such as Enumerable driving `each` or
/// Comparable driving `<=>`, go through the box-0 wrapper instead. Builtins
/// run in ROOT, which faithfully reproduces CRuby's documented
/// builtins-call-builtins leak.
pub fn send_value_in(
    box_id: u32,
    recv: &RubyValue,
    name: Symbol,
    args: &[RubyValue],
    block: Option<RubyValue>,
) -> Result<RubyValue, Signal> {
    send_value_in_reason(box_id, recv, name, args, block, MissingReason::NoEntry)
}

/// The holder module whose refined `name` answers for `recv`, or `None` to
/// fall through to ordinary dispatch. `candidates` is `(refined class,
/// holder, singleton)` in most-recently-activated-first order, decided at
/// compile time from the `using` scopes covering the call site; the only
/// runtime question left is whether the receiver is actually of the refined
/// class. A SINGLETON candidate (`refine Range.singleton_class`) refines
/// CLASS methods, so it matches a Class receiver descending from the target
/// where a plain one matches an instance of it.
pub fn refinement_home(
    recv: &RubyValue,
    name: Symbol,
    candidates: &[(ClassId, ClassId, bool)],
) -> Option<ClassId> {
    let cls = recv.class_id();
    candidates.iter().find_map(|&(target, holder, singleton)| {
        let applies = match singleton {
            false => is_a(cls, target),
            true => matches!(recv, RubyValue::Class(c) if is_a(*c, target)),
        };
        (applies && holder_defines(holder, name)).then_some(holder)
    })
}

/// Whether refinement holder `holder` supplies `name` -- its compiled rows, or
/// the ones a runtime `Refinement#import_methods` copied into the overlay.
fn holder_defines(holder: ClassId, name: Symbol) -> bool {
    value_method(holder, 0, name).is_some()
        || (crate::runtime_meta::is_live()
            && crate::runtime_meta::overlay_value_body(holder, name).is_some())
}

/// Run refinement holder `holder`'s `name` against `recv`, from whichever of
/// the two tables carries it.
fn call_refined(
    holder: ClassId,
    recv: &RubyValue,
    name: Symbol,
    args: &[RubyValue],
    block: Option<RubyValue>,
) -> Option<Result<RubyValue, Signal>> {
    if let Some(f) = value_method(holder, 0, name) {
        return Some(f(recv, args, block));
    }
    let body = crate::runtime_meta::overlay_value_body(holder, name)?;
    Some(crate::runtime_meta::call_value_body(
        holder, name, &body, recv, args, block,
    ))
}

/// A call site the active refinements may answer. The refined body wins
/// outright when the receiver is of the refined class; otherwise this is an
/// ordinary send, which is what keeps an unrefined receiver -- and a name
/// no refinement defines for THIS receiver -- on its normal path.
pub fn refined_send_in(
    box_id: u32,
    recv: &RubyValue,
    name: Symbol,
    args: &[RubyValue],
    block: Option<RubyValue>,
    candidates: &[(ClassId, ClassId, bool)],
    explicit: bool,
) -> Result<RubyValue, Signal> {
    if let Some(holder) = refinement_home(recv, name, candidates) {
        // A refined method is an ordinary method for visibility: `private def`
        // inside a `refine` block (or a private row `import_methods` copied in)
        // refuses an explicit receiver.
        if explicit && instance_method_visibility(holder, name) == Some(MethodVisibility::Private) {
            return Err(raise_method_missing(
                recv,
                &name.to_string(),
                args,
                MissingReason::Private,
            ));
        }
        if let Some(r) = call_refined(holder, recv, name, args, block.clone()) {
            return r;
        }
    }
    send_value_in(box_id, recv, name, args, block)
}

/// `recv.send(name, ...)` / `recv.public_send(...)` at a site some `using`
/// covers. `name` is a runtime value here, so the whole active set rides
/// along and the match happens at the call.
pub fn refined_send_dynamic(
    box_id: u32,
    recv: &RubyValue,
    name: Symbol,
    args: &[RubyValue],
    block: Option<RubyValue>,
    candidates: &[(ClassId, ClassId, bool)],
    public: bool,
) -> Result<RubyValue, Signal> {
    if let Some(r) = refinement_home(recv, name, candidates)
        .and_then(|h| call_refined(h, recv, name, args, block.clone()))
    {
        return r;
    }
    if public {
        send_value_public_in(box_id, recv, name, args, block)
    } else {
        send_value_in(box_id, recv, name, args, block)
    }
}

/// `recv.respond_to?(name)` at a site some `using` covers -- a refined name
/// answers `true` even though it appears in no `instance_methods` list.
pub fn refined_responds_to(
    recv: &RubyValue,
    name: Symbol,
    include_all: bool,
    candidates: &[(ClassId, ClassId, bool)],
) -> Result<bool, Signal> {
    if refinement_home(recv, name, candidates).is_some() {
        return Ok(true);
    }
    responds_to_or_missing(recv, name, include_all)
}

/// `recv.method(name)` at a site some `using` covers. A refined name binds
/// to the HOLDER, which is what makes `#owner` answer a `Refinement`.
pub fn refined_method(
    recv: &RubyValue,
    name: Symbol,
    candidates: &[(ClassId, ClassId, bool)],
) -> Result<RubyValue, Signal> {
    match refinement_home(recv, name, candidates) {
        Some(holder) => Ok(crate::builtins::method::method_value(
            recv.clone(),
            name,
            holder,
            crate::MethodKind::Instance,
        )),
        None => crate::builtins::method::method_new(recv, &RubyValue::Symbol(name)),
    }
}

/// A bareword VCALL (`foo` -- implicit self, no args, no parens, could have
/// been a local): a miss raises `NameError`, not `NoMethodError`, per Ruby.
/// Everything else (method_missing, alias re-dispatch) is identical to a
/// normal send; only the terminal "nothing matched" raise differs.
pub fn send_value_vcall_in(
    box_id: u32,
    recv: &RubyValue,
    name: Symbol,
) -> Result<RubyValue, Signal> {
    send_value_in_reason(box_id, recv, name, &[], None, MissingReason::VCall)
}

fn send_value_in_reason(
    box_id: u32,
    recv: &RubyValue,
    name: Symbol,
    args: &[RubyValue],
    block: Option<RubyValue>,
    reason: MissingReason,
) -> Result<RubyValue, Signal> {
    // Recursion that never re-enters a compiled prologue (method_missing
    // self-forwarding, builtin-row cycles) still deepens the native stack --
    // check here as the prologues do.
    crate::stack_guard::stack_check()?;
    // The husk probe: EVERY send to a moved object -- `equal?`, `!`,
    // `__id__`, `class`, all of them -- raises `Ractor::MovedError`. A
    // container husk's class word cannot say so (Str/Array/Hash have none),
    // hence the flags probe; an object husk would resolve through its
    // retagged id anyway, this just makes the raise uniform.
    if crate::runtime_meta::any_moved() && value_moved(recv) {
        return Err(crate::ractor::moved_object_error());
    }
    if let RubyValue::Object(o) = recv {
        return send_in_reason(box_id, o, name, args, block, reason);
    }
    // A singleton method installed directly on this VALUE (`def SOME_ARRAY.[]`)
    // is closer than anything its class offers, so it is probed first -- and,
    // like every other overlay probe, only once something was defined at
    // runtime, so the ordinary path is untouched.
    if crate::runtime_meta::is_live()
        && let Some(m) = crate::runtime_meta::value_singleton_method(recv, name)
    {
        return m.call_with_self_and_block(recv, args, block);
    }
    note_dispatch(name);
    // The flat one-probe path below -- almost every send in almost every
    // program -- resolves on the `Symbol` alone, so the text is fetched only
    // where a by-NAME builtin table is actually consulted, never up front.
    // (`name_str` used to take the interner's global mutex, which made this
    // load-bearing; it is now two slab indexes, so the ordering is kept for
    // tidiness rather than for the lock.)
    // CLASS/MODULE-level methods (`File.read`, `Time.now`, `Math.sqrt`):
    // this runtime has no singleton-method tables, so a class value gets its
    // own table probed ahead of the walk. The walk itself describes INSTANCE
    // methods, and a `RubyValue::Class`'s own chain runs over Class/Module --
    // it would never reach File's or Math's rows.
    if let RubyValue::Class(cid) = recv {
        // Retired by an `undef` inside `class << self` -- checked before any
        // table, so an ancestor's still-live `def self.x` cannot answer past
        // it. See `OverlayEntry::class_undefs`.
        if crate::runtime_meta::is_live() && crate::runtime_meta::class_method_undefined(*cid, name)
        {
            return Err(raise_method_missing(recv, &name.to_string(), args, reason));
        }
        // A class/singleton method DEFINED AT RUNTIME
        // (`define_singleton_method` on a class, a runtime `def self.x`) wins
        // over both the frozen `def self.x` and the builtin `Class#new`/`#name`,
        // matching Ruby's "closest singleton" placement. Runs under the class
        // value itself. Only probed once something is defined at runtime.
        if crate::runtime_meta::is_live()
            && let Some(p) = crate::runtime_meta::overlay_class_method(*cid, name)
        {
            // The caller's block must ride along: `def M.wrap; yield; end`
            // desugars to a method-body lambda whose `yield` reads the
            // block the METHOD was called with. Dropping it here made
            // `M.wrap { "hi" }` raise LocalJumpError.
            return p.call_with_self_and_block(recv, args, block);
        }
        // A USER `def self.x` and the builtin Class/Module table, flattened
        // into one probe (user rows win -- real Ruby's placement rule: the
        // singleton method is strictly closer than one inherited from
        // Class/Module). A class with NO registry entry (a never-required
        // feature-gated ext) still gets the direct builtin probe below.
        if let Some((f, label)) = REGISTRY.get().and_then(|r| r.flat_class_hit(*cid, name)) {
            return with_c_frame(label, || f(recv, args, block));
        }
        // A module the class EXTENDED, whose row is its own INSTANCE method:
        // CRuby seats the module in the singleton ancestry, just past the
        // class's own rows, and the row takes a `&RubyValue` receiver -- so
        // the class value passes straight through as `self`.
        if let Some((f, owner)) = extended_class_method_fn(*cid, name) {
            return with_c_frame(c_frame_label(owner, name, '#'), || f(recv, args, block));
        }
        // A MINTED struct/data class's OWN singleton methods (`Point.members`,
        // `Point[1, 2]`, and `Point.new` itself). CRuby defines these directly
        // on the new class's singleton -- `Struct.new(:a).method(:new).owner`
        // is `#<Class:#<Class:0x...>>`, not `#<Class:Struct>` -- precisely so
        // they shadow `Struct.new`'s member-list constructor.
        //
        // They must therefore be probed BEFORE the ancestor walk below. A
        // minted class has no registry entry, so that walk takes it, reaches
        // `Struct`, and answers `k.new(1, 2, 3)` with `Struct.new` -- "1 is not
        // a symbol nor a string". They are also not reached by the MRO walk
        // further down, which runs over the class VALUE's own ancestry
        // (Class/Module), not the struct's.
        if crate::builtins::rstruct::is_struct_class(*cid)
            && let Some(f) = crate::builtins::rstruct::class_lookup(name.name_str())
        {
            return f(recv, args, block);
        }
        // A class born at RUNTIME (`Class.new(Base)`, `class Sub < expr`) was
        // never seen by `mro::materialize_class_methods`, so nothing flattened
        // its ancestors' `def self.x` onto it -- and the probe above is FLAT,
        // with no walk of its own. Without this, `Class.new(Base).made` is a
        // NoMethodError however ordinary `made` is, and `class << self; undef
        // inherited; end` cannot even find a target to undefine.
        //
        // The instance side has had this insurance all along (`lookup_mro`);
        // this is its class-method twin. Gated on the overlay being live and on
        // the receiver having no frozen entry, so a compile-time class -- whose
        // rows ARE flattened -- pays nothing: the walk would only rediscover
        // what the flat probe just answered.
        //
        // Placed before the builtin `Class`/`Module` table below because that
        // is ruby's order: an ancestor's singleton sits nearer than `Class`.
        //
        // One known divergence stays: the ancestor's compiled body carries the
        // ANCESTOR's class id, so a class-level `@x` read through an inherited
        // class method reaches the ancestor's storage where ruby gives the
        // receiver its own. Materialization avoids that by emitting a copy per
        // subclass, which a runtime class has no compile-time site for.
        //
        // ...and never for a name the receiver's OWN constructor serves.
        // `new`/`allocate` are `Class`'s methods parameterized by the receiver,
        // not an ancestor's singleton method, but a builtin root publishes its
        // own `new` row -- so the walk read `Class.new(String).new("hi")` as
        // `String.new` and handed back a plain String, which then reported
        // `String` for `.class` and failed `is_a?(Tagged)`. `runtime_class_new`
        // had already chosen the right constructor for the minted class; this
        // just stops the walk from answering ahead of it.
        if crate::runtime_meta::is_live()
            && REGISTRY
                .get()
                .is_some_and(|r| !r.entries.contains_key(&cid.0))
            && !(matches!(name.name_str(), "new" | "allocate") && constructor_of(*cid).is_some())
        {
            // The first REGISTERED class ancestor's flattened row first, not
            // the owner's own: materialization re-resolves a class method's
            // self-sends per class, so the nearest ancestor's copy is the one
            // whose overrides the receiver inherits. Asking the OWNER's row
            // (as reflection rightly does) ran `Class.new(Spec).run_suite`
            // with `Runnable`'s viewpoint, whose `runnable_methods` raises
            // "subclass responsibility" -- `Test`'s override never dispatched.
            let flattened = ancestors_of_value(*cid).iter().skip(1).find_map(|&anc| {
                let e = registry().entries.get(&anc.0)?;
                match e.is_module {
                    true => None,
                    false => e.class_methods.get(&name).copied().map(|f| (anc, f)),
                }
            });
            if let Some((anc, f)) = flattened {
                return with_c_frame(c_frame_label(anc, name, '.'), || f(recv, args, block));
            }
            if let Some(f) = class_method_fn(*cid, name) {
                return with_c_frame(c_frame_label(*cid, name, '.'), || f(recv, args, block));
            }
        }
        if let Some(lookup) = crate::builtins::class_method_table(*cid)
            && let Some(f) = lookup(name.name_str())
        {
            return with_c_frame(c_frame_label(*cid, name, '.'), || f(recv, args, block));
        }
        // The same table on a VALUE SUBCLASS's payload ROOT -- `DOSTime.local`,
        // `IOBuffer.open`. Nothing copies a builtin's class-method rows onto a
        // subclass entry the way materialization copies a user `def self.x`, so
        // this probe is the only place they can be found. It has to sit HERE
        // rather than in the miss tail: `B.open` must reach `StringIO.open`
        // before the MRO walk below finds `Kernel#open`, which is exactly
        // ruby's order (`#<Class:B>` is nearer than `Kernel`). The result comes
        // back re-tagged as the subclass, because CRuby allocates through the
        // receiver class. See `value_subclass::root_class_method_target`.
        {
            let n = name.name_str();
            if let Some(root) = crate::builtins::value_subclass::root_class_method_target(*cid, n) {
                return crate::builtins::value_subclass::call_root_class_method(
                    *cid, root, n, args, block,
                );
            }
            // ...and the RECEIVER-HONOURING roots, where the row allocates
            // through the receiver itself (`Date`'s do). The receiver passes
            // through unchanged and the result needs no re-tagging -- the row
            // already did it. See `value_subclass::recv_honouring_root`.
            if let Some(root) = crate::builtins::value_subclass::recv_honouring_root(*cid)
                && let Some(lookup) = crate::builtins::class_method_table(root)
                && let Some(f) = lookup(n)
                && !crate::builtins::builtin_class_method_is_private(root, n)
            {
                return with_c_frame(c_frame_label(root, name, '.'), || f(recv, args, block));
            }
        }
        // An ANCESTOR's runtime class method -- what a `Base.extend Store` or a
        // `define_singleton_method` on a superclass installs. A subclass's
        // singleton class inherits its parent's in ruby, so `Sub.tag` answers;
        // zeo probed the receiver's own overlay alone and stopped. Last, so
        // nothing that already resolves changes order: a frozen `def self.x`
        // nearer the receiver still wins, which is ruby's placement rule too.
        if crate::runtime_meta::is_live() {
            let inherited = ancestors_of_value(*cid)
                .iter()
                .skip(1)
                .find_map(|&anc| crate::runtime_meta::overlay_class_method(anc, name));
            if let Some(p) = inherited {
                return p.call_with_self_and_block(recv, args, block);
            }
        }
    }
    // THE MRO WALK -- the receiver's real ancestor chain, most
    // derived first. Per ancestor: user reopens (the value
    // methods) beat that ancestor's builtin table -- real Ruby's placement
    // rule (a `class Numeric; def foo` reopen is found on `5`, but a
    // builtin `Integer#foo` row would beat it). Everything -- including
    // the Kernel universals, BasicObject's `==`, and the
    // `Enumerable`/`Comparable` module tables (whose rows drive the
    // receiver's own `each`/`<=>`) -- is an ordinary `class_table` hit.
    //
    // Box 0 with a dormant overlay -- almost every send in almost every
    // program -- takes the flattened one-probe form of the same walk
    // (`flat_value_hit`); a per-box patch or live overlay keeps the full
    // walk, whose per-ancestor `(box, name)` probe it needs.
    let cid = recv.class_id();
    if box_id == 0 && !crate::runtime_meta::is_live() {
        if let Some(hit) = REGISTRY.get().and_then(|r| r.flat_value_hit(cid, name)) {
            if let Some(hit) = hit {
                return with_c_frame(hit.frame_label, || (hit.f)(recv, args, block));
            }
            // A genuine flat miss: fall through to the alias tail below.
        } else {
            let n = name.name_str();
            for &anc in ancestors_of_value(cid) {
                if let Some(f) = value_method(anc, box_id, name) {
                    return f(recv, args, block);
                }
                if let Some(table) = crate::builtins::class_table(anc)
                    && let Some(f) = table(n)
                {
                    return with_c_frame(c_frame_label(anc, name, '#'), || f(recv, args, block));
                }
            }
        }
    } else {
        // `Math`'s module functions reach here too when `Math` is mixed in
        // (`include Math` -> a private `sqrt(x)`), as an ordinary `class_table`
        // hit on its registered instance table -- no special arm needed.
        let live = crate::runtime_meta::is_live();
        let n = name.name_str();
        for &anc in ancestors_of_value(cid) {
            // An `undef` at this position TERMINATES the walk, before any
            // table -- including this ancestor's NATIVE one. A builtin's
            // `class_table` is a static list, so the compile-time registry
            // entry and the runtime overlay tombstone are the ONLY records
            // that a native row was retired. `respond_to?`/`method_defined?`
            // already read both, so without this the two disagreed: the
            // predicate said no and the call still answered.
            if (live && crate::runtime_meta::overlay_is_undefined(anc, name))
                || REGISTRY.get().is_some_and(|r| r.is_undefined(anc, name))
            {
                break;
            }
            // A runtime `define_method` REPLACES, so within one ancestor the
            // overlay outranks both the reopen and the builtin table -- the
            // placement `send_in_reason` gives an object receiver through
            // `resolve_dynamic`. PER ancestor, not ahead of the whole walk:
            // `Enumerable.define_method(:map)` must not beat `Array#map`.
            if live && let Some(p) = crate::runtime_meta::overlay_value_body(anc, name) {
                return crate::runtime_meta::call_value_body(anc, name, &p, recv, args, block);
            }
            if let Some(f) = value_method(anc, box_id, name) {
                return f(recv, args, block);
            }
            if let Some(table) = crate::builtins::class_table(anc)
                && let Some(f) = table(n)
            {
                return with_c_frame(c_frame_label(anc, name, '#'), || f(recv, args, block));
            }
        }
    }
    // A CLASS-method alias row (`class << self; alias [] new`): the same
    // rewrite for a class-object receiver, whose `class_id()` is `Class` and so
    // would never find the row on the class itself. First, because a class
    // receiver's own singleton table is what `[]` should mean here.
    if let RubyValue::Class(cid) = recv
        && let Some(old) = class_alias_target(*cid, name)
    {
        return send_value_in_reason(box_id, recv, old, args, block, reason);
    }
    // A builtin-alias row (`alias_method :dup!, :dup`): rewrite the name and
    // re-dispatch. Probed only after every real method missed -- a real
    // definition of the alias name always wins -- and rows are terminal, so
    // the re-entry can't loop. See `alias_target`.
    if let Some(old) = alias_target(recv.class_id(), name) {
        return send_value_in_reason(box_id, recv, old, args, block, reason);
    }
    // A CLASS-level `method_missing` (`def self.method_missing`, or one in
    // `class << self`) catches a missing CLASS method, exactly as an
    // instance's hook catches an instance miss (`method_missing_or_raise`)
    // -- the whole public API of Faker-style gems. Guarded on the hook
    // actually being user-defined so the plain miss below stays one raise,
    // and on the missing name not being `method_missing` itself.
    if let RubyValue::Class(cid) = recv {
        let mm = crate::symbol::wk::method_missing();
        if name != mm && class_defines_user_hook(*cid, mm) {
            let mut full_args = Vec::with_capacity(args.len() + 1);
            full_args.push(RubyValue::Symbol(name));
            full_args.extend_from_slice(args);
            return send_class_walking(*cid, 0, mm, &full_args, block);
        }
    }
    // Every receiver shape -- class, module, immediate, object -- gets its
    // message from the one method-missing raiser, so the class/module form
    // ("for class Widget") and the instance form stay in step.
    Err(raise_method_missing(recv, &name.to_string(), args, reason))
}

/// Whether any ancestor supplies a USER-DEFINED class-level `name` -- a
/// runtime overlay row (defs, singleton prepends) or a registered flattened
/// class-method row. Builtin class-method tables are deliberately not
/// consulted: this probes user HOOKS (`method_missing`,
/// `respond_to_missing?`), which no builtin defines as a class method.
/// Module ancestors past the receiver itself contribute nothing to a
/// singleton chain and are skipped, as `send_class_walking` skips them.
fn class_defines_user_hook(recv_class: ClassId, name: Symbol) -> bool {
    for &anc in ancestors_of_value(recv_class) {
        let entry = registry().entries.get(&anc.0);
        if anc != recv_class && entry.is_some_and(|e| e.is_module) {
            continue;
        }
        if crate::runtime_meta::is_live()
            && crate::runtime_meta::overlay_class_method(anc, name).is_some()
        {
            return true;
        }
        if entry.is_some_and(|e| e.class_methods.contains_key(&name)) {
            return true;
        }
    }
    false
}

pub fn send(
    recv: &RObj,
    name: Symbol,
    args: &[RubyValue],
    block: Option<RubyValue>,
) -> Result<RubyValue, Signal> {
    send_in(0, recv, name, args, block)
}

/// `send` with the caller's box -- see `send_value_in`'s docs.
pub fn send_in(
    box_id: u32,
    recv: &RObj,
    name: Symbol,
    args: &[RubyValue],
    block: Option<RubyValue>,
) -> Result<RubyValue, Signal> {
    send_in_reason(box_id, recv, name, args, block, MissingReason::NoEntry)
}

fn send_in_reason(
    box_id: u32,
    recv: &RObj,
    name: Symbol,
    args: &[RubyValue],
    block: Option<RubyValue>,
    reason: MissingReason,
) -> Result<RubyValue, Signal> {
    let id = recv.class_id();
    // A retagged husk short-circuits: every `Ractor::MovedObject` row raises
    // this same error, so the direct raise is behaviorally identical and
    // covers arbitrary names without the method_missing detour. A plain
    // compare on the id already in hand -- free.
    if id == zeo_abi::RACTOR_MOVED_OBJECT_CLASS {
        return Err(crate::ractor::moved_object_error());
    }
    note_dispatch(name);
    // A definition hook sees the class only as far as it has been built, and
    // that governs DISPATCH as well as reflection: a method written below the
    // `def` the hook is reporting is not installed yet. Resolution therefore
    // resumes ABOVE this class, exactly as `super` does -- an inherited copy
    // still answers (`Base#shared` while `Sub#shared` is still ahead), and
    // nothing above is an ordinary miss. Outside a hook body -- every program
    // that defines none -- this is one relaxed atomic load.
    if crate::runtime_meta::pending_here(id, name) {
        return match method_owner_after(id, id, name) {
            Some(_) => send_super_from(&RubyValue::Object(recv.clone()), id, name, args, block),
            None => method_missing_or_raise(recv, id, name, args, block, reason),
        };
    }
    // Runtime metaprogramming: a per-object singleton, a runtime
    // `define_method` override, or a runtime-class instance's own/inherited
    // methods -- probed first (Ruby: a runtime `define_method` REPLACES), but
    // only once anything has been defined at runtime (`is_live`), so the frozen
    // lock-free fast path below is untouched for all existing code.
    if crate::runtime_meta::is_live()
        && let Some(m) = crate::runtime_meta::resolve_dynamic(recv, id, name)
    {
        return m.call(recv, args, block);
    }
    // A name THIS object retired through its own singleton class. The class
    // still defines it, so every walk below would answer -- the tombstone is
    // what stops them, and `method_missing` gets its turn exactly as it does
    // for a name nothing ever defined.
    if crate::runtime_meta::is_live() {
        let boxed = RubyValue::Object(recv.clone());
        if crate::runtime_meta::object_method_undefined(&boxed, name) {
            return method_missing_or_raise(recv, id, name, args, block, MissingReason::NoEntry);
        }
    }
    // ENV's methods are probed by IDENTITY, not by class: `ENV.class` is
    // `Object` (real Ruby -- it is a lone singleton with Hash-shaped methods,
    // not a Hash). Its OWN explicitly-defined methods must be checked BEFORE
    // the registry, because several (`dup`/`clone`/`freeze`) OVERRIDE Kernel
    // universals that ENV's `Object` identity would otherwise match first --
    // `ENV.dup` must raise, not shallow-copy. The Hash-snapshot fallback for
    // ENV's read-only Enumerable surface stays AFTER the registry walk, so ENV
    // still inherits `object_id`/`equal?`/etc. from Object.
    //
    // A pointer compare, and the boxed handle is built only past the
    // `lookup_mro` hit below -- the ~100%-hit path pays neither an Arc bump
    // nor a downcast.
    let is_env = crate::builtins::env::is_env_obj(recv);
    if is_env && let Some(f) = crate::builtins::env::lookup(name.name_str()) {
        return f(&RubyValue::Object(recv.clone()), args, block);
    }
    if let Some(f) = registry().lookup_mro(id, name) {
        return f.call(recv, args, block);
    }
    let boxed = RubyValue::Object(recv.clone());

    // ENV's singleton class INCLUDES Enumerable (oracle: its ancestors are
    // `[#<Class:ENV>, Enumerable, Object, Kernel, BasicObject]`), and a fresh
    // Hash snapshot answers every one of those rows faithfully without a
    // per-method stub. Mutators are in `env::lookup` above -- they must write
    // the real environment.
    //
    // Only ENUMERABLE's names, though: a universal like `equal?`/`object_id`
    // has to resolve on ENV itself, or it compares two different snapshots
    // and `ENV.equal?(ENV)` answers false.
    if is_env
        && crate::builtins::class_table(zeo_abi::ENUMERABLE_CLASS)
            .is_some_and(|lookup| lookup(name.name_str()).is_some())
    {
        let snapshot = crate::builtins::env::snapshot();
        return send_value(&snapshot, name, args, block);
    }

    // The SAME MRO walk `send_value` runs, over a boxed
    // handle: Kernel's universals, BasicObject's `==`, and the
    // Enumerable/Comparable module tables all resolve as real ancestor
    // methods, so `method_missing` fires only AFTER them -- real Ruby finds
    // a real (module) method first, always.
    //
    // The method's TEXT is fetched only where a by-name builtin table or the
    // value-subclass rewrap needs it: `name_str` takes the interner's global
    // mutex, and the flat one-probe hit below resolves on the `Symbol` alone.
    // Value-subclass payload bridge (D3): `class Stack < Array` carries a
    // `RubyValue::Array` payload; at its payload root the inherited builtin
    // method runs against that value, not the boxed object. `None` for every
    // ordinary object, so this costs one field read on the miss path.
    let payload = recv.builtin_payload();
    let payload_root = recv.builtin_root();
    // Same flat-vs-walk split as `send_value_in_reason`: box 0 with a
    // dormant overlay takes the one-probe flattened walk; anything else
    // keeps the per-ancestor probes it needs.
    let flat = if box_id == 0 && !crate::runtime_meta::is_live() {
        REGISTRY.get().and_then(|r| r.flat_value_hit(id, name))
    } else {
        None
    };
    match flat {
        Some(Some(hit)) => {
            // At the payload root, a BUILTIN hit runs against the wrapped
            // value and re-wraps a self-return (`push`/`<<`) back to the
            // subclass; reopen rows always run against the boxed receiver.
            if hit.builtin
                && payload_root
                    .is_some_and(|r| crate::builtins::value_subclass::payload_owns(r, hit.owner))
                && let Some(ref p) = payload
            {
                let result = with_c_frame(hit.frame_label, || (hit.f)(p, args, block))?;
                return Ok(crate::builtins::value_subclass::rewrap_self_return(
                    result,
                    p,
                    recv,
                    name.name_str(),
                ));
            }
            return with_c_frame(hit.frame_label, || (hit.f)(&boxed, args, block));
        }
        // A genuine flat miss: straight to the alias tail below.
        Some(None) => {}
        None => {
            let n = name.name_str();
            let live = crate::runtime_meta::is_live();
            for &anc in ancestors_of_value(id) {
                // An `undef_method` at this position TERMINATES the walk,
                // before this ancestor's own NATIVE table -- the tombstone is
                // the only record that a builtin row was retired, since
                // `class_table` itself is a static list. See the twin in
                // `send_value_in_reason`.
                if (live && crate::runtime_meta::overlay_is_undefined(anc, name))
                    || REGISTRY.get().is_some_and(|r| r.is_undefined(anc, name))
                {
                    break;
                }
                if let Some(f) = value_method(anc, box_id, name) {
                    // The same payload bridge the `class_table` arm below
                    // runs: an ext builtin's rows register as VALUE methods
                    // (zlib, strscan), and handing one the boxed subclass
                    // instead of its payload panicked the row's receiver
                    // downcast (`TaggedInflate#inflate` died in `zs_of`).
                    if payload_root
                        .is_some_and(|r| crate::builtins::value_subclass::payload_owns(r, anc))
                        && let Some(ref p) = payload
                    {
                        let result = f(p, args, block)?;
                        return Ok(crate::builtins::value_subclass::rewrap_self_return(
                            result, p, recv, n,
                        ));
                    }
                    return f(&boxed, args, block);
                }
                // `include Math` reaches its module functions here as an
                // ordinary `class_table` hit on Math's registered instance
                // table.
                if let Some(table) = crate::builtins::class_table(anc)
                    && let Some(f) = table(n)
                {
                    let label = c_frame_label(anc, name, '#');
                    // At the payload root, run against the wrapped value
                    // and re-wrap a self-return (`push`/`<<`) back to the
                    // subclass.
                    if payload_root
                        .is_some_and(|r| crate::builtins::value_subclass::payload_owns(r, anc))
                        && let Some(ref p) = payload
                    {
                        let result = with_c_frame(label, || f(p, args, block))?;
                        return Ok(crate::builtins::value_subclass::rewrap_self_return(
                            result, p, recv, n,
                        ));
                    }
                    return with_c_frame(label, || f(&boxed, args, block));
                }
            }
        }
    }

    // A builtin-alias row (`alias_method :raise!, :raise`): rewrite the name
    // and re-dispatch -- after every real method (a real definition of the
    // alias name wins) and BEFORE `method_missing` (an alias is a real
    // method in Ruby). Rows are terminal, so the re-entry can't loop.
    if let Some(old) = alias_target(id, name) {
        return send_in_reason(box_id, recv, old, args, block, reason);
    }
    method_missing_or_raise(recv, id, name, args, block, reason)
}

/// The tail every unresolved send shares: `method_missing` if the receiver has
/// one, else CRuby's raise. Also where a send truncated by the definition
/// watermark lands, so a class with its own `method_missing` still gets it.
fn method_missing_or_raise(
    recv: &RObj,
    id: ClassId,
    name: Symbol,
    args: &[RubyValue],
    block: Option<RubyValue>,
    reason: MissingReason,
) -> Result<RubyValue, Signal> {
    // method_missing fallback, with `name` prepended to args (mirrors
    // CRuby's own protocol) -- AFTER every real method, per real Ruby.
    let mm = crate::symbol::wk::method_missing();
    let mm_impl = crate::runtime_meta::is_live()
        .then(|| crate::runtime_meta::resolve_dynamic(recv, id, mm))
        .flatten()
        .or_else(|| registry().lookup(id, mm).cloned());
    if let Some(f) = mm_impl {
        let mut full_args = Vec::with_capacity(args.len() + 1);
        full_args.push(RubyValue::Symbol(name));
        full_args.extend_from_slice(args);
        return f.call(recv, &full_args, block);
    }

    // A real, catchable `NoMethodError` (replacing the original
    // eprintln-and-`process::exit(1)` shortcut): propagates like any other
    // raised exception -- rescuable at the call site, re-raised at a
    // Thread's `join`/`value` if uncaught there, and printed by the
    // top-level uncaught handler otherwise. Shares the one method-missing
    // raiser with every other failure mode.
    Err(raise_method_missing(
        &RubyValue::Object(recv.clone()),
        &name.to_string(),
        args,
        reason,
    ))
}

